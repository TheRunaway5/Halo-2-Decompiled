#!/usr/bin/env python3
"""Export bounded original-backed netgame flag corrections for owned MCC maps.

Both readers authenticate the real cache formats. The target includes the
original TU1.5 load-time postprocessor, rather than raw Xbox serialization.
Only position/facing words of matching type7/8 rows qualify. Complete flag
banks guard each runtime profile. Original assets stay offline references.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
from audit_rendering import Cache, file_sha
from mcc_content import MccCache, directory


def flags(cache):
    tag=next(t for t in cache.tags.values() if t['group']=='scnr' and t['address'])
    root=cache.pointer(tag['address'],cache.magic,0x120)
    return tag,b''.join(bytes(cache.data[at:at+32]) for at in cache.block(root+0x118,32))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mcc-root',type=Path,required=True)
    parser.add_argument('--original-root',type=Path,action='append',required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--fixture',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();scratch=Path(os.environ['HALO2_TEST_SCRATCH'])
    authority=Path(__file__).resolve().parents[1]/'analysis/multiplayer/title-update-1.5/netgame-postprocess/measured/report.json'
    authority_hash=file_sha(authority)
    assert authority_hash=='d3a369d8e75267d1505e282f82836dbb4c3ceb48b4dc6fc3cc2314f9e05ff40c'
    measured=json.loads(authority.read_text())
    references=[p for root in args.original_root for p in root.rglob('*.map') if p.is_file()]
    contexts=[];profiles=[]
    for path in sorted((directory(args.mcc_root)/'h2_maps_win64_dx11').glob('*.map')):
        donor=MccCache(path)
        scenarios=[t for t in donor.tags.values() if t['group']=='scnr' and t['address']]
        if len(scenarios)!=1:continue
        tag,raw=flags(donor)
        selected=[i for i in range(len(raw)//32) if struct.unpack_from('<h',raw,i*32+16)[0] in (7,8)]
        if not selected:continue
        reference=next((p for p in references if p.name==path.name),None)
        if reference is None:raise ValueError('No owned original map: '+path.name)
        original=Cache(reference);original_tag,expected=flags(original)
        assert original_tag['name']==tag['name'] and len(expected)==len(raw)
        root=original.pointer(original_tag['address'],original.magic,0x3a0)
        level=original.pointer(original.u32(root+0x39c),original.magic,0x18)
        multiplayer=original.pointer(original.u32(level+0x14),original.magic,4)
        map_id=original.u32(multiplayer)
        if map_id in (100,1200):
            execution=next(r for r in measured['cases'] if r['image_label']=='owned_1_5' and r['source_map_id']==map_id)
            assert execution['xbe_sha256']=='21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd'
            assert execution['cache_sha256']==file_sha(reference) and bytes.fromhex(execution['raw_netgame_hex'])==expected
            expected=bytes.fromhex(execution['processed_netgame_hex'])
        after=bytearray(raw);patches=[]
        for index in selected:
            offset=index*32
            assert raw[offset+16:offset+32]==expected[offset+16:offset+32]
            for field in range(4):
                at=offset+field*4;before=struct.unpack_from('<I',raw,at)[0];target=struct.unpack_from('<I',expected,at)[0]
                if before!=target:
                    patches.append(dict(offset=at,before=before,after=target))
                    struct.pack_into('<I',after,at,target)
        row=dict(map=path.name,map_id=map_id,path=tag['name'],count=len(raw)//32,patches=patches,
            donor_sha256=hashlib.sha256(raw).hexdigest(),target_sha256=hashlib.sha256(after).hexdigest(),
            original_map=str(reference),original_map_sha256=file_sha(reference),mcc_map_sha256=file_sha(path),
            target_equals_original_loaded=after==expected)
        contexts.append(row)
        if patches:profiles.append(dict(row,donor_flags_hex=raw.hex(),target_flags_hex=after.hex()))
    assert len(contexts)==9 and len(profiles)==1 and sum(len(p['patches']) for p in profiles)==4
    lines=['// Generated by tools/generate_mcc_teleporter_profiles.py.',
           '// Four verified TU1.5-loaded position/facing words; full flag-bank tuple admission.']
    for n,row in enumerate(profiles):
        lines.append('constexpr std::array teleporter_patches_'+str(n)+'{'+','.join(
            'TeleporterPatch{'+','.join('0x'+format(p[k],'x')+'u' for k in ('offset','before','after'))+'}' for p in row['patches'])+'};')
    lines.append('constexpr std::array teleporter_profiles{')
    for n,row in enumerate(profiles):
        lines.append('    TeleporterProfile{'+json.dumps('tu15-'+Path(row['map']).stem+'-teleporters')+','+
            json.dumps(row['path'])+','+str(row['count'])+'u,hex("'+row['donor_sha256']+'"),hex("'+
            row['target_sha256']+'"),teleporter_patches_'+str(n)+'},')
    lines.append('};');temporary=scratch/'teleporter-profiles.inc';temporary.write_text('\n'.join(lines)+'\n')
    args.output.write_bytes(temporary.read_bytes());args.fixture.parent.mkdir(parents=True,exist_ok=True)
    args.fixture.write_text(json.dumps(dict(profiles=profiles),indent=2)+'\n')
    args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(dict(contexts=contexts,
        generator_sha256=file_sha(Path(__file__)),postprocess_authority_sha256=authority_hash,
        output_sha256=file_sha(args.output),fixture_sha256=file_sha(args.fixture),runtime_original_assets_required=False),indent=2)+'\n')
    print(json.dumps(dict(original_contexts=len(contexts),profiles=len(profiles),changed_words=4)))


if __name__=='__main__':main()
