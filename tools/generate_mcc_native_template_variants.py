#!/usr/bin/env python3
"""Emit the finite, audited native-template payload allowlist (no runtime IO)."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = tuple("shaders\\shader_templates\\opaque\\" + name for name in (
    "tex_bump", "tex_bump_active_camo", "tex_bump_dprs_env", "tex_bump_env",
    "tex_bump_env_no_detail", "tex_bump_illum_bloom"))
SHAPES = ((2, 50, 8, 32, 116), (2, 50, 8, 32, 116), (2, 50, 12, 40, 168),
          (3, 75, 15, 57, 238), (2, 50, 8, 32, 142), (2, 50, 12, 36, 126))
VARIANT_COUNTS = (35, 33, 39, 38, 36, 18)
MAP_COUNTS = (39, 37, 39, 39, 39, 18)


def generate(source: bytes) -> str:
    data = json.loads(source)
    if (data.get("schema") != "H2_MCC_NATIVE_TEMPLATE_VARIANTS_V1" or
            data.get("existing_stem_instances") != 211 or data.get("exact_raw_variants") != 199):
        raise ValueError("Unsupported native-template evidence profile")
    if tuple(p["template"] for p in data["profiles"]) != TEMPLATES:
        raise ValueError("Unreviewed native-template contract")
    lines = ["// Generated by tools/generate_mcc_native_template_variants.py; do not edit.",
             "// Evidence JSON SHA256: " + hashlib.sha256(source).hexdigest(),
             "constexpr std::array<std::string_view,6> native_template_names{{"]
    lines += ["    " + json.dumps(name) + "," for name in TEMPLATES]
    lines += ["}};", "constexpr std::array<NativeTemplateVariant,199> native_template_variants{{"]
    all_keys = set()
    for index, profile in enumerate(data["profiles"]):
        if tuple(profile["native_shape_lod_layer_pass_impl_remap"]) != SHAPES[index]:
            raise ValueError("Changed native bank contract")
        variants = profile["variants"]
        evidence = profile["map_evidence"]
        if len(variants) != VARIANT_COUNTS[index] or len(evidence) != MAP_COUNTS[index]:
            raise ValueError("Changed audited variant/map census")
        seen_maps, by_payload = set(), {}
        for variant in variants:
            payload, size, fingerprint = (variant[k] for k in ("payload", "bytes", "fnv64"))
            if (not re.fullmatch(r"[0-9a-f]{64}\.bin", payload) or
                    not re.fullmatch(r"[0-9a-f]{16}", fingerprint) or
                    not isinstance(size, int) or not 96 <= size <= 16 * 1024 * 1024):
                raise ValueError("Invalid exact native payload fingerprint/extent")
            key = index, payload
            if key in all_keys or not variant["maps"]:
                raise ValueError("Duplicate or unowned native payload")
            all_keys.add(key)
            for name in variant["maps"]:
                if name in seen_maps:
                    raise ValueError("Duplicate native map owner")
                seen_maps.add(name)
            by_payload[payload] = set(variant["maps"])
            lines.append(f'    {{native_template_names[{index}],"{payload}",{size},0x{fingerprint}ull}},')
        if len(seen_maps) != MAP_COUNTS[index]:
            raise ValueError("Native map ownership census changed")
        seen_evidence = set()
        for row in evidence:
            name = row["map"]
            if name in seen_evidence or name not in by_payload.get(row["payload"], set()):
                raise ValueError("Native payload lacks its exact map evidence")
            seen_evidence.add(name)
            for key in ("library_sha256", "original_source_sha256"):
                if not re.fullmatch(r"[0-9a-f]{64}", row[key]):
                    raise ValueError("Invalid native library/source evidence")
        if seen_evidence != seen_maps:
            raise ValueError("Incomplete native map evidence")
    lines += ["}};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--data", type=Path, default=ROOT / "tools/reference/mcc-native-template-variants.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src/rendering/mcc_native_template_variants.inc")
    args = parser.parse_args()
    rendered = generate(args.data.read_bytes())
    if args.check:
        if not args.output.is_file() or args.output.read_text() != rendered:
            parser.error("Generated native-template variant allowlist is out of date")
    else:
        args.output.write_text(rendered)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
