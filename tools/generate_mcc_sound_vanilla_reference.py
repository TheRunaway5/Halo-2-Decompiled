#!/usr/bin/env python3
"""Generate the finite payload-authenticated TU1.5 sound flag catalog.

The checked-in facts contain only functional metadata/hash identities. Runtime
loading never reads this JSON or an Xbox reference asset. --check is portable.
"""
import argparse
import json
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
FACTS=ROOT/'tools/mcc-sound-vanilla-flag-profiles.json'
OUTPUT=ROOT/'src/audio/mcc_sound_vanilla_reference_profiles.inc'

def digest(value):
    assert re.fullmatch('[0-9a-f]{64}',value), 'Invalid authenticated digest'
    return '{'+','.join('std::byte{0x'+value[n:n+2]+'}'for n in range(0,64,2))+'}'
def quoted(value):return json.dumps(value,ensure_ascii=True)
def bytes28(value):
    assert re.fullmatch('[0-9a-f]{56}',value), 'Sound preimage is not 28 bytes'
    return '{'+','.join('std::byte{0x'+value[n:n+2]+'}'for n in range(0,56,2))+'}'
def generate(data):
    assert data['schema']=='H2_MCC_TU15_FINITE_SOUND_FLAG_AUTHORING_V1'
    owners=data['owners'];assert len(owners)==9
    lines=['// Generated by tools/generate_mcc_sound_vanilla_reference.py; do not edit.',
           '// Finite complete-owner metadata + actual encoded-payload admission.',
           'static std::span<const mcc_sound_reference_detail::Owner> canonical_sound_flag_profiles(){',
           '    static const std::vector<mcc_sound_reference_detail::Owner> profiles{']
    owner_ids=set();sound_count=permutation_count=0;paths=set()
    for owner in owners:
        assert owner['owner']not in owner_ids;owner_ids.add(owner['owner'])
        assert re.fullmatch('[0-9a-f]{64}',owner['source_map_sha256'])
        assert re.fullmatch('[0-9a-f]{64}',owner['original_map_sha256'])
        lines.append('        mcc_sound_reference_detail::Owner{{'+str(owner['owner'])+'u},'+str(owner['root'])+'u,'+quoted(owner['path'])+','+digest(owner['metadata_sha256'])+',{')
        sounds=set()
        for sound in owner['sounds']:
            assert sound['handle']not in sounds;sounds.add(sound['handle']);paths.add(sound['path']);sound_count+=1
            before,after=sound['before'],sound['after'];raw=bytes.fromhex(sound['header_hex']);original=bytes.fromhex(sound['original_header_hex']);flags=int.from_bytes(raw[:2],'little')
            assert len(raw)==28 and len(original)==20
            assert before==(flags&0x3ff)|((flags&0xf000)>>2)
            assert after==int.from_bytes(original[:2],'little')
            assert before^after in(4,8,32)and not((before^after)&after)
            lines.append('            mcc_sound_reference_detail::Sound{{'+str(sound['handle'])+'u},'+str(sound['root'])+'u,'+quoted(sound['path'])+','+bytes28(sound['header_hex'])+','+str(before)+'u,'+str(after)+'u,{')
            identities=set()
            for p in sound['permutations']:
                key=(p['range'],p['permutation']);assert key not in identities;identities.add(key);permutation_count+=1
                assert p['range_name']and p['permutation_name']
                v=p['payload'];assert v['encoded_bytes']>0 and v['packets']and sum(z['bytes']for z in v['packets'])==v['encoded_bytes']
                assert v['codec']in range(6)and v['sample_rate']in(22050,44100,32000,48000)and v['channels']in(1,2,4)
                fields=[str(p[n])+'u'for n in('range','permutation','global_range','global_permutation','range_import','permutation_import','range_sid','permutation_sid')]
                fields +=[quoted(p['range_name']),quoted(p['permutation_name'])]
                packets='{'+','.join('{'+str(q['bytes'])+'u,'+str(q['pcm_bytes'])+'u,'+str(q['reset_after']).lower()+'}'for q in v['packets'])+'}'
                fields +=['MccSoundVanillaPayload{'+digest(v['sha256'])+','+','.join(str(v[n])+'u'for n in('encoded_bytes','codec','sample_rate','channels','samples','sound_class'))+','+packets+'}']
                lines.append('                mcc_sound_reference_detail::Permutation{'+','.join(fields)+'},')
            lines.append('            }},')
        lines.append('        }},')
    assert sound_count==66 and permutation_count==88 and len(paths)==29
    lines +=['    };','    return profiles;','}',
              '// Cache source authentication uses the genuine retained raw matg',
              '// allocation after checking its sound row against the active clone.',
              '// The original generic Source catalog above remains unchanged.',
              'static std::span<const mcc_sound_reference_detail::Owner> raw_globals_sound_flag_profiles(){',
              '    static const std::vector<mcc_sound_reference_detail::Owner> profiles=[] {',
              '        const auto original=canonical_sound_flag_profiles();',
              '        std::vector<mcc_sound_reference_detail::Owner> result(original.begin(),original.end());']
    for index,owner in enumerate(owners):
        lines.append('        result['+str(index)+'].metadata='+digest(owner['raw_globals_metadata_sha256'])+';')
    lines +=['        return result;','    }();','    return profiles;','}']
    return '\n'.join(lines)+'\n'
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();result=generate(json.loads(FACTS.read_text()))
    if args.check:
        if OUTPUT.read_text()!=result:raise SystemExit('Sound reference catalog is stale')
        print('Finite sound reference catalog current:9owners66sounds88payloads')
    else:OUTPUT.write_text(result)
if __name__=='__main__':main()
