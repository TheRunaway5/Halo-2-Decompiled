#!/usr/bin/env python3
"""Generate pointer relocation descriptors for the pinned PC animation layout."""
import hashlib
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/reference/assembly/src/Assembly/Plugins/Halo2/jmad.xml"
OUTPUT = ROOT / "src/mcc_animation_layout.inc"


def generate(source=SOURCE,node_type="PointerNode",field_type="PointerField",node_name="pointer_nodes",field_name="pointer_fields"):
    nodes, fields = [], []

    def visit(element):
        node = len(nodes)
        nodes.append(None)
        own = []
        for field in element:
            if field.tag not in ("tagblock", "dataref"):
                continue
            child = visit(field) if field.tag == "tagblock" else 0
            own.append((int(field.attrib["offset"], 0),
                        int(field.attrib.get("elementSize", "1"), 0), child,
                        field.tag == "dataref"))
        nodes[node] = (len(fields), len(own))
        fields.extend(own)
        return node

    visit(ET.parse(source).getroot())
    lines = ["// Generated by tools/generate_mcc_animation_layout.py; do not edit.",
             "// Assembly fd14ef3c46135e9422966c6a64cd926fb0bd23fb " + source.name,
             "// Source SHA-256: " + hashlib.sha256(source.read_bytes()).hexdigest(),
             f"constexpr std::array<{node_type},{len(nodes)}> {node_name}{{{{"]
    lines += [f"    {{{first},{count}}}," for first, count in nodes]
    lines += ["}};", f"constexpr std::array<{field_type},{len(fields)}> {field_name}{{{{"]
    lines += [f"    {{0x{offset:x},0x{stride:x},{child},{str(data).lower()}}},"
              for offset, stride, child, data in fields]
    lines += ["}};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.write_text(generate())
    source=ROOT/"analysis/multiplayer/pc-gameplay-tag-comparison-20261011/schemas/Halo2MCC/matg.xml"
    (ROOT/"src/mcc_globals_clone_layout.inc").write_text(generate(source,"CloneNode","CloneField","clone_nodes","clone_fields"))
