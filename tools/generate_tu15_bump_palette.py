#!/usr/bin/env python3
"""Generate the fixed native bump palette from MCC, with offline TU1.5 proof.

This is reference/build tooling. Onboarding, normal builds and bitmap loading
use the generated constant and do not open either executable.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from oracle_smg_firing_1_1 import Xbe
from research_mp_sandbox_update_functions import NEW_DEFAULT, NEW_PIN

PALETTE_SHA = 'd077fbea214db2ecde0fcd58967f777a7b7c63f9f5ed1796969b95511c3e38cc'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--mcc-engine', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--manifest', type=Path, required=True)
    args = parser.parse_args()
    assert hashlib.sha256(Path(NEW_DEFAULT).read_bytes()).hexdigest() == NEW_PIN
    reference = Xbe(NEW_DEFAULT).read(0x474DA8, 1024)
    assert hashlib.sha256(reference).hexdigest() == PALETTE_SHA
    engine = args.mcc_engine.read_bytes()
    offset = engine.find(reference)
    if offset < 0 or engine.find(reference, offset + 1) >= 0:
        raise ValueError('MCC does not contain the uniquely authenticated palette')
    palette = engine[offset:offset + 1024]
    words = struct.unpack('<256I', palette)
    lines = ['// Generated by tools/generate_tu15_bump_palette.py.',
        '// Fixed color data shared by MCC and Xbox TU1.5; no shader program.',
        '// Palette SHA-256: ' + PALETTE_SHA,
        '#include "halo2/texture.hpp"', 'namespace halo2 {', 'namespace {',
        'constexpr std::array<std::uint32_t,256> colors{']
    lines += ['    ' + ','.join(f'0x{word:08x}u' for word in words[i:i + 8]) + ','
        for i in range(0, 256, 8)]
    lines += ['};', 'constexpr auto palette=[] {', '    std::array<std::byte,1024> result{};',
        '    for(unsigned i=0;i<colors.size();++i)for(unsigned j=0;j<4;++j)',
        '        result[i*4+j]=std::byte(colors[i]>>(j*8));', '    return result;', '}();', '}',
        'std::span<const std::byte,1024> tu15_bump_palette() {return palette;}', '}', '']
    args.output.write_text('\n'.join(lines))
    fnv = 14695981039346656037
    for byte in palette:
        fnv = ((fnv ^ byte) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    args.manifest.parent.mkdir(parents=True, exist_ok=True)
    report = dict(schema='H2_NATIVE_FIXED_BUMP_PALETTE_V1',
        source_mcc_engine=str(args.mcc_engine.resolve()),
        source_mcc_engine_sha256=hashlib.sha256(engine).hexdigest(), source_file_offset=offset,
        palette_sha256=PALETTE_SHA, palette_bytes=len(palette), palette_fnv1a64=f'{fnv:016x}',
        reference_xbe_sha256=NEW_PIN, reference_address=0x474DA8,
        generated_cpp_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),
        runtime_executable_input=False, shader_program=False)
    args.manifest.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
