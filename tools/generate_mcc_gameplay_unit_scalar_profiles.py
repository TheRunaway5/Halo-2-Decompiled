#!/usr/bin/env python3
"""Compile reviewed normalized unit tuples; no maps or executables are read."""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = (root / "tools/mcc-gameplay-unit-scalar-profiles.json").read_bytes()
    manifest = json.loads(raw)
    if manifest["schema"] != "H2_MCC_TU15_UNIT_SCALAR_PROFILE_V1":
        raise ValueError("Unsupported reviewed unit scalar profile schema")
    profiles = manifest["profiles"]
    if len(profiles) != 29 or len({(p["group"], p["name"]) for p in profiles}) != 29:
        raise ValueError("Reviewed unit profile census changed")
    output = [
        "// Generated by tools/generate_mcc_gameplay_unit_scalar_profiles.py.",
        "// Reviewed manifest SHA256: " + hashlib.sha256(raw).hexdigest(),
        "constexpr std::array unit_profiles{",
    ]
    for profile in profiles:
        group = {"bipd": "biped", "vehi": "vehicle"}[profile["group"]]
        fields = profile["fields"]
        if not 1 <= len(fields) <= 4:
            raise ValueError("Unit tuple exceeds the verified field bound")
        compiled = []
        for field in fields:
            width = field["bytes"]
            donor = bytes.fromhex(field["donor_bits"])
            target = bytes.fromhex(field["target_bits"])
            if width not in (4, 12) or len(donor) != width or len(target) != width:
                raise ValueError("Unit scalar field width changed")
            descriptor = field["descriptor"]
            if descriptor != 0xFFFFFFFF and (
                (descriptor, field["stride"]) not in ((0x284, 0x80), (0x1C8, 0xB0))
                or field["count"] not in (1, 2, 3)
                or not 0 <= field["index"] < field["count"]
            ):
                raise ValueError("Unit scalar block guard changed")
            if descriptor != 0xFFFFFFFF and field["offset"] + width > field["stride"]:
                raise ValueError("Unit scalar field escapes its compiled record")
            def words(data):
                return "{" + ",".join("0x%08xu" % int.from_bytes(data[n:n + 4], "little")
                                       for n in range(0, len(data), 4)) + "}"
            compiled.append("Field{%du,%du,%du,%du,%du,%du,%s,%s}" % (
                descriptor, field["count"], field["index"], field["stride"],
                field["offset"], width // 4, words(donor), words(target)))
        compiled += ["{}"] * (4 - len(fields))
        output.append("    Profile{tag_groups::%s,%s,{{%s}},%d}," % (
            group, json.dumps(profile["name"]), ",".join(compiled), len(fields)))
    output.append("};")
    text = "\n".join(output) + "\n"
    target = root / "src/mcc_gameplay_unit_scalar_profiles.inc"
    if args.check:
        if target.read_text() != text:
            raise SystemExit("Compiled unit scalar profiles differ from their reviewed manifest")
    else:
        target.write_text(text)
    print("Verified 29 exact named normalized unit scalar tuples")


if __name__ == "__main__":
    main()
