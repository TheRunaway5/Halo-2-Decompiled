#!/usr/bin/env python3
"""Emit exact, source-paired MCC action-template compatibility entries."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / 'tests/fixtures/mcc_action_prompt_templates.json'
OUTPUT = ROOT / 'src/ui/hud/mcc_action_prompt_templates.inc'
# These complete action prefixes have same-role, same-name original witnesses
# below. Never translate E45A alone: it has a different original meaning.
ALIASES = {'\ue47c \ue45a': 'Hold \ue448', '\ue47c \ue45b': 'Hold \ue448',
           '\ue47c \ue46a': 'Hold \ue449', '\ue47d \ue46a': 'Hold \ue449',
           '\ue47c \ue468': 'Hold \ue448'}


def adapt(source):
    for before, after in ALIASES.items():
        source = source.replace(before, after)
    return source.replace('\r\n', '\n').replace('\n', '\r\n')


def generate():
    evidence = json.loads(REFERENCE.read_text())
    assert evidence['schema'] == 1 and evidence['matched_fields'] > 0
    assert evidence['maps'] and all(len(row['mcc_sha256']) == 64 and
                                    (row['original_sha256'] is None or len(row['original_sha256']) == 64)
                                    for row in evidence['maps'])
    pairs = {}
    for row in evidence['templates']:
        assert row['owners'], 'A template needs an authored field owner'
        assert pairs.setdefault(row['mcc'], row['original']) == row['original'], 'Ambiguous source template'
    for before, after in ALIASES.items():
        assert any(before in source and after in target and adapt(source) == target
                   for source, target in pairs.items()), f'Unwitnessed action prefix: {before!r}'
    # MCC-only weapon/seat names retain their literal wording and weapon icon.
    # Admit only complete, witnessed action prefixes in an actual field owner.
    unknown = [row for row in evidence['unpaired_fields'] if row['text'] not in pairs]
    for row in unknown:
        source = row['text']
        assert any(prefix in source for prefix in ALIASES), f'Unqualified action template: {row!r}'
        target = adapt(source)
        assert not any('\ue446' <= character <= '\ue47f' for character in target
                       if character not in '\ue448\ue449\ue44a\ue44c'), f'Unresolved action: {row!r}'
        assert pairs.setdefault(source, target) == target
    changed = sorted((source, target) for source, target in pairs.items() if source != target)
    lines = ['// Generated by tools/generate_action_prompt_templates.py; do not edit.',
             '// Exact English templates paired by authored name and field role.',
             f'static constexpr std::array<std::pair<std::string_view,std::string_view>,{len(changed)}> mcc_action_templates{{{{']
    for source, target in changed:
        lines.append('  {' + json.dumps(source) + ',' + json.dumps(target) + '},')
    lines += ['}};', '']
    return '\n'.join(lines), len(changed)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, count = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            raise SystemExit('Action-template source differs from the qualified reference')
    else:
        OUTPUT.write_text(text)
    print(f'PASS exact MCC action-template reference: replacements={count}')


if __name__ == '__main__':
    main()
