#!/usr/bin/env python3
"""Generate exact original authored permutation-time/native metadata policy."""
from pathlib import Path
import argparse
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]


def digest(value):
    result = bytes.fromhex(value)
    if len(result) != 32:
        raise ValueError("invalid SHA256")
    return result


def text(value):
    data = value.encode("utf-8")
    if not data or len(data) > 0x100000:
        raise ValueError("absent/excessive named sound identity")
    return struct.pack("<I", len(data)) + data


def generate(policy):
    if policy["schema"] != "H2_MCC_SOUND_PERMUTATION_TIME_REFERENCE_V1":
        raise ValueError("unknown policy schema")
    for name in ("primary_authority_sha256", "finite_authority_sha256",
                 "encoded_payload_authority_sha256"):
        digest(policy[name])
    records = {}
    for row in policy["keys"]:
        key = hashlib.sha256(b"H2_TU15_SOUND_TIMING_KEY_V1\0" + text(row["path"]) +
                             text(row["range"]) + text(row["permutation"])).digest()
        if key != digest(row["key_sha256"]) or key in records:
            raise ValueError("invalid/duplicate named permutation key")
        for field, reference in (("source_ms", "mcc_reference"),
                                 ("original_ms", "original_reference")):
            value = row[field]
            ref = row[reference]
            raw = bytes.fromhex(ref["row_hex"])
            if (type(value) is not int or not 0 <= value <= 0xffff or len(raw) != 16 or
                    hashlib.sha256(raw).digest() != digest(ref["row_sha256"]) or
                    struct.unpack_from("<H", raw, 6)[0] != value or not ref["case"]):
                raise ValueError("authored time differs from exact reference row")
            for name in ("sound", "gestalt"):
                if type(ref[name]) is not int or not 0 <= ref[name] < 0xffffffff:
                    raise ValueError("invalid full-salt reference owner")
            if not 0 < ref["sound_root"] < 0xffffffff:
                raise ValueError("invalid source sound root")
            for name in ("range_ordinal", "permutation_ordinal", "source_range", "source_permutation"):
                if type(ref[name]) is not int or not 0 <= ref[name] < 0x8000:
                    raise ValueError("invalid signed source ordinal")
        records[key] = (key + digest(row["payload_sha256"]) +
                        struct.pack("<HH", row["source_ms"], row["original_ms"]))
    if not records:
        raise ValueError("empty authored-time policy")
    lines = ["// Generated by tools/generate_mcc_sound_permutation_time_reference.py; do not edit.",
             "static constexpr char permutation_time_records[]=\n" + "\n".join(
                 '    "' + "".join(f"\\x{x:02x}" for x in records[key]) + '"'
                 for key in sorted(records)) + ";"]
    owners = set()
    encoded = []
    for row in policy["owners"]:
        identity = (row["handle"], row["root"], row["path"], row["metadata_sha256"])
        if (identity in owners or type(row["handle"]) is not int or
                not 0 <= row["handle"] < 0xffffffff or
                type(row["root"]) is not int or not 0 < row["root"] < 0xffffffff):
            raise ValueError("invalid/duplicate complete metadata owner")
        text(row["path"])
        owners.add(identity)
        raw = digest(row["metadata_sha256"])
        encoded.append("    Owner{{%du},%du,%s,{%s}}," % (
            row["handle"], row["root"], json.dumps(row["path"]),
            ",".join("std::byte{0x%02x}" % x for x in raw)))
    if not encoded:
        raise ValueError("missing complete owner profiles")
    lines.append("static const std::array<Owner,%d> permutation_time_owners{{\n%s\n}};" %
                 (len(encoded), "\n".join(encoded)))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = ROOT / "tools/mcc-sound-permutation-time-reference-profiles.json"
    target = ROOT / "src/mcc_sound_permutation_time_reference_profiles.inc"
    result = generate(json.loads(source.read_text()))
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit("permutation-time reference profile is stale")
    else:
        target.write_text(result)


if __name__ == "__main__":
    main()
