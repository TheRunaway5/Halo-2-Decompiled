#!/usr/bin/env python3
"""Export original readonly selectors used by teleporters and Relic's switch.

Run with tools/run_test.py. The complete16D0E0 collision collector is already
compiled; its embedded readonly switch tables also need real native backing.
No contact, occupied result, object state or instruction is supplied.
"""
from source_layout import source_file
import argparse
import csv
import hashlib
import json
import os
from pathlib import Path
import re
from capstone.x86 import X86_OP_IMM
from oracle_smg_firing_1_1 import ROOT, Xbe, _Code, _trace
from research_mp_sandbox_update_functions import NEW_DEFAULT, NEW_PIN


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args()
    scratch=Path(os.environ['HALO2_TEST_SCRATCH'])
    assert hashlib.sha256(NEW_DEFAULT.read_bytes()).hexdigest()==NEW_PIN
    image=Xbe(NEW_DEFAULT)
    starts={int(row['address'],16) for row in csv.DictReader(
        (ROOT/'analysis/multiplayer/title-update-1.5/decompiled/functions.tsv').open(),delimiter='\t')}
    lines=['// Generated by tools/export_native_tu15_teleporter_query_data.py.',
           '// Original English TU1.5 SHA256: '+NEW_PIN]
    tables=[];owners=[]
    for entry,name,expected in (
        (0x16d0e0,'source_combat_action_tu15_generated.cpp',[(0x16d27c,4,3),(0x16d288,1,12)]),
        (0x11e180,'source_scene_device_constructor_tu15_generated.cpp',[(0x11e260,4,4)])):
        function=_trace(_Code(image,'.text'),entry,starts)
        compiled=source_file(ROOT, name);source=compiled.read_bytes()
        sites={int(pc,16) for pc in re.findall(r'services\.instruction\(0x([0-9a-f]+)u?\)',source.decode())}
        assert function.code.keys()<=sites
        assert sorted(function.tables)==expected
        owners.append(dict(entry=hex(entry),compiled_owner=str(compiled.relative_to(ROOT)),
            compiled_owner_sha256=hashlib.sha256(source).hexdigest()))
        for address,width,count in sorted(function.tables):
            section=next(s for s in image.sections if s.va<=address and address+width*count<=s.va+s.vsize)
            assert not section.flags&1
            data=image.read(address,width*count)
            if width==4:assert all(int.from_bytes(data[i:i+4],'little') in function.code for i in range(0,len(data),4))
            else:assert all(value<3 for value in data)
            lines.append('constexpr std::array<std::byte,'+str(len(data))+'> teleporter_query_'+str(len(tables))+'{'+
                ','.join('std::byte{0x'+format(value,'02x')+'}' for value in data)+'};')
            tables.append(dict(address=hex(address),width=width,count=count,hex=data.hex(),entry=hex(entry)))
    # Whole1A6530 passes this original empty UTF16 string to_wcsncpy before
    # looking up the authored blocked notice. Preserve its actual terminator.
    instruction=_Code(image,'.text').at(0x1a6556)
    assert instruction.mnemonic=='push' and instruction.operands[0].imm==0x45c7cc
    readonly=image.section('.rdata')
    assert readonly.va<=0x45c7cc<0x45c7ce<=readonly.va+readonly.vsize
    literal=image.read(0x45c7cc,2)
    assert literal==bytes(2)
    lines.append('constexpr std::array<std::byte,2> teleporter_query_'+str(len(tables))+'{std::byte{0},std::byte{0}};')
    tables.append(dict(address='0x45c7cc',width=2,count=1,hex=literal.hex(),instruction='001a6556'))
    # Loading the real locale enables the original event formatter reached
    # during Relic's longer switch/walk route. Admit its literal tokens and
    # numeric/string format operands from the complete authenticated body.
    # These are program constants, never a produced caption/player/score.
    code=_Code(image,'.text');function=_trace(code,0x1a7ce0,starts)
    compiled=ROOT/'src/gameplay/units/source_combat_action_tu15_generated.cpp';source=compiled.read_bytes()
    sites={int(pc,16) for pc in re.findall(r'services\.instruction\(0x([0-9a-f]+)u?\)',source.decode())}
    assert function.code.keys()<=sites
    owners.append(dict(entry='0x1a7ce0',compiled_owner=str(compiled.relative_to(ROOT)),
        compiled_owner_sha256=hashlib.sha256(source).hexdigest()))
    literals={}
    for pc in sorted(function.code):
        instruction=code.at(pc)
        for operand in instruction.operands:
            if operand.type!=X86_OP_IMM or not readonly.va<=operand.imm<readonly.va+readonly.vsize:continue
            assert instruction.mnemonic=='push',(hex(pc),instruction.mnemonic,instruction.op_str)
            address=operand.imm;data=bytearray()
            for index in range(256):
                pair=image.read(address+index*2,2);data.extend(pair)
                if pair==bytes(2):break
            else:raise AssertionError('Unterminated original event-format literal')
            text=bytes(data).decode('utf-16-le').rstrip('\0')
            assert text.startswith(('#','%')),(hex(address),text)
            literals.setdefault(address,dict(data=bytes(data),text=text,sites=[]))['sites'].append(hex(pc))
    assert any(row['text']=='#cause_player' for row in literals.values())
    for address,row in sorted(literals.items()):
        data=row['data']
        lines.append('constexpr std::array<std::byte,'+str(len(data))+'> teleporter_query_'+str(len(tables))+'{'+
            ','.join('std::byte{0x'+format(value,'02x')+'}' for value in data)+'};')
        tables.append(dict(address=hex(address),width=2,count=len(data)//2,hex=data.hex(),
            text=row['text'],instructions=row['sites'],entry='0x1a7ce0'))
    lines.append('constexpr std::array teleporter_query_tables{'+','.join(
        'BranchTable{'+row['address']+'u,teleporter_query_'+str(index)+'}' for index,row in enumerate(tables))+'};')
    temporary=scratch/'teleporter-query-data.inc'
    temporary.write_text('\n'.join(lines)+'\n')
    args.output.write_bytes(temporary.read_bytes())
    report=dict(passed=True,source_sha256=NEW_PIN,compiled_owners=owners,tables=tables,
        bytes=sum(row['width']*row['count'] for row in tables),output_sha256=hashlib.sha256(temporary.read_bytes()).hexdigest(),
        scope='Immutable original query/control dispatch and blocked-notice literal data only; outcomes remain owned by original execution')
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report))


if __name__=='__main__':main()
