#!/usr/bin/env python3
"""Compile the finite complete NoAlpha metadata/state qualification policy."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def generate(raw):
    value=json.loads(raw)
    if value['schema']!='H2_MCC_NATIVE_NO_ALPHA_V1' or len(value['profiles'])!=2:
        raise ValueError('Unreviewed finite NoAlpha source census')
    setup=value['setup']
    if (setup['source_pass_sha256']!='58f9cc3554afa98ca465293ff448ba6a23c71bb4528518d300eba665dc44c57b' or
        setup['source_stem_sha256']!='b11171fc55c9a4d62a86bcdd98ca9ec2c995c06ed67905dd1f67a409dc260b55' or
        setup['native_source_map']!='01b_spacestation' or setup['no_alpha_source_mask']!=7 or
        setup['tu15_state_index']!=67 or setup['tu15_state_value']!=0x00010101):
        raise ValueError('NoAlpha authored/TU state authority changed')
    encoded=json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False)
    return ('// Generated by tools/generate_mcc_native_no_alpha.py; do not edit.\n'
        '// Source data SHA256: '+hashlib.sha256(raw).hexdigest()+'\n'
        'constexpr char native_no_alpha_storage[]=R"H2NOALPHA('+encoded+')H2NOALPHA";\n'
        'constexpr std::string_view native_no_alpha_profiles{native_no_alpha_storage,sizeof(native_no_alpha_storage)-1};\n')
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    text=generate((ROOT/'tools/data/mcc-native-no-alpha.json').read_bytes());target=ROOT/'src/rendering/mcc_native_no_alpha_profiles.inc'
    if a.check:
        if not target.is_file() or target.read_text()!=text:raise ValueError('Stale finite NoAlpha source registry')
    else:target.write_text(text)
if __name__=='__main__':main()
