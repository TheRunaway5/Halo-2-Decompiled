#include "native_tu15_operand_visit.hpp"
#include <bit>
#include <fstream>
#include <iostream>
#include <sstream>

namespace {
std::string number(std::uint64_t value) {
  std::ostringstream out;out<<"0x"<<std::hex<<value<<"ull";return out.str();
}
struct Initializers {
  std::ostream& out;
  unsigned owners{};
  std::size_t scalars{};
  std::vector<std::string> owner_stack;
  template<class T> void scalar(T value,const std::string& path) {
    ++scalars;out<<"    "<<path<<" = ";
    if constexpr(std::is_same_v<T,float>)
      out<<"std::bit_cast<float>(std::uint32_t{"<<number(std::bit_cast<std::uint32_t>(value))<<"})";
    else if constexpr(std::is_same_v<T,double>)
      out<<"std::bit_cast<double>(std::uint64_t{"<<number(std::bit_cast<std::uint64_t>(value))<<"})";
    else {
      std::uint64_t bits;
      if constexpr(std::is_enum_v<T>)bits=std::uint64_t(static_cast<std::underlying_type_t<T>>(value));
      else bits=std::uint64_t(value);
      out<<"static_cast<std::remove_cvref_t<decltype("<<path<<")>>("<<number(bits)<<")";
    }
    out<<";\n";
  }
  void optional(const std::string& path,bool present) {
    out<<"    "<<path<<(present?".emplace();\n":".reset();\n");
  }
  template<class T> std::string shared(const std::string& path,bool present) {
    if(!present){out<<"    "<<path<<".reset();\n";return {};}
    const auto owner="owned_"+std::to_string(++owners);owner_stack.push_back(owner);
    out<<"    auto "<<owner<<" = std::make_shared<std::remove_const_t<typename std::remove_cvref_t<decltype("<<path<<")>::element_type>>();\n";
    return "(*"+owner+")";
  }
  void shared_end(const std::string& path,bool present) {
    if(present){out<<"    "<<path<<" = "<<owner_stack.back()<<";\n";owner_stack.pop_back();}
  }
  void map(const std::string& path,std::size_t) {out<<"    "<<path<<".clear();\n";}
  template<class T> std::string map_entry(const std::string& path,T key) {
    return path+"["+number(std::uint64_t(key))+"]";
  }
  void sequence(const std::string& path,std::size_t size,bool resizable) {
    if(resizable)out<<"    "<<path<<".resize("<<size<<");\n";
  }
};
}
int main(int argc,char** argv)try {
  if(argc!=3)throw std::runtime_error("Supply the reference-only English TU1.5 XBE and output C++ file");
  const auto reference=halo2::OriginalData::load_xbe(argv[1]);
  if(reference->image!=halo2::OriginalData::Image::TitleUpdate15)
    throw std::runtime_error("Native gameplay operands require the authenticated TU1.5 reference");
  std::ostringstream code;
  code<<"// Generated by tools/generate_native_tu15_operands.cpp from the authenticated TU1.5 reference.\n"
        "// Reference SHA-256: 21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd.\n"
        "// Named immutable fields only. No XBE headers, executable sections, host pointers or live state.\n"
        "#include \"halo2/original_data.hpp\"\n#include \"halo2/full_scoreboard_paint_constants.hpp\"\n#include <bit>\n#include <type_traits>\n\n"
        "namespace halo2 {\nstd::shared_ptr<const OriginalData> OriginalData::native_tu15() {\n"
        "  static const std::shared_ptr<const OriginalData> data=[] {\n"
        "    auto result=std::make_shared<OriginalData>();\n"
        "    result->source=\"native-tu15-engine-operands\";\n";
  Initializers emitter{code};halo2::reference::operand_fields(emitter,*reference,"(*result)");
  code<<"    return result;\n  }();\n  return data;\n}\n} // namespace halo2\n";
  const auto target=std::filesystem::path(argv[2]);
  const auto temporary=target.string()+".tmp";
  {std::ofstream out(temporary,std::ios::binary);out<<code.str();
   if(!out)throw std::runtime_error("Could not write native operand initializers");}
  std::filesystem::rename(temporary,target);
  std::cout<<"Generated "<<emitter.scalars<<" named scalar operands with "<<emitter.owners<<" owned subrecords\n";
  return 0;
}catch(const std::exception& error){std::cerr<<error.what()<<'\n';return 1;}
