#!/usr/bin/env python3
"""Compile the finite paired MCC/TU1.5 data-admission registry, never programs."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = (
    ("opaque", "overlay", "01b_spacestation", "copy"),
    ("opaque", "tex_alpha_test", "01b_spacestation", "drop_pc_only_pixels"),
    ("opaque", "tex_bump_alpha_test", "01b_spacestation", "copy"),
    ("opaque", "tex_bump_alpha_test_single_pass", "01b_spacestation", "copy"),
    ("opaque", "tex_bump_env_alpha_test_combined", "01b_spacestation", "environment_alpha"),
    ("opaque", "tex_bump_env_combined", "01b_spacestation", "environment_combined"),
    ("opaque", "tex_bump_env_illum_combined", "01b_spacestation", "copy"),
    ("opaque", "tex_bump_illum", "01b_spacestation", "copy"),
    ("transparent", "one_alpha_env", "03a_oldmombasa", "swap_environment_pixels"),
    ("transparent", "one_alpha_env_illum", "dune", "swap_environment_pixels"),
    ("water", "water_edge_blend", "dune", "copy"),
    ("opaque", "decal_simple", "03b_newmombasa", "copy"),
    ("opaque", "tex_bump_detail_keep", "05a_deltaapproach", "copy"),
)


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def generate(raw):
    value = json.loads(raw)
    if value["schema"] != "H2_MCC_NATIVE_WORLD_COOKED_PROFILES_V1" or len(value["profiles"]) != len(RULES):
        raise ValueError("Changed finite native cooked-profile schema/census")
    projected = []
    owners = set()
    for profile, (category, family, source, operation) in zip(value["profiles"], RULES):
        name = "shaders\\shader_templates\\" + category + "\\" + family
        if (profile["template"] != name or profile["mapping"] != operation or
                profile["native_source_map"] != source or
                profile["native_record"]["group"] != "stem" or profile["native_record"]["name"] != name):
            raise ValueError("Unreviewed native cooked-profile operation or source")
        graph = profile["source_graph"]
        if hashlib.sha256(canonical(graph)).hexdigest() != profile["source_graph_sha256"]:
            raise ValueError("Changed complete literal MCC stem/remap identity")
        if len(bytes.fromhex(graph["root_hex"])) != 96 or len(graph["definitions"]) != 3:
            raise ValueError("Changed literal MCC compiled-template root")
        for definition in graph["definitions"]:
            if len(bytes.fromhex(definition["definition_hex"])) != 40:
                raise ValueError("Changed literal MCC template-definition extent")
            for array, (field, stride) in zip(definition["arrays"], ((0, 10), (8, 2), (16, 10), (24, 6), (32, 4))):
                if (array["field"] != field or not 0 <= array["count"] <= 65536 or
                        len(bytes.fromhex(array["raw_hex"])) != array["count"] * stride or
                        len(array["typed_references"]) != (array["count"] if field == 16 else 0)):
                    raise ValueError("Changed complete MCC compiled-remap bank")
                if any(len(ref) != 2 or ref[0] != "spas" for ref in array["typed_references"]):
                    raise ValueError("MCC compiled-template reference escapes typed pass ownership")
        if any(profile["source_counts"][str(field)] for field in (60, 68, 76, 84)):
            raise ValueError("Animated authoring is outside this qualified profile")
        if not profile["paired_proof"]["complete_main_bank_transform_matches"]:
            raise ValueError("Missing literal complete paired main-bank mapping proof")
        for owner in profile["needed_PC_owners"]:
            key = owner["map"], owner["datum"]
            if owner["map"] not in ("needle", "street_sweeper") or key in owners:
                raise ValueError("Unknown or repeated geometry source owner")
            owners.add(key)
        projected.append({key: profile[key] for key in (
            "template", "mapping", "source_graph", "source_counts", "shader_type_flags",
            "runtime_diffuse_slot", "allowed_none_bitmap_slots", "native_shape")})
        projected[-1]["native_record"] = {key: profile["native_record"][key]
                                           for key in ("payload", "bytes", "fnv64")}
    if len(owners) != 31:
        raise ValueError("Changed complete twenty-seven-owner source proof")
    data = canonical({"schema": value["schema"], "profiles": projected}).decode()
    return ("// Generated by tools/generate_mcc_native_world_cooked_profiles.py; do not edit.\n"
            "// Paired source data SHA256: " + hashlib.sha256(raw).hexdigest() + "\n"
            "constexpr std::string_view native_world_cooked_profiles=R\"H2COOKED(" + data + ")H2COOKED\";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = (ROOT / "tools/data/mcc-native-world-cooked-profiles.json").read_bytes()
    text = generate(data)
    output = ROOT / "src/rendering/mcc_native_world_cooked_profiles.inc"
    if args.check:
        if not output.is_file() or output.read_text() != text:
            raise ValueError("Stale finite native cooked-profile registry")
    else:
        output.write_text(text)


if __name__ == "__main__":
    main()
