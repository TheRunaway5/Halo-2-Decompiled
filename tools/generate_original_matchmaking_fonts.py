#!/usr/bin/env python3
"""Emit bounded, exact DVD v1 font payloads for the finite original UI views.

Run through tools/run_test.py with --output under HALO2_TEST_SCRATCH. Copy the
qualified generated include into the source tree explicitly after reviewing
the receipt. Original font inputs are read-only; no sampled pixels are made.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
OWNERS = (
    (1, "conduit-12", 436791, "337dfeb3b9dd787bcd9309d2efd8d8b3d3bcac2a0169000d0249abc131dfdab8"),
    (2, "handel_gothic-11", 437452, "d7a767c200b9cf213b3faaa11aa4f12d93b3a2f362d3ac474d1a6b5eee2cd3c7"),
    (4, "conduit-13", 437344, "e949a8f316f41f1635e5c3ce807bf720a5606dfd9352b40a3fccc4c3b13d645b"),
    (9, "conduit-16", 440022, "ae58c2493f749194859c1409047518cd96b15725679acb0175f32f0679ddb19f"),
)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts", type=Path, default=ROOT / "assets/disc/maps/fonts")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    owned = Path(os.environ["HALO2_TEST_SCRATCH"]).resolve()
    output = args.output.resolve()
    if not output.is_relative_to(owned):
        raise ValueError("generated font include must stay in owned test scratch")
    lines = ["// Exact pinned original DVD v1 fonts; no MCC resampling or glyph redraw.",
             "// Generated by tools/generate_original_matchmaking_fonts.py."]
    rows = []
    total = 0
    for selector, name, size, sha256 in OWNERS:
        path = args.fonts / name
        data = path.read_bytes()
        if len(data) != size or digest(data) != sha256 or struct.unpack_from("<I", data, 0x200)[0] != 0xF0000001:
            raise ValueError(f"unrecognized original font authority: {name}")
        compressed = zlib.compress(data, 9)
        if len(compressed) > 81000 or zlib.decompress(compressed) != data:
            raise ValueError(f"font compression outside finite bounds: {name}")
        encoded = compressed.hex()
        chunks = [encoded[i:i + 4096] for i in range(0, len(encoded), 4096)]
        lines.append(f"constexpr std::array<std::string_view,{len(chunks)}> original_font_{selector}{{{{")
        lines.extend(f'    "{chunk}",' for chunk in chunks)
        lines.append("}};")
        rows.append(dict(selector=selector, name=name, bytes=size, sha256=sha256,
                         compressed_bytes=len(compressed), compressed_sha256=digest(compressed),
                         chunks=len(chunks)))
        total += len(compressed)
    if total > 320000:
        raise ValueError("original font bank exceeds its bounded payload")
    lines.append("constexpr std::array<OriginalFontPayload,4> original_font_payloads{{")
    for row in rows:
        lines.append(f'    OriginalFontPayload{{{row["selector"]},"{row["name"]}","{row["sha256"]}",{row["bytes"]},{row["compressed_bytes"]},original_font_{row["selector"]}}},')
    lines.append("}};")
    encoded = ("\n".join(lines) + "\n").encode()
    if len(encoded) > 650000:
        raise ValueError("generated original font source exceeds650KiB")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(encoded)
    report = dict(schema="H2_ORIGINAL_MATCHMAKING_FONT_PAYLOAD_V1", passed=True,
                  source="original DVD v1 font files used by the recovered TU1.5 UI selectors",
                  owners=rows, selector_aliases={"6": 4}, compressed_bytes=total,
                  output_bytes=len(encoded), output_sha256=digest(encoded),
                  generator_sha256=digest(Path(__file__).read_bytes()), scratch=str(owned),
                  pixels="Original compressed A4R4G4B4 glyph streams, lookup and metrics retained exactly",
                  retained_large_artifacts=[])
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(f"original font payload: {total} compressed bytes, generated source {len(encoded)} bytes")


if __name__ == "__main__":
    main()
