#!/usr/bin/env python3
"""Generate the finite original timing operand policy; --check needs no assets."""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / 'tools/mcc-sound-timing-reference-profiles.json'
OUTPUT = ROOT / 'src/audio/mcc_sound_timing_reference_profiles.inc'


def digest(value):
    assert re.fullmatch('[0-9a-f]{64}', value)
    return '{' + ','.join('std::byte{0x' + value[n:n+2] + '}' for n in range(0, 64, 2)) + '}'


def named_key(path, pitch, permutation):
    result = b'H2_TU15_SOUND_TIMING_KEY_V1\0'
    for name in (path, pitch, permutation):
        raw = name.encode('utf8')
        assert raw and len(raw) <= 0x100000
        result += struct.pack('<I', len(raw)) + raw
    return hashlib.sha256(result).digest()


def generate(data):
    assert data['schema'] == 'H2_MCC_SOUND_TIMING_REFERENCE_V1'
    assert len(data['owners']) == 41 and len(data['keys']) == 24624
    records, keys, excluded = [], set(), []
    original_rows = []
    for row in data['keys']:
        key = named_key(row['path'], row['range'], row['permutation'])
        assert key.hex() == row['key_sha256'] and key not in keys
        keys.add(key)
        payload = bytes.fromhex(row['payload_sha256'])
        original = row['original']
        assert isinstance(row['admitted'], bool)
        original_rows.append({'path': row['path'], 'range': row['range'],
                              'permutation': row['permutation'],
                              'original_duration_tuple': original})
        assert len(payload) == 32 and len(original) == 9
        assert all(0 <= original[i] < n for i, n in enumerate((3, 3, 5)))
        assert 0 < original[3] <= 0xffffffff
        assert all(-32768 <= v <= 32767 for v in original[4:])
        prefix = key + payload + struct.pack('<IBBB', original[3], *original[:3])
        assert len(prefix) == 71
        record = prefix + struct.pack('<5h', *original[4:])
        assert len(record) == 81
        records.append((key, prefix, record))
        if not row['admitted']:
            assert row['path'] == 'sound\\vehicles\\wraith\\wraith_projectile\\track1\\loop'
            assert row['range'] == '|default|' and row['permutation'] in ('wraithlp1', 'wraithlp2', 'wraithlp3')
            assert original[4:] == [1, 0, 0, 0, 0]
            excluded.append(key)
    assert len(excluded) == 3
    original_bytes = (json.dumps(original_rows, separators=(',', ':')) + '\n').encode()
    assert hashlib.sha256(original_bytes).hexdigest() == data['source_original_tuples_sha256']
    records.sort()
    assert hashlib.sha256(b''.join(x[1] for x in records)).hexdigest() == data['source_reference71_sha256']
    packed = b''.join(x[2] for x in records)
    lines = ['// Generated by tools/generate_mcc_sound_timing_reference.py; do not edit.',
             '// 81 bytes: key32,payload32,encoded4,format3,original pitch shorts10.',
             'static constexpr char timing_reference_bytes[]=']
    for at in range(0, len(packed), 81):
        lines.append('    "' + ''.join('\\x%02x' % b for b in packed[at:at+81]) + '"')
    lines += ['    ;', 'static_assert(sizeof(timing_reference_bytes)-1==24624u*81u);',
              'static constexpr std::array<MccSoundVanillaDigest,3> timing_unavailable_pitch_keys{{']
    lines += ['    ' + digest(k.hex()) + ',' for k in sorted(excluded)]
    lines += ['}};', 'static const std::array<TimingOwner,41> timing_known_owners{{']
    seen = set()
    for owner in data['owners']:
        key = (owner['handle'], owner['root'], owner['path'], owner['metadata_sha256'])
        assert key not in seen and owner['source_maps']
        seen.add(key)
        for source in owner['source_maps']:
            assert re.fullmatch('[0-9a-f]{64}', source['sha256'])
        lines.append('    TimingOwner{{%du},%du,%s,%s},' % (
            owner['handle'], owner['root'], json.dumps(owner['path']), digest(owner['metadata_sha256'])))
    lines += ['}};']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(json.loads(FACTS.read_text()))
    if args.check:
        if OUTPUT.read_text() != result:
            raise SystemExit('Sound timing reference policy is stale')
        print('Sound timing policy current: 41 owners, 24621 admitted keys, 3 explicit pitch gaps')
    else:
        OUTPUT.write_text(result)


if __name__ == '__main__':
    main()
