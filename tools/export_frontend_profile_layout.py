#!/usr/bin/env python3
"""Export Appearance and Select Player layout metadata for the existing Halo 2 painter."""
import argparse
import json
import os
from pathlib import Path
import re

from audit_rendering import Cache, file_sha
from audit_selected_mcc_frontend import cache as read_mcc
from export_matchmaking_ui_tu15 import Definition, ROOT, XBOX_PIN


def widgets(cache, base):
    codec = Definition(cache)
    screens = {}
    for tag in cache.tags.values():
        if tag["group"] == "wgit" and tag["address"]:
            _, header = cache.tag(tag["datum"], "wgit")
            screen = cache.u16(header + 4)
            if screen in (47, 193):
                screens[str(screen)] = codec.screen(tag)
    assert set(screens) == {"47", "193"}
    globals_tag = next(t for t in cache.tags.values() if t["group"] == "wigl")
    _, globals_header = cache.tag(globals_tag["datum"], "wigl")
    skin_refs = cache.block(globals_header + 0x138, 8)
    skins = {str(i): codec.skin(cache.u32(skin_refs[i] + 4)) for i in (8, 13)}
    groups = {}
    while codec.groups:
        datum = codec.groups.pop()
        name = cache.tags[datum]["name"]
        if name not in base["groups"] and name not in groups:
            groups[name] = codec.skin(datum)
    images = {cache.tags[d]["name"]: codec.image(d) for d in codec.images
              if cache.tags[d]["name"] not in base["images"]}
    return dict(screens=screens, skins=skins, groups=groups, images=images)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mcc", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.resolve().relative_to(Path(os.environ["HALO2_TEST_SCRATCH"]).resolve())
    xbox = ROOT / "assets/disc/maps/mainmenu.map"
    assert file_sha(xbox) == XBOX_PIN
    base = json.loads((ROOT / "resources/frontend/mcc-native-layout.json").read_text())["layout"]
    original = Cache(xbox)
    selected, digest = read_mcc(args.mcc)
    profile = dict(original=widgets(original, base["original"]), raw=widgets(selected, base["raw"]))

    # Keep the selected language bank and identifier namespace. The original
    # symbol and selected compiled identifier are joined by the named catalog.
    table = (ROOT / "src/ui/mcc_frontend_string_ids.inc").read_text()
    ids = {int(a, 16): int(b, 16) for a, b in re.findall(r'\{0x([0-9a-f]+)u,0x([0-9a-f]+)u,', table)}

    def localize(node):
        if isinstance(node, list):
            for child in node:
                localize(child)
        elif isinstance(node, dict):
            for key, value in node.items():
                if key in ("string", "placeholder", "header") and value:
                    node[key] = ids[value & 0xffff]
                else:
                    localize(value)

    localize(profile["original"])
    # Existing sides already qualify their own descriptors. For the additions
    # the codec exposes logical dimensions and sprite registration at runtime.
    for image in profile["raw"]["images"].values():
        for frame in image["frames"]:
            del frame["format"]
    dump = json.dumps(profile, sort_keys=True, separators=(",", ":"))
    args.output.write_text(
        f"// Generated by tools/export_frontend_profile_layout.py\n"
        f"// Original mainmenu {XBOX_PIN}\n// MCC mainmenu {digest}\n"
        f'inline constexpr std::string_view profile_layout_data = R"H2UI({dump})H2UI";\n')


if __name__ == "__main__":
    main()
