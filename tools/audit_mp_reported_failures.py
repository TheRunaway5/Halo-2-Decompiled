#!/usr/bin/env python3
"""Freeze literal resources and bounded native event/metadata comparisons.

These are diagnostics and an event-provider seam, not completed live grenade,
canister, sound scheduler, original hardware decoding or all-map sound parity.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'analysis/multiplayer/integration/reported-failures-20261008'
sys.path.insert(0, str(ROOT / 'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        assert path.read_bytes() == data, ('Immutable output differs', str(path))
    else:
        path.write_bytes(data)


def encoded(value):
    return (json.dumps(value, sort_keys=True, indent=2) + '\n').encode()


def audit(output):
    output = output.resolve()
    assert ROOT in output.parents, 'Checkpoint output must stay inside the owned project'
    inputs, repeat_files = {}, 0
    for name in ('sound-resources', 'all-sound-resources', 'sound-size-u5'):
        left, right = BASE / name / 'measured', BASE / name / 'repeated'
        files = {p.relative_to(left) for p in left.rglob('*') if p.is_file()}
        assert files == {p.relative_to(right) for p in right.rglob('*') if p.is_file()}
        for relative in sorted(files):
            assert sha(left / relative) == sha(right / relative), (name, relative)
            repeat_files += 1
        report = json.loads((left / 'report.json').read_text())
        if name != 'sound-size-u5':
            assert report['fixture_sha256'] == sha(left / 'fixtures.tsv')
            assert report['tool_sha256'] == sha(ROOT / 'tools' / (
                'export_mp_first_person_sound_resources.py' if name == 'sound-resources'
                else 'export_mp_all_sound_resources.py'))
            assert report['cache_reader_sha256'] == sha(ROOT / 'tools/inspect_multiplayer.py')
            for path, expected in report['resource_files'].items():
                assert sha(ROOT / path) == expected
                inputs[path] = expected
            for row in report['maps']:
                assert sha(ROOT / row['path']) == row['sha256']
                inputs[row['path']] = row['sha256']
            assert sum(row['encoded_cases'] for row in report['maps']) == report['cases']
            assert len(report['maps']) == 21
    source_report = json.loads((BASE / 'sound-size-u5/measured/report.json').read_text())
    assert source_report['tool_sha256'] == sha(ROOT / 'tools/research_mp_sound_size_u5.py')
    assert source_report['matcher_sha256'] == sha(ROOT / 'tools/research_animation_selection_u5.py')
    assert source_report['raw_report_sha256'] == sha(BASE / 'sound-size-u5/measured/raw/report.json')
    images = {}
    for path, expected in source_report['image_sha256'].items():
        assert sha(path) == expected
        inputs[path] = expected
        images['u5' if 'u5English' in path else 'old'] = Xbe(path)
    owner = source_report['owners'][0]
    assert len(source_report['owners']) == 1 and owner['old'] == '0021abd0'
    assert owner['u5'] == '0021f4d0' and owner['rows'] == 18
    assert owner['unique_full_body_match'] and owner['normalized_complete_body_and_internal_branch_equal']
    instruction_rows = 0
    for path in (BASE / 'sound-size-u5/measured/raw/instructions').glob('*.asm'):
        image = images[path.stem.split('-')[-1]]
        for line in path.read_text().splitlines():
            address, raw, _ = line.split(' ', 2)
            data = bytes.fromhex(raw)
            assert image.read(int(address, 16), len(data)) == data
            instruction_rows += 1
    assert instruction_rows == 36

    # The constant inputs are literal memory operands in already independently
    # matched complete original bodies, never values generated by this port.
    constant_sources = [
        ROOT / 'analysis/multiplayer/integration/inventory-source/unit-animation-clock/u5-correspondence/report.json',
        ROOT / 'analysis/multiplayer/integration/animation-variant/u5/report.json']
    constants = {}
    wanted = {'00465030', '00465048', '0046504c', '004650c0', '00465028'}
    for path in constant_sources:
        data = json.loads(path.read_text())
        for row in data['owners']:
            for memory in row['memory']:
                if memory['old_va'] in wanted:
                    assert row['unique_full_body_match'] and row['normalized_complete_body_and_internal_branch_equal']
                    assert memory['bytes'] == 4 and memory['old_hex'] == memory['new_hex']
                    for tag, at, expected in [('old', memory['old_va'], memory['old_hex']),
                                              ('u5', memory['new_va'], memory['new_hex'])]:
                        assert images[tag].read(int(at, 16), 4).hex() == expected
                    value = {key: memory[key] for key in ('old_va', 'new_va', 'old_hex', 'new_hex')}
                    if memory['old_va'] in constants:
                        assert constants[memory['old_va']] == value
                    constants[memory['old_va']] = value
    assert set(constants) == wanted

    tests = []
    for kind in ('normal', 'sanitized'):
        full = BASE / f'all-sound-resources/{kind}/LastTest.log'
        focused = BASE / f'focused-{kind}/LastTest.log'
        full_text, focused_text = full.read_text(), focused.read_text()
        for text in (full_text, focused_text):
            assert 'Test Passed.' in text
            assert 'Test Failed.' not in text and 'ERROR: AddressSanitizer' not in text
            assert 'runtime error:' not in text
        assert focused_text.count('Test Passed.') == 4
        line = re.search(r'^ownedMaps=21 originalEncodedCases=88254 .*$', full_text, re.M).group()
        assert 'decodeFailures=0' in line and 'uniqueDecodedResources=5197' in line
        assert 'exactEncodedBytes=3334678947' in line
        assert 'originalGraphs=58 originalDefinitions=3372 stableReferences=3372 graphBounds=58' in focused_text
        assert 'Actual local event delivery: 2 original callbacks' in focused_text
        assert '541 original ticks/2705 primary-channel phase states,4 original callbacks and 516 local match ticks matched' in focused_text
        assert 'originalEncodedCases=483 uniqueDecodedResources=23' in focused_text
        tests.append(dict(kind=kind, full_output=line, full_log_sha256=sha(full),
                          focused_log_sha256=sha(focused), focused_tests=4))

    prior = {}
    for relative, keys in [
        ('analysis/multiplayer/integration/unit-animation-definitions-20261008/manifest.json', ('pins', 'preserved_prior_pins')),
        ('analysis/multiplayer/integration/spawn-source/animation-selection/manifest.json', ('artifact_pins', 'protected_prior_pins')),
        ('analysis/multiplayer/sandbox-source/contact-lifecycle/final/manifest.json', ('files',))]:
        manifest = ROOT / relative
        data = json.loads(manifest.read_text())
        prior[relative] = sha(manifest)
        for key in keys:
            for path, expected in data[key].items():
                assert sha(ROOT / path) == expected, ('Prior authority changed', path)
                if path in prior:
                    assert prior[path] == expected
                prior[path] = expected

    sources = [
        'include/halo2/unit_animation_constants.hpp', 'include/halo2/original_data.hpp', 'src/original_data.cpp',
        'include/halo2/unit_animation_metadata_store.hpp', 'src/unit_animation_metadata_store.cpp',
        'tests/unit_animation_metadata_store_tests.cpp', 'include/halo2/multiplayer.hpp',
        'src/multiplayer.cpp', 'tests/fp_clock_tests.cpp', 'src/content.cpp',
        'tools/research_mp_sound_size_u5.py', 'tools/export_mp_first_person_sound_resources.py',
        'tools/export_mp_all_sound_resources.py', 'tests/multiplayer_sound_resources_tests.cpp',
        'tests/multiplayer_all_sound_resources_tests.cpp', 'tools/audit_mp_reported_failures.py',
        'docs/MP_REPORTED_GAMEPLAY_FAILURES_RESEARCH.md']
    snapshots = {}
    for relative in sources + ['CMakeLists.txt']:
        path = output / 'source' / relative
        save(path, (ROOT / relative).read_bytes())
        snapshots[relative] = dict(copy=str(path.relative_to(ROOT)), sha256=sha(path))
    artifacts = {}
    for path in BASE.rglob('*'):
        if path.is_file() and output not in path.parents:
            artifacts[str(path.relative_to(ROOT))] = sha(path)
    for path in output.rglob('*'):
        if path.is_file():
            artifacts[str(path.relative_to(ROOT))] = sha(path)
    manifest = dict(schema='reported-multiplayer-failures-checkpoint-v1', scope=__doc__,
                    source_snapshots=snapshots, artifact_pins=artifacts, owned_input_pins=inputs,
                    protected_prior_pins=prior, repeat_files=repeat_files,
                    sound_size_instruction_rows=instruction_rows, animation_operand_pairs=constants,
                    native_tests=tests, mismatches=0,
                    cmake_scope='Observed complete shared CMake file; owns only metadata store and two resource-test registrations.',
                    live_grenade=False, live_canister_collision_explosion=False,
                    live_first_person_sound_playback=False, all_map_event_sound_parity=False)
    save(output / 'manifest.json', encoded(manifest))
    print(json.dumps(dict(artifacts=len(artifacts), protected_prior=len(prior),
                          owned_inputs=len(inputs), independent_repeat_files=repeat_files,
                          mismatches=0, manifest_sha256=sha(output / 'manifest.json'))))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path)
    audit(parser.parse_args().output)
