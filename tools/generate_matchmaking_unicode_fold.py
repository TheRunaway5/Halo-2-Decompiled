#!/usr/bin/env python3
"""Generate native full case folding from the retained Unicode16 source data.

Run through tools/run_test.py; the generated source is an intentional output.
Normalization remains provided by the pinned Unicode16 normalization crate.
"""
import hashlib
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    scratch = Path(os.environ['HALO2_TEST_SCRATCH'])
    source = ROOT/'rust/online_protocol/data/unicode16/CaseFolding.txt'
    raw = source.read_bytes()
    assert raw.startswith(b'# CaseFolding-16.0.0.txt')
    mappings = {}
    for line in raw.decode().splitlines():
        fields = line.split('#',1)[0].split(';')
        if len(fields)<3 or fields[1].strip() not in ('C','F'):
            continue
        code = int(fields[0],16)
        assert code not in mappings
        mappings[code] = [int(c,16) for c in fields[2].split()]
    rows = ['//! Generated by tools/generate_matchmaking_unicode_fold.py; do not edit.',
            '//! Unicode16 full default C+F mappings; Turkic T mappings are excluded.',
            '//! Source: https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt',
            '//! Copyright 2024 Unicode, Inc.; see data/unicode16/LICENSE.txt.',
            '#[cfg(test)]',
            f'pub const SOURCE_SHA256: &str = "{hashlib.sha256(raw).hexdigest()}";',
            'pub const MAPPINGS: &[(u32, &str)] = &[']
    for code, mapped in sorted(mappings.items()):
        value = ''.join('\\u{'+format(c,'x')+'}' for c in mapped)
        rows.append(f'    (0x{code:x}, "{value}"),')
    rows.extend(('];',''))
    output = scratch/'matchmaking_unicode_fold_table.rs'
    output.write_text('\n'.join(rows))
    target = ROOT/'rust/online_protocol/src/matchmaking_unicode_fold_table.rs'
    target.write_bytes(output.read_bytes())
    print(f'{len(mappings)} Unicode16 mappings; source SHA256 {hashlib.sha256(raw).hexdigest()}')


if __name__=='__main__':
    main()
