#!/usr/bin/env python3
"""Retain complete original utility/light constructor programs for native consumers.

Run extract_reference_light_programs.py against the unchanged original first.
All 560 fixture rows and every authenticated instruction must agree. This is
program construction only; completed coordinates and target scheduling retain
separate owners.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'tools'), str(ROOT / 'tools/reference/halo2-decompiled/tools')]
from oracle_smg_firing_1_1 import Xbe


def generate(reference):
    if reference['original_sha256'] != '5a9edb4c874a782594c86020db49b0086f44ae38f53ff2276b3192a2c2383d18':
        raise RuntimeError('Unrecognized original program source')
    image_path = Path('/mnt/SSD4TB/Leaks/Halo 2/2003/game/halo2debug.xbe')
    if hashlib.sha256(image_path.read_bytes()).hexdigest() != reference['original_sha256']:
        raise RuntimeError('Original executable differs')
    image = Xbe(image_path)
    for row in reference['instructions']:
        if hashlib.sha256(image.read(int(row['address'], 16), row['size'])).hexdigest() != row['sha256']:
            raise RuntimeError('Original constructor instruction differs')
    utility, dependent = [None] * 128, [None] * 24
    for row in reference['fixtures']:
        words, inputs = row['words'], row['inputs']
        if len(words) != 60 or hashlib.sha256(struct.pack('<60I', *words)).hexdigest() != row['sha256']:
            raise RuntimeError('Original constructed program differs')
        if inputs['builtin'] in (6, 10):
            index = (inputs['builtin'] == 10) * 64 + (inputs['context_7438a8'] != 0) * 32 + \
                (inputs['global_48f346'] != 0) * 16 + inputs['context_u176'] * 4 + inputs['context_u178']
            target = utility
        elif inputs['builtin'] == 7:
            index = (inputs['context_7438a8'] != 0) * 12 + inputs['context_u0dc'] * 3 + inputs['global_7439dc']
            target = dependent
        else:
            raise RuntimeError('Unexpected original constructor kind')
        if target[index] is not None and target[index] != words:
            raise RuntimeError('Original selector canonicalization changes a program')
        target[index] = words
    if len(reference['fixtures']) != 560 or any(row is None for row in utility + dependent):
        raise RuntimeError('Original constructor domain is incomplete')
    output = '// Generated by tools/pstencil/generate_light_response_2003.py.\n'
    output += '// Unchanged original964B0, 560 declared fixtures; not a captured frame.\n'
    for name, rows in (('utility_2003_programs', utility), ('dependent_2003_programs', dependent)):
        output += f'constexpr std::array<std::array<std::uint32_t,60>,{len(rows)}> {name}{{{{\n'
        for words in rows:
            output += '    {{' + ','.join(f'0x{word:08x}u' for word in words) + '}},\n'
        output += '}};\n'
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=ROOT / 'src/pstencil/light_response_2003_programs.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads(args.reference.read_text()))
    if args.check:
        if args.output.read_text() != output:
            raise RuntimeError('Generated original program table differs')
    else:
        args.output.write_text(output)
    print(json.dumps(dict(fixtures=560, utility_programs=128, dependent_programs=24,
        sha256=hashlib.sha256(output.encode()).hexdigest(), check=args.check)))


if __name__ == '__main__':
    main()
