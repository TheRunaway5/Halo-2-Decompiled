#!/usr/bin/env python3
"""Export bounded original MOPP opcode selector/targets, never contact results.

Run through tools/run_test.py. TU1.5 is an offline immutable reference only.
The live Zanzibar query reads byte30A918 through30A341. The original bound
and complete traced selector/target tables establish exact108/128-byte owners.
"""
import argparse
import hashlib
import json
import os
import re
from pathlib import Path
import struct

from oracle_smg_firing_1_1 import Xbe, _Code, _trace
from research_mp_sandbox_update_functions import NEW_DEFAULT, NEW_PIN
from generate_collision_query_tu15 import ENTRIES
from capstone import CS_AC_READ


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    assert os.environ.get('HALO2_TEST_SCRATCH'), 'Use tools/run_test.py'
    assert hashlib.sha256(NEW_DEFAULT.read_bytes()).hexdigest() == NEW_PIN
    image = Xbe(NEW_DEFAULT)
    code = _Code(image, '.text')
    body = _trace(code, 0x30a320, {0x30a320})
    assert body.tables == [(0x30a870, 4, 32), (0x30a8f0, 1, 108)]
    assert bytes(code.at(0x30a32b).bytes).hex() == '83f86b'
    assert bytes(code.at(0x30a341).bytes).hex() == '0fb688f0a83000'
    assert bytes(code.at(0x30a348).bytes).hex() == 'ff248d70a83000'
    address, count = 0x30a8f0, 108
    section = next(s for s in image.sections if s.va <= address and address + count <= s.va + s.vsize)
    assert not section.flags & 1
    data = image.read(address, count)
    targets = struct.unpack('<32I', image.read(0x30a870, 128))
    assert all(value < len(targets) and targets[value] in body.code for value in data)
    consumer = Path(__file__).resolve().parents[1] / 'src/physics/collision/source_collision_query_tu15_generated.cpp'
    roots = {int(value, 16) for value in re.findall(r'^static void run_([0-9a-f]+)\(WorldState &s\) \{', consumer.read_text(), re.M)}
    assert roots == set(ENTRIES)
    readonly = image.section('.rdata')
    assert not readonly.flags & 1
    literals = {}
    for entry in ENTRIES:
        for pc in _trace(code, entry, set(ENTRIES)).code:
            instruction = code.at(pc)
            if instruction.mnemonic == 'lea' or instruction.mnemonic.startswith(('nop', 'prefetch')):
                continue
            for operand in instruction.operands:
                if (operand.type == 3 and not operand.mem.base and not operand.mem.index and
                        operand.access & CS_AC_READ and readonly.va <= operand.mem.disp and
                        operand.mem.disp + operand.size <= readonly.va + readonly.vsize):
                    assert 0 < operand.size <= 16
                    literals[operand.mem.disp, operand.size] = image.read(operand.mem.disp, operand.size)
    assert set(literals) == {(0x41c67c, 4), (0x41c680, 16), (0x41c690, 16), (0x41c6b0, 16),
                             (0x461950, 16), (0x461960, 16), (0x46a0d0, 4), (0x46a0e8, 4)}
    text = ['// Generated by tools/export_native_tu15_collision_query_data.py.',
            '// English TU1.5 SHA256: ' + NEW_PIN,
            '// Exact bounded byte selector; no code, collision or produced state.',
            'constexpr std::array<std::byte,108> collision_query_selector{']
    for offset in range(0, len(data), 12):
        text.append('    ' + ','.join(f'std::byte{{0x{value:02x}}}' for value in data[offset:offset + 12]) + ',')
    text += ['};', 'constexpr std::array<std::byte,128> collision_query_targets{']
    target_data = image.read(0x30a870, 128)
    for offset in range(0, len(target_data), 12):
        text.append('    ' + ','.join(f'std::byte{{0x{value:02x}}}' for value in target_data[offset:offset + 12]) + ',')
    text += ['};']
    for index, ((literal_address, size), raw) in enumerate(sorted(literals.items())):
        text += [f'constexpr std::array<std::byte,{size}> collision_query_literal_{index}{{',
                 '    ' + ','.join(f'std::byte{{0x{value:02x}}}' for value in raw), '};']
    text += ['constexpr std::array collision_query_tables{',
             '    BranchTable{0x30a8f0u,collision_query_selector},',
             '    BranchTable{0x30a870u,collision_query_targets},']
    for index, ((literal_address, _), _) in enumerate(sorted(literals.items())):
        text.append(f'    BranchTable{{0x{literal_address:x}u,collision_query_literal_{index}}},')
    text.append('};')
    output = ('\n'.join(text) + '\n').encode()
    args.output.write_bytes(output)
    report = {'passed': True, 'tu15_sha256': NEW_PIN, 'entry': 0x30a320,
              'selector_address': address, 'selector_bytes': count,
              'input_bound': 0x6b, 'target_count': 32, 'target_address': 0x30a870,
              'target_bytes': 128, 'target_hex': target_data.hex(), 'selector_hex': data.hex(),
              'source_instructions': [0x30a32b, 0x30a341, 0x30a348],
              'fixed_readonly_operands': [{'address': address, 'bytes': size, 'hex': raw.hex()}
                  for (address, size), raw in sorted(literals.items())],
              'compiled_query_sha256': hashlib.sha256(consumer.read_bytes()).hexdigest(),
              'output_sha256': hashlib.sha256(output).hexdigest(),
              'contact_or_full_goal_acceptance': False}
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
