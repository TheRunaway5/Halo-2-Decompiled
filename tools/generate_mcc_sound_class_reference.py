#!/usr/bin/env python3
"""Generate the exact finite named-class authoring profile; no runtime references."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PIN = "21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd"
# Pins cover complete offline-audited typed operands and owning source contexts.
DELTA_PIN = "1f7c0e6d13cf98f6973fa922d71a8a4836202092f503022404a5dc0e53f9a123"
CONTEXT_PIN = "6c6086605542523bf9c269496ce82e8cf508edd23e8fdc44a7d7f6bf8d1f997d"


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


def generate(raw):
    data = json.loads(raw)
    if (data.get("schema") != "H2_MCC_NAMED_SOUND_CLASS_REFERENCE_V1" or
            data.get("original_xbe_sha256") != PIN or
            data.get("original_class_name_table") != 0x47C7A8 or
            (data.get("class_count"), data.get("source_stride"), data.get("native_stride")) != (54, 120, 92) or
            data.get("unsupported_class_indices") != [15, 16, 17, 39, 40, 41]):
        raise ValueError("Changed sound-class authority/layout/unsupported domains")
    deltas, contexts = data["deltas"], data["contexts"]
    if (len(deltas) != 48 or len({d["class_index"] for d in deltas}) != 25 or
            hashlib.sha256(canonical(deltas)).hexdigest() != DELTA_PIN):
        raise ValueError("Changed exact named-class typed word proof")
    if (len(contexts) != 39 or
            hashlib.sha256(canonical(contexts)).hexdigest() != CONTEXT_PIN or
            len({c["source_bank_sha256"] for c in contexts}) != 13 or
            sum(len(c["source_maps"]) for c in contexts) != 40):
        raise ValueError("Changed complete class-bank/namespace census")
    def sha(value):
        if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{64}", value):
            raise ValueError("Malformed source digest")
        return value
    for digest in data["evidence"].values():
        sha(digest)
    lines = ["// Generated by tools/generate_mcc_sound_class_reference.py; do not edit.",
             "// Evidence JSON SHA256: " + hashlib.sha256(raw).hexdigest(),
             "constexpr std::array<ClassContext,39> class_contexts{{"]
    for c in contexts:
        g, owner = c["globals"], c["legacy"]
        if (g["group"] != "matg" or g["name"] != r"globals\globals" or
                owner["group"] != "sncl" or owner["name"] != r"sound\sound_classes" or
                any(not re.fullmatch(r"[0-9a-f]{%d}" % n, c[k]) for k, n in
                    [("sound_block", 16), ("sound_globals", 88), ("class_root", 16)])):
            raise ValueError("Changed complete typed class route")
        values = [g["datum"], g["address"], g["size"], owner["datum"], owner["address"], owner["size"]]
        strings = [c["sound_block"], c["sound_globals"], c["class_root"], sha(c["source_bank_sha256"])]
        lines.append("    {" + ",".join(str(v) + "u" for v in values) + "," + ",".join(json.dumps(s) for s in strings) + "},")
    lines += ["}};", "constexpr std::array<MccSoundClassReferenceWord,48> class_words{{"]
    for d in deltas:
        lines.append("    {" + str(d["class_index"]) + "," + str(d["offset"]) +
                     ",MccSoundClassReferenceWordKind::" + d["kind"] + "," +
                     hex(d["before_bits"]) + "u," + hex(d["after_bits"]) + "u," +
                     json.dumps(d["name"]) + "," + json.dumps(d["field"]) + "},")
    return "\n".join(lines + ["}};", ""])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    p.add_argument("--data", type=Path, default=ROOT / "tools/data/mcc-sound-class-reference.json")
    p.add_argument("--output", type=Path, default=ROOT / "src/mcc_sound_class_reference.inc")
    a = p.parse_args()
    generated = generate(a.data.read_bytes())
    if a.check:
        if not a.output.is_file() or a.output.read_text() != generated:
            p.error("Generated named-class sound profile is stale")
    else:
        a.output.write_text(generated)


if __name__ == "__main__":
    main()
