#!/usr/bin/env python3
"""Extract the reviewed complete duration leaf without rebuilding its parent."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARENT = ROOT / "src/physics_live_support_tu15_generated.cpp"
OUTPUT = ROOT / "src/source_sound_duration_tu15.cpp"
PCS_OUTPUT = ROOT / "src/mcc_sound_duration_pcs.inc"
FUNCTIONS = (
    "long double native_fldl2e(",
    "long double native_sound_duration_divide(",
    "long double native_integer_multiply(",
    "long double native_f2xm1(",
    "long double native_fscale(",
    "long double native_frndint(",
    "std::uint32_t sign_extend(",
    "static void run_21f590(WorldState &s) {",
)


def function(source, signature):
    start = source.index(signature)
    opening = source.index("{", start)
    if ";" in source[start:opening]:
        raise ValueError("Duration extraction selected a declaration")
    depth = 1
    end = opening + 1
    while depth:
        if end == len(source):
            raise ValueError("Duration extraction has an incomplete function")
        depth += (source[end] == "{") - (source[end] == "}")
        end += 1
    return source[start:end]


def generate(source):
    blocks = [function(source, signature) for signature in FUNCTIONS]
    # This primary complete body was independently compared against TU1.5 CPU
    # execution, including all GPRs/flags, stack stores and x87 C1/status.
    if "native_sound_duration_divide" not in blocks[-1]:
        raise ValueError("Duration lowering lost its reviewed C1 division")
    if "MccSoundLayoutRequirement" not in blocks[-1]:
        raise ValueError("Duration lowering lost its codec-domain admission")
    digest = hashlib.sha256("\n\n".join(blocks).encode()).hexdigest()
    return (
        '// Generated by tools/generate_source_sound_duration_tu15.py.\n'
        '// Complete original211-byte body SHA256:\n'
        '// 6cab0fba83a56a36f6f934ef61eb96eb2105140cee8ac5c9039574ed918810f7\n'
        f'// Parent lowering and helpers SHA256: {digest}\n'
        '#include "physics_world_runtime_internal.hpp"\n'
        '#include "halo2/source_sound_duration_tu15.hpp"\n'
        '#include "halo2/mcc_sound_tag_layout.hpp"\n'
        'namespace halo2 {\nnamespace {\n'
        'using namespace physics_world_runtime_detail;\n'
        + "\n\n".join(blocks)
        + '\n} // namespace\n'
        'void source_run_sound_duration_tu15(SourcePhysicsContactMemory &memory,\n'
        '    SourcePhysicsWorldRuntimeAbi &abi,SourcePhysicsFactoryFloatingPoint fp,\n'
        '    const SourcePhysicsWorldRuntimeServices &services,\n'
        '    const SourcePhysicsContactRecordObserver &observe) {\n'
        '    FpScope scope(fp);\n'
        '    WorldState state{memory,observe,services,SourcePhysicsContactImage::TitleUpdate15};\n'
        '    state.load(abi);\n'
        '    try {run_21f590(state);}\n'
        '    catch(...) {abi=state.save();throw;}\n'
        '    abi=state.save();\n'
        '}\n} // namespace halo2\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = PARENT.read_text()
    result = generate(source)
    pcs = re.findall(r"s\.services\.instruction\((0x[0-9a-f]+u)\)",
                     function(source, FUNCTIONS[-1]))
    if len(pcs) != 67 or pcs[0] != "0x21f590u" or pcs[-1] != "0x21f660u":
        parser.error("The complete duration leaf lost its reviewed instruction sequence")
    pc_result = ",".join(pcs) + "\n"
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != result:
            parser.error("The standalone duration leaf differs from its parent lowering")
        if not PCS_OUTPUT.is_file() or PCS_OUTPUT.read_text() != pc_result:
            parser.error("The MCC read adapter differs from the complete duration instruction sequence")
    else:
        OUTPUT.write_text(result)
        PCS_OUTPUT.write_text(pc_result)


if __name__ == "__main__":
    main()
