#!/usr/bin/env python3
"""Compile source-proved sky parameter layouts; never shader instructions."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

ROOT=Path(__file__).resolve().parents[1]
FIELDS=((0,10),(8,2),(16,10),(24,6),(32,4))
RULES=(('sky_two_alpha_clouds',0,'23902019b2a97af100e570f8b40f00c6f84c2653128541c74a76ba9f8ee1660c.bin'),
       ('sky_two_alpha_clouds',10,'23902019b2a97af100e570f8b40f00c6f84c2653128541c74a76ba9f8ee1660c.bin'),
       ('sky_one_alpha_env',0,'cb5f8eea52c18c5b67cf8301dfd1381294086dc9b456db5ab1e3352d87bd038a.bin'),
       ('sky_one_alpha_env_illum',0,'1b33a662e7079a10e3d0455ca8e4efb6f18051474af3a6bc9111b01e43ab9bc6.bin'))


def canonical(value):
    return json.dumps(value,sort_keys=True,separators=(',',':'),ensure_ascii=False).encode()


def generate(raw):
    value=json.loads(raw)
    if value['schema']!='H2_MCC_NATIVE_SKY_COOKED_PROFILES_V1' or len(value['profiles'])!=len(RULES):
        raise ValueError('Changed qualified sky profile census')
    proof=value['curve_reference']
    original=(ROOT/'tests/fixtures/workshop_sky_curves_tu15.tsv').read_bytes()
    if (proof['xbe_sha256']!='21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd' or
            proof['cases']!=432 or hashlib.sha256(original).hexdigest()!=proof['fixture_sha256']):
        raise ValueError('Sky curves lost their unchanged original execution reference')
    projected=[]
    for profile,(family,overlays,payload) in zip(value['profiles'],RULES):
        name='shaders\\shader_templates\\transparent\\'+family
        if (profile['template']!=name or profile['native_record']['payload']!=payload or
                profile['native_record']['group']!='stem' or profile['native_record']['name']!=name or
                profile['source_counts']['60']!=overlays or len(profile['clock_overlays'])!=overlays or
                not profile['paired_proof']['complete_main_banks'] or not profile['paired_proof']['complete_roles_and_curves'] or
                not profile['paired_proof']['native_template_pair']['complete_postprocess_equal'] or
                profile['paired_proof']['native_template_pair']['admitted_payload']!=payload):
            raise ValueError('Unreviewed original sky layout or source owner')
        expected='copy' if family=='sky_two_alpha_clouds' else 'swap_environment_pixels'
        if profile['mapping']!=expected:
            raise ValueError('Unproved sky pixel ordering')
        graph=profile['source_graph']
        if (hashlib.sha256(canonical(graph)).hexdigest()!=profile['source_graph_sha256'] or
                len(bytes.fromhex(graph['root_hex']))!=96 or len(graph['definitions'])!=3):
            raise ValueError('Changed complete MCC sky compiler graph')
        for definition in graph['definitions']:
            if len(bytes.fromhex(definition['definition_hex']))!=40 or len(definition['arrays'])!=5:
                raise ValueError('Changed complete sky platform definition')
            for array,(field,stride) in zip(definition['arrays'],FIELDS):
                if (array['field']!=field or not 0<=array['count']<=65536 or
                        len(bytes.fromhex(array['raw_hex']))!=array['count']*stride or
                        len(array['typed_references'])!=(array['count'] if field==16 else 0) or
                        any(len(ref)!=2 or ref[0]!='spas' for ref in array['typed_references'])):
                    raise ValueError('Changed complete typed sky template remap')
        for overlay in profile['clock_overlays']:
            curves=overlay.get('curve_hex_variants',[overlay['curve_hex']])
            if (overlay['input'] or overlay['range'] or overlay['curve_hex'] not in curves or
                    not 1<=len(curves)<=2 or any(not 20<=len(bytes.fromhex(x))<=4096 for x in curves)):
                raise ValueError('Unreviewed sky curve data or input owner')
            for word in overlay['period_words']:
                period=struct.unpack('<f',struct.pack('<I',word))[0]
                if not math.isfinite(period) or period<=0:
                    raise ValueError('Unreviewed sky animation period')
        for field,stride in ((28,6),(36,2),(44,2),(52,10),(68,4),(76,2),(84,4),(92,4)):
            if len(bytes.fromhex(profile['native_role_banks'][str(field)]))!=profile['source_counts'][str(field)]*stride:
                raise ValueError('Changed complete native sky animation roles')
        projected.append({key:profile[key] for key in ('template','source_graph','source_counts','shader_type_flags',
            'runtime_diffuse_slot','native_shape','clock_overlays','native_role_banks','mapping')})
        projected[-1]['native_record']={key:profile['native_record'][key] for key in ('payload','bytes','fnv64')}
    data=canonical(dict(schema=value['schema'],profiles=projected)).decode()
    return ('// Generated by tools/generate_mcc_native_sky_profiles.py; do not edit.\n'
            '// Paired source data SHA256: '+hashlib.sha256(raw).hexdigest()+'\n'
            'constexpr std::string_view native_sky_cooked_profiles=R"H2SKYDATA('+data+')H2SKYDATA";\n')


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    text=generate((ROOT/'tools/data/mcc-native-sky-cooked-profiles.json').read_bytes())
    output=ROOT/'src/rendering/mcc_native_sky_cooked_profiles.inc'
    if a.check:
        if not output.is_file() or output.read_text()!=text:raise ValueError('Stale native sky parameter registry')
    else:output.write_text(text)


if __name__=='__main__':main()
