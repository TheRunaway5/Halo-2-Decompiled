#!/usr/bin/env python3
"""Export the original four registered game-engine method-record prefixes.

Each prefix stops after51 aligned original code targets, before independently
registered next owners/padding or the final UTF16 string. No C++ class layout,
callback implementation, mutable state or successful dispatch is inferred.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe
from functions import _Code
PIN='21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--fixture',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();image=Xbe(args.reference)
    assert hashlib.sha256(image.data).hexdigest()==PIN
    code=_Code(image,'.text');readonly=image.section('.rdata');assert not readonly.flags&1
    roots=struct.unpack('<4I',image.read(0x48c498,16));assert roots==(0x468be8,0x468cb8,0x468d88,0x468e58)
    assert code.at(0x15a1b8).bytes.hex()=='ff5268'
    rows=[]
    for index,base in enumerate(roots):
        raw=image.read(base,51*4);words=struct.unpack('<51I',raw)
        assert readonly.va<=base<base+len(raw)<=readonly.va+readonly.vsize
        assert all(value%16==0 and code.inside(value)and code.at(value)for value in words)
        if index<3:
            assert roots[index+1]==base+52*4 and image.read(base+51*4,4)==bytes(4)
            end='one original zero padding word before the next registered owner'
        else:
            assert image.read(base+51*4,len('#territory_name\0')*2).decode('utf-16le')=='#territory_name\0'
            end='original UTF16 #territory_name string begins immediately after this prefix'
        rows.append(dict(base=base,words=words,bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest(),terminal=end))
    lines=['// Generated by tools/export_native_tu15_game_engine_methods.py.',
        '// English TU1.5 reference SHA256: '+PIN,
        '// Exact51-method prefixes only; padding/string bytes stay outside.',
        'constexpr std::array game_engine_method_records{']
    for row in rows:
        lines.append(f'    std::pair{{0x{row["base"]:x}u,std::array<std::uint32_t,51>{{')
        for offset in range(0,51,8):
            lines.append('        '+','.join(f'0x{v:x}u'for v in row['words'][offset:offset+8])+(','if offset+8<51 else''))
        lines.append('    }}'+(','if row is not rows[-1] else''))
    lines+=['};','for(const auto &[base,methods]:game_engine_method_records)',
        '    for(unsigned slot=0;slot<methods.size();++slot)',
        '        share_immutable_word(memory,base+slot*4u,methods[slot],',
        '            "native TU1.5 authored registered game-engine method record");']
    args.output.write_text('\n'.join(lines)+'\n')
    fixture=['// Original bytes independently read from the authenticated TU1.5 image.',
        '// Reference SHA256: '+PIN,
        'struct OriginalGameEngineMethods {std::uint32_t base;std::array<std::byte,204> bytes;};',
        'constexpr std::array original_game_engine_methods{']
    for row in rows:
        raw=image.read(row['base'],204);fixture.append(f'    OriginalGameEngineMethods{{0x{row["base"]:x}u,{{')
        for offset in range(0,len(raw),16):
            fixture.append('        '+','.join(f'std::byte{{0x{v:02x}}}'for v in raw[offset:offset+16])+(','if offset+16<len(raw)else''))
        fixture.append('    }}'+(','if row is not rows[-1]else''))
    fixture.append('};');args.fixture.write_text('\n'.join(fixture)+'\n')
    report=dict(passed=True,reference_sha256=PIN,registry='0x48c498',records=rows,total_bytes=sum(r['bytes']for r in rows),output_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),fixture_sha256=hashlib.sha256(args.fixture.read_bytes()).hexdigest(),scope=__doc__)
    args.report.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items()if k not in('records','scope')}))

if __name__=='__main__':main()
