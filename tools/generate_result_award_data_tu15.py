#!/usr/bin/env python3
"""Declare exact TU1.5 weapon, PvP and award result metadata and names."""
import argparse,hashlib,json,os,struct
from pathlib import Path
from oracle_smg_firing_1_1 import Xbe
from research_mp_sandbox_update_functions import NEW_DEFAULT,NEW_PIN

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,required=True);p.add_argument('--report',type=Path,required=True)
    a=p.parse_args();scratch=Path(os.environ['HALO2_TEST_SCRATCH']).resolve()
    if not a.output.resolve().is_relative_to(scratch):raise ValueError('Generate only in owned scratch')
    image=Xbe(NEW_DEFAULT);assert hashlib.sha256(image.data).hexdigest()==NEW_PIN
    # Actual19C780 supplies this exact32-row,16-byte metadata owner to19BF90.
    assert image.read(0x19cadd,7)==bytes.fromhex('68e0a647006a20')
    assert image.read(0x19cb5d,7)==bytes.fromhex('6850a647006a07')
    assert image.read(0x19cc1d,7)==bytes.fromhex('68c0a647006a02')
    assert image.read(0x19babf,7)==bytes.fromhex('0fb790e8a64700')
    specifications=((0x47a650,7,'weapon'),(0x47a6c0,2,'player-versus-player'),(0x47a6e0,32,'award'))
    regions=[(p,image.read(p,n*16),True,'original%d-row retained %s descriptors'%(n,name))for p,n,name in specifications]
    seen=set()
    for address in [struct.unpack_from('<I',image.read(p,n*16),index*16)[0]
                    for p,n,_ in specifications for index in range(n)]:
        assert address
        if address in seen:continue
        seen.add(address);name=bytearray()
        for offset in range(256):
            b=image.read(address+offset,1);name+=b
            if b==b'\0':break
        else:raise ValueError('Original award name lacks a bounded terminator')
        regions.append((address,bytes(name),False,'original retained award name '+name[:-1].decode('ascii')))
    lines=['// Generated by tools/generate_result_award_data_tu15.py.',
           '// Original TU1.5 SHA-256 '+NEW_PIN+'.',
           '// Authored metadata only;19BAA0 and the actual result owners update live counters.']
    for address,data,writable,owner in regions:
        lines.append('memory.mount(0x%xu,std::array<std::byte,%d>{'%(address,len(data)))
        for offset in range(0,len(data),12):
            lines.append('    '+','.join('std::byte{0x%02x}'%b for b in data[offset:offset+12])+',')
        lines.append('},SourceRuntimeMemory::Access::'+('ReadWrite'if writable else'ReadOnly')+',')
        lines.append('    "native TU1.5 '+owner+'");')
    a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(lines)+'\n')
    a.report.parent.mkdir(parents=True,exist_ok=True);a.report.write_text(json.dumps(dict(
        original_sha256=NEW_PIN,generated_sha256=hashlib.sha256(a.output.read_bytes()).hexdigest(),
        generator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),scratch=str(scratch),
        regions=[dict(address=hex(p),size=len(b),writable=w,sha256=hashlib.sha256(b).hexdigest(),owner=n)
                 for p,b,w,n in regions],instruction_patches=[],supplied_returns=[]),indent=2)+'\n')
    print('Original result award metadata:',len(regions),'regions,',sum(len(b)for _,b,_,_ in regions),'bytes')
if __name__=='__main__':main()
