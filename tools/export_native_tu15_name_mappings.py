#!/usr/bin/env python3
"""Export the exact reference-only233CF1 table/string instruction operands.

The compiled runtime consumes only the generated bounded data, never this XBE.
This exports no image section, synthesized callback or gameplay result.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe

PIN = '21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd'


def export(reference, output, report):
    scratch = Path(os.environ['HALO2_TEST_SCRATCH']).resolve(strict=True)
    for path in (output, report):
        if not path.resolve().is_relative_to(scratch):
            raise ValueError('Generated outputs must remain in HALO2_TEST_SCRATCH')
    image = Xbe(reference)
    if hashlib.sha256(image.data).hexdigest() != PIN:
        raise ValueError('Requires the exact authenticated reference TU1.5 image')

    def read(address, size):
        section = next((s for s in image.sections
                        if s.va <= address < address + size <= s.va + s.rsize), None)
        if section is None:
            raise ValueError('Name operand is not wholly original file-backed data')
        return image.read(address, size), section

    tokens, _ = read(0x455e48, 18 * 8)
    glyphs, _ = read(0x47c91c, 131 * 12)
    token_rows, intervals = [], []
    for n in range(18):
        pointer, glyph_word = struct.unpack_from('<II', tokens, n * 8)
        for count in range(256):
            word, _ = read(pointer + count * 2, 2)
            if word == b'\0\0':
                break
        else:
            raise ValueError('Original token lacks its bounded UTF16 terminator')
        if not count:
            raise ValueError('Original token is empty')
        intervals.append((pointer, pointer + (count + 1) * 2))
        token_rows.append({'index': n, 'pointer': pointer, 'glyph_word': glyph_word,
                           'utf16_units': count, 'record8_hex': tokens[n * 8:n * 8 + 8].hex()})
    # Preserve genuine pointer aliases/suffixes by exporting the exact union.
    # Adjacent strings can share one data owner; no gap or extra byte is read.
    strings = []
    for start, end in sorted(set(intervals)):
        if strings and start <= strings[-1][1]:
            strings[-1] = (strings[-1][0], max(end, strings[-1][1]))
        else:
            strings.append((start, end))
    ranges = [(0x455e48, len(tokens)), (0x47c91c, len(glyphs))]
    ranges += [(start, end - start) for start, end in strings]
    if sum(size for _, size in ranges) > 16384:
        raise ValueError('Unexpectedly large name operand closure')
    for i, (start, size) in enumerate(ranges):
        if any(start < other + length and other < start + size
               for other, length in ranges[:i]):
            raise ValueError('Unexpected table/string overlap')

    lines = ['// Generated by tools/export_native_tu15_name_mappings.py.',
             '// Reference-only SHA-256: ' + PIN]
    rows = []
    for n, (address, size) in enumerate(ranges):
        raw, section = read(address, size)
        rows.append({'address': address, 'bytes': size, 'read_only': not bool(section.flags & 1),
                     'section': section.name, 'section_flags': section.flags,
                     'sha256': hashlib.sha256(raw).hexdigest(), 'raw_hex': raw.hex()})
        lines.append(f'constexpr std::array<std::byte,{size}> native_name_data_{n}{{')
        for offset in range(0, size, 16):
            lines.append('    ' + ','.join(f'std::byte{{0x{v:02x}}}' for v in raw[offset:offset + 16]) + ',')
        lines.append('};')
    lines += ['struct NativeTu15NameMappingRegion {',
              '    std::uint32_t address; bool read_only; std::span<const std::byte> bytes;',
              '};', 'constexpr std::array native_name_mapping_regions{']
    for n, row in enumerate(rows):
        lines.append(f'    NativeTu15NameMappingRegion{{0x{row["address"]:x}u,{str(row["read_only"]).lower()},native_name_data_{n}}},')
    lines.append('};')
    output.write_text('\n'.join(lines) + '\n')
    evidence = {'schema': 'native-tu15-name-mapping-data-v1', 'reference_sha256': PIN,
                'exporter_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                'reader_sha256': hashlib.sha256((ROOT / 'tools/reference/halo2-decompiled/tools/xbe.py').read_bytes()).hexdigest(),
                'output_sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
                'regions': rows, 'tokens': token_rows, 'total_bytes': sum(r['bytes'] for r in rows),
                'consumers': ['233D51/233D57 token pointer', '233D72 token glyph16',
                              '233D39/233E31 glyph key/callback', '32A970 original UTF16 length'],
                'limits': 'Static operand data only; no dynamic private glyph callback or live profile/menu qualification',
                'runtime_reference_dependency': False, 'supplied_gameplay_results': []}
    report.write_text(json.dumps(evidence, indent=2) + '\n')
    print(json.dumps({'regions': len(rows), 'bytes': evidence['total_bytes'],
                      'section_access': sorted(set((r['section'], r['section_flags'], r['read_only']) for r in rows))}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    export(args.reference, args.output, args.report)
