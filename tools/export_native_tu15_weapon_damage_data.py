#!/usr/bin/env python3
"""Export the immutable original damage-response table reached by rocket impacts.

Run through tools/run_test.py. The XBE is an offline reference, never runtime
code or a supplied gameplay result.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct
from oracle_smg_firing_1_1 import Xbe, _Code
from research_mp_sandbox_update_functions import NEW_DEFAULT, NEW_PIN


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    assert os.environ.get('HALO2_TEST_SCRATCH'), 'Use tools/run_test.py'
    assert hashlib.sha256(NEW_DEFAULT.read_bytes()).hexdigest() == NEW_PIN
    image = Xbe(NEW_DEFAULT)
    code = _Code(image, '.text')
    instruction = code.at(0xdcb75)
    assert bytes(instruction.bytes).hex() == 'ff248d98cd0d00'
    address, size = 0xdcd98, 20
    section = next(s for s in image.sections
                   if s.va <= address and address + size <= s.va + s.vsize)
    assert not section.flags & 1
    raw = image.read(address, size)
    targets = struct.unpack('<5I', raw)
    assert targets == (0xdcbea, 0xdcbd1, 0xdcba5, 0xdcd81, 0xdcbbb)
    assert image.read(address + size, 4) == b'\xcc' * 4
    for target in targets:
        assert code.at(target).address == target
    text = ('// Generated by tools/export_native_tu15_weapon_damage_data.py.\n'
            '// English TU1.5 SHA256: ' + NEW_PIN + '\n'
            'constexpr std::array<std::byte,20> weapon_damage_response{\n    ' +
            ','.join(f'std::byte{{0x{value:02x}}}' for value in raw) + '\n};\n'
            'constexpr std::array weapon_damage_tables{\n'
            '    BranchTable{0xdcd98u,weapon_damage_response}\n};\n')
    args.output.write_text(text)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(dict(passed=True, reference_sha256=NEW_PIN,
        instruction_address=instruction.address, instruction_hex=bytes(instruction.bytes).hex(),
        table_address=address, table_hex=raw.hex(), targets=targets,
        output_sha256=hashlib.sha256(text.encode()).hexdigest(),
        generated_data_is_immutable=True, game_results_supplied=False), indent=2) + '\n')


if __name__ == '__main__':
    main()
