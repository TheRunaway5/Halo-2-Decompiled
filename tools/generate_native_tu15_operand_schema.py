#!/usr/bin/env python3
"""Describe all named immutable operand fields from the actual C++ declarations.

Development/reference tooling only. MCC onboarding does not need Clang or an
Xbox executable. A changed declaration must update this schema explicitly.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import subprocess
import tempfile


def schema(root, compiler):
    with tempfile.TemporaryDirectory(prefix="halo2-operand-schema-") as temporary:
        unit = Path(temporary) / "operands.cpp"
        unit.write_text('#include "halo2/original_data.hpp"\n#include "halo2/full_scoreboard_paint_constants.hpp"\n')
        result = subprocess.run([compiler, "-std=c++20", "-I" + str(root / "include"),
            "-Xclang", "-ast-dump=json", "-Xclang", "-ast-dump-filter=halo2", "-fsyntax-only", str(unit)],
            check=True, capture_output=True, text=True)
    records = {}
    def walk(node, prefix="halo2"):
        if node.get("kind") in ("CXXRecordDecl", "RecordDecl") and node.get("completeDefinition"):
            name = node.get("name")
            full = prefix + "::" + name if name else prefix
            fields = [(child["name"], child["type"].get("desugaredQualType", child["type"]["qualType"]))
                      for child in node.get("inner", []) if child.get("kind") == "FieldDecl"]
            if name and fields:
                records[full] = fields
            prefix = full
        for child in node.get("inner", []):
            walk(child, prefix)
    decoder, offset = json.JSONDecoder(), 0
    while offset < len(result.stdout):
        while offset < len(result.stdout) and result.stdout[offset].isspace():
            offset += 1
        if offset == len(result.stdout):
            break
        node, offset = decoder.raw_decode(result.stdout, offset)
        walk(node)
    names = defaultdict(list)
    for name in records:
        names[name.rsplit("::", 1)[-1]].append(name)
    seen, queue = {"halo2::OriginalData"}, ["halo2::OriginalData"]
    while queue:
        name = queue.pop()
        for field, kind in records[name]:
            if name == "halo2::OriginalData" and field == "source":
                continue
            for word in re.findall(r"[A-Za-z_][A-Za-z_0-9]*", kind):
                if word not in names:
                    continue
                if len(names[word]) != 1:
                    raise ValueError("Ambiguous operand record: " + word)
                target = names[word][0]
                if target not in seen:
                    seen.add(target)
                    queue.append(target)
    return {name: records[name] for name in sorted(seen)}


def render(records):
    rows = ["// Generated by tools/generate_native_tu15_operand_schema.py.",
            "// Named typed fields only; no object padding, host pointers or executable sections."]
    for name, fields in records.items():
        rows.append("H2_OPERAND_RECORD(" + name + ",")
        rows.extend("  H2_OPERAND_FIELD(" + field + ")" for field, _ in fields
                    if (name, field) != ("halo2::OriginalData", "source"))
        rows.append(")")
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--compiler", default="clang++")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = args.root / "tools/native_tu15_operand_fields.inc"
    output = render(schema(args.root, args.compiler))
    if args.check:
        if target.read_text() != output:
            raise ValueError("Native TU1.5 operand declarations changed; regenerate the complete named-field schema")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(output)


if __name__ == "__main__":
    main()
