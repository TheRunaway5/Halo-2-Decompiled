def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()

def digest(raw):
    return hashlib.sha256(raw).hexdigest()

def u32(raw, at):
    return struct.unpack_from("<I", raw, at)[0]

def put(raw, at, word):
    struct.pack_into("<I", raw, at, word)

def require(value, message):
    if not value:
        raise ValueError("Shared character source: " + message)

def tag_json(tag):
    return {key: tag[key] for key in ("group", "name", "datum", "address", "size")}

def resolve_shared_source(cache, supplied=None):
    if supplied is not None:
        return Path(supplied)
    cache = Path(cache)
    provenance = cache / "provenance.json"
    if provenance.is_file():
        original = json.loads(provenance.read_bytes()).get("source")
        require(isinstance(original, str) and Path(original).is_absolute(),
                "prepared cache requires its declared original MCC source directory")
        return Path(original) / "h2_maps_win64_dx11/shared.map"
    return cache / "halo2/h2_maps_win64_dx11/shared.map"

def authenticated_shared_source(cache, supplied=None):
    shared = resolve_shared_source(cache, supplied)
    require(digest(shared.read_bytes()) == SOURCE_SHARED, "complete actual shared source changed")
    return shared

def named_vectors(name, stem_name, raw):
    contract = SEMANTIC_VECTOR_MATERIALS[name]
    require(contract['template'] == stem_name, 'named vector plan lost its exact template')
    output = []
    for row in contract['rows']:
        require(row['native'] == len(output), 'named vector plan is not complete and ordered')
        if row['kind'] == 'source':
            start = row['source']*16
            require(start+16 <= len(raw), 'named source vector is absent')
            words = [0 if lane is None else u32(raw,start+lane*4) for lane in row['lanes']]
        else:
            require(row['kind'] in ('pass_parameter_default','template_bitmap_default'), 'unknown named vector operation')
            if row['kind'] == 'pass_parameter_default':
                require(row['source_extern'] == 0, 'named default became an unresolved external')
            words = row['words']
        require(len(words) == 4, 'incomplete named vector lanes')
        output.append(struct.pack('<4I',*words))
    return b''.join(output)

def named_pixels(name,pixels,vectors):
    output = []
    for row in SEMANTIC_PIXEL_MATERIALS[name]:
        require(row['native'] == len(output), 'named pixel plan is not complete and ordered')
        kind = row['kind']
        if kind in ('pixel','existing_exact_source_pixel'):
            start = row['source']*4
            require(start+4 <= len(pixels), 'named source pixel is absent')
            value = pixels[start:start+4]
        elif kind == 'vector':
            start = row['source']*16
            require(start+16 <= len(vectors), 'named pixel source vector is absent')
            value = pack_vector(vectors[start:start+16],row['component'])
        else:
            require(kind == 'absent_parameter_default' and row['declared_source_extern'] == 0,
                    'unknown or external named pixel default')
            value = pack_vector(struct.pack('<4f',*row['RGB'],0.),row['component'])
        output.append(value)
    return b''.join(output)

