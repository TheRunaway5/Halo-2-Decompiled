"""Emit the sealed, completely paired alpha-environment metadata contract."""
import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PROFILE_SHA256 = 'b2ef79928eabc931992d28f3a049dc9a83c2d15bcf2b5858703208a7065ca482'


def need(ok, why):
    if not ok:
        raise ValueError('Native alpha-environment metadata: ' + why)


def generate(raw):
    need(hashlib.sha256(raw).hexdigest() == PROFILE_SHA256, 'complete sealed projection profile changed')
    profile = json.loads(raw)
    need(profile['schema'] == 'H2_MCC_NATIVE_ALPHA_ENVIRONMENT_PROFILES_V1' and
         profile['template'] == r'shaders\shader_templates\opaque\tex_bump_env_alpha_test' and
         [x['source'] for x in profile['roles']['vector_sources']] == [2, 0, 1, 3, 0, 4, 5, 6, 7] and
         profile['roles']['vector_sources'][3]['lanes'] == [None, None, 0, 1] and
         profile['roles']['vector_sources'][1]['lanes'] == [0, 1, None, None] and
         profile['authority']['materials'] == 88 and profile['authority']['paired_controls'] == 68,
         'complete paired authority contract differs')
    need(len(profile['native_records']) == 38 and len(profile['source_graph']['definitions']) == 3,
         'complete original variants or source platform definitions differ')
    data = {key: profile[key] for key in ('template', 'source_graph', 'native_arrays', 'native_records', 'roles')}
    text = json.dumps(data, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
    need(')H2ALPHAENV"' not in text, 'metadata escaped its generated literal')
    return ('// Generated by tools/generate_mcc_native_alpha_environment.py; do not edit.\n'
            '// Complete paired metadata SHA256: ' + PROFILE_SHA256 + '\n'
            'constexpr std::string_view native_alpha_environment_profile=R"H2ALPHAENV(' + text + ')H2ALPHAENV";\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate((ROOT / 'tools/data/mcc-native-alpha-environment-profiles.json').read_bytes())
    target = ROOT / 'src/rendering/mcc_native_alpha_environment_profiles.inc'
    if args.check:
        need(target.is_file() and target.read_text() == text, 'stale generated source')
    else:
        target.write_text(text)


if __name__ == '__main__':
    main()
