#!/usr/bin/env python3
"""Export the finite authenticated TU1.5 opaque closure for PC map admission.

This imports no material instances. Existing complete cooked-tuple projectors
still admit each MCC shader independently. Programs and assets remain read-only.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = '01b_spacestation'
SOURCE_CANONICAL = 'db415f7973f0cc7a966148db98fd2837c8dfd3c4c320e534eec00ae7e11beb41'
FAMILIES = ('tex_bump', 'tex_bump_active_camo', 'tex_bump_dprs_env',
            'tex_bump_env', 'tex_bump_env_no_detail', 'tex_bump_illum_bloom')


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode()


def generate(cache):
    source = cache / 'native-shaders' / SOURCE
    library = json.loads((source / 'library.json').read_bytes())
    if hashlib.sha256(canonical(library)).hexdigest() != SOURCE_CANONICAL:
        raise ValueError('World closure source is not the complete audited TU1.5 library')
    records = {(r['group'], r['name']): r for r in library['shader_tags']}
    if len(records) != len(library['shader_tags']):
        raise ValueError('Ambiguous original world source identities')
    roots = [('stem', 'shaders\\shader_templates\\opaque\\' + name) for name in FAMILIES]
    pending, wanted = list(roots), set()
    while pending:
        key = pending.pop()
        if key in wanted:
            continue
        if key[0] not in ('stem', 'spas', 'vrtx') or key not in records:
            raise ValueError('World program dependency escapes the finite original namespace')
        wanted.add(key)
        record = records[key]
        if record['strings']:
            raise ValueError('PC world closure may not alter its StringID bank')
        payload = (source / 'payloads' / record['payload']).read_bytes()
        if (len(payload) != record['bytes'] or
                hashlib.sha256(payload).hexdigest() + '.bin' != record['payload']):
            raise ValueError('Changed complete original world payload')
        for _, target in record['references']:
            if target[0] not in ('stem', 'spas', 'vrtx'):
                raise ValueError('World template closure unexpectedly requires a material or image')
            pending.append(tuple(target))
    if len(wanted) != 52:
        raise ValueError('Changed finite six-template world closure')
    hud = json.loads((ROOT / 'tools/data/mcc-native-hud-bootstrap.json').read_bytes())
    sky = json.loads((ROOT / 'tools/data/mcc-native-pc-sky-closure.json').read_bytes())
    maps = []
    for row in sky['maps']:
        base = {'schema': 'H2_PRESERVED_NATIVE_SHADERS_V1', 'map': row['map'],
                'shader_tags': hud['records'] + row['records']}
        if any(tuple((r['group'], r['name'])) in wanted for r in base['shader_tags']):
            raise ValueError('World programs would replace an authenticated HUD/sky identity')
        maps.append({'map': row['map'], 'bytes': row['bytes'], 'sha256': row['sha256'],
                     'bootstrap_canonical_sha256': hashlib.sha256(canonical(base)).hexdigest()})
    return {'schema': 'H2_MCC_NATIVE_PC_WORLD_CLOSURE_V1', 'source_map': SOURCE,
            'source_canonical_sha256': SOURCE_CANONICAL, 'roots': roots, 'maps': maps,
            'records': [records[key] for key in sorted(wanted)],
            'scope': 'Six existing strict opaque cooked profiles; no instance aliases or PC shader interpretation'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    policy = generate(args.cache)
    data = json.dumps(policy, indent=2) + '\n'
    generated = ('// Generated by tools/generate_mcc_native_pc_world_closure.py; do not edit.\n'
                 '// Data SHA256: ' + hashlib.sha256(data.encode()).hexdigest() + '\n'
                 'constexpr std::string_view native_pc_world_closure_policy=R"H2PCWORLD('
                 + canonical(policy).decode() + ')H2PCWORLD";\n')
    outputs = {ROOT / 'tools/data/mcc-native-pc-world-closure.json': data,
               ROOT / 'src/runtime/mcc_native_pc_world_closure.inc': generated}
    for path, value in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text() != value:
                raise ValueError('Stale PC world closure: ' + str(path))
        else:
            path.write_text(value)
    print('Authenticated PC world closure: 6 templates, 52 complete original records')


if __name__ == '__main__':
    main()
