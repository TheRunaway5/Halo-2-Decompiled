#!/usr/bin/env python3
"""Render the finite, offline-reference-authenticated stored-sphere profile."""
from pathlib import Path
import argparse,json,sys
root=Path(__file__).resolve().parents[1]
def render(data):
    fields=data['fields'];assert len(fields)==49
    assert len({f['instance'] for f in fields})==35
    assert len({f['definition'] for f in fields})==12
    assert len({(f['instance'],f['component']) for f in fields})==49
    assert fields==sorted(fields,key=lambda f:(f['instance'],f['component']))
    assert all(0<=f['instance']<243 and 0<=f['definition']<43 and 0<=f['component']<4 and f['before']!=f['after'] for f in fields)
    assert sum(sum(a!=b for a,b in zip(f['before'].to_bytes(4,'little'),f['after'].to_bytes(4,'little')))for f in fields)==51
    p=data['owner'];lines=['// Generated by tools/generate_mcc_bsp_instance_bounds.py; do not edit.',
       f'constexpr std::uint32_t owner_datum=0x{p["datum"]:08x}u, owner_address=0x{p["address"]:08x}u, owner_bytes={p["size"]};',
       f'constexpr std::string_view owner_name={json.dumps(p["name"])};',
       f'constexpr auto root_sha=hex_digest("{data["root_sha256"]}");',
       f'constexpr auto definitions_sha=hex_digest("{data["definition_bank_sha256"]}");',
       f'constexpr auto instance_pre_sha=hex_digest("{data["instance_preimage_sha256"]}");',
       f'constexpr auto instance_post_sha=hex_digest("{data["instance_postimage_sha256"]}");']
    for key,label in [('instance0_transform_before','transform_before'),('instance0_transform_after','transform_after')]:
        assert len(data[key])==13
        lines.append(f'constexpr std::array<std::uint32_t,13> {label}{{'+','.join(f'0x{x:08x}u'for x in data[key])+'};')
    lines+=['struct Scalar {std::uint16_t instance,definition;std::uint8_t component;std::uint32_t before,after;};','constexpr std::array<Scalar,49> scalars{{']
    lines += [f'    {{{f["instance"]},{f["definition"]},{f["component"]},0x{f["before"]:08x}u,0x{f["after"]:08x}u}},' for f in fields]
    lines+=['}};','']
    return '\n'.join(lines)
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    src=root/'tools/mcc-bsp-instance-bounds-profile.json';target=root/'src/mcc_bsp_instance_bounds_profile.inc';expected=render(json.loads(src.read_text()))
    if args.check:
        if not target.exists()or target.read_text()!=expected:sys.exit('Stored BSP sphere profile is stale')
        print('Stored BSP sphere profile is current: 49 words / 35 spheres')
    else:target.write_text(expected)
if __name__=='__main__':main()
