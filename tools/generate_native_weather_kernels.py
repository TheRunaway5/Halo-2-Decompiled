#!/usr/bin/env python3
"""Offline finite weather/shadow-filter kernel lowering; no runtime compiler.

The production includes are checked in. --output writes only small generated
source files; probes/builds use the repository test-storage owner.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from native_world_vertex_kernel import lower_vertex_program
from native_world_fragment_kernel import lower_combiner_program

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'include/halo2/native_weather_vertex.hpp'
DESTINATION = ROOT / 'shaders/native-programs/weather'


def program(name):
    text = HEADER.read_text()
    match = re.search(r'\b' + name + r'_program\{([^}]+)\}', text, re.S)
    if not match:
        raise ValueError('Missing complete literal weather source program')
    words = [int(value.strip(), 0) for value in match[1].split(',')]
    count = words[0] >> 16
    if words[0] & 65535 != 0x2078 or len(words) != count * 4 + 1:
        raise ValueError('Malformed complete weather program')
    return words


def plate_controls(power, alpha):
    w = [0] * 60
    w[1:4] = [0x04209140, 0x18201140, 0xdd202df1]
    w[27:30] = [0xc00, 0xd00, 0xd00]
    w[34:38] = [0x08010802, 0x04201140, 0x2020, 0xcc202d20]
    w[45:49] = [0x3045, 0xc00, 0x4d00, 0xc00]
    w[53:55] = [0x11108, 0x8421]
    w[38], w[49] = (0x19011a02 if alpha else 0x09010a02), 0x3045
    w[4] = 0x1d201d00 | (0x20 if power > 3 else 0)
    w[30] = 0xd00 | ((0x20 if power > 2 else 0x10 if power > 1 else 0) << 12)
    w[39], w[50] = (0x24251b01 if alpha else 0x24250b01), 0x1045
    w[5] = 0x1d201d00 | (0x20 if power > 6 else 0)
    w[31] = 0xd00 | ((0x20 if power > 5 else 0x10 if power > 4 else 0) << 12)
    w[40], w[51] = 0x04250000, 0xd0
    w[6:10] = [0x1d120c02, 0x1d2d0000, 0x1d010000, 0x1d00]
    w[32], w[33] = 0xd00 | ((0x10 if power > 0 else 0) << 12), 0xd0
    return w


def point_pixel(rain=False):
    w = [0] * 60
    w[0] = 0xd4301010 if rain else 0xd4db1010
    w[8], w[9], w[26] = 0x0c200000, 0x1c80, 0xc0
    w[34], w[45] = (0xc4200000 if rain else 0xc4cb0000), 0xc0
    w[53], w[54] = 0x11101, 0 if rain else 0x8000
    w[57:60] = [0xffffffff, 0xffffffff, 0x1ff]
    return w


def shadow_filter_pixel():
    w = [0] * 60
    w[0:3] = [0x18201920, 0x1a201b20, 0x1c201d20]
    w[8:10] = [0xc, 0x1c00]
    w[26:29] = w[45:48] = [0x30c00, 0x30d00, 0x30c00]
    w[34:37] = [0x08200920, 0x0a200b20, 0x0c200d20]
    w[53:55] = [0x11003, 0x8421]
    return w


def fixed_combiner(words, *, name='runCombiners', constants=False):
    text = lower_combiner_program(words)
    text = text.replace('vec4 runCombiners(', 'vec4 ' + name + '(')
    # Each combiner has its own fixed register bank. Shader instances do not
    # share state between specialized variants.
    if name != 'runCombiners':
        text = text.replace('registers', name + 'Registers').replace('argb', name + 'Argb')
    def color(match):
        index = int(match[1]) * 4 + int(match[2])
        if index not in (*range(10, 26), 43, 44):
            raise ValueError('Lowered weather shader reads a control word')
        if constants:
            slot = (index - 10) * 2 if index < 18 else (index - 18) * 2 + 1 if index < 26 else index - 27
            return f'material.constants[{slot}]'
        return f'vec4({((words[index] >> 16) & 255) / 255.0:.9g},' \
               f'{((words[index] >> 8) & 255) / 255.0:.9g},' \
               f'{(words[index] & 255) / 255.0:.9g},{(words[index] >> 24) / 255.0:.9g})'
    argb = 'argb' if name == 'runCombiners' else name + 'Argb'
    text = re.sub(re.escape(argb) + r'\(material\.program\[(\d+)\]\[(\d+)\]\)', color, text)
    if 'material.program' in text or 'word(' in text or 'operation' in text:
        raise ValueError('A runtime program reader survived finite weather lowering')
    return text


def generated_sources():
    vp = program('point')
    rows = [vp[i:i+4] for i in range(1, len(vp), 4)]
    native = lower_vertex_program(rows)['statements']
    native = native[native.index('    // Original instruction'):]
    native = native.replace('vpConstant(', 'nativeWeatherConstant(')
    native = native.replace('vpProduct(', 'nativeWeatherProduct(')
    body = ('// Generated by tools/generate_native_weather_kernels.py from complete VS22.\n'
            'vec4 vpOut[16];\n'
            'vec4 nativeWeatherProduct(vec4 a,vec4 b){\n'
            '    return vec4(a.x==0.0||b.x==0.0?0.0:a.x*b.x,a.y==0.0||b.y==0.0?0.0:a.y*b.y,\n'
            '                a.z==0.0||b.z==0.0?0.0:a.z*b.z,a.w==0.0||b.w==0.0?0.0:a.w*b.w);\n}\n'
            'vec4 nativeWeatherConstant(uint i){return weather.camera[i];}\n'
            'void sourceWeatherPointProgram(vec4 position,uint color){\n'
            '    vec4 vpTemp[13];vec4 vpInput[16];\n'
            '    for(uint i=0u;i<13u;++i)vpTemp[i]=vec4(0);\n'
            '    for(uint i=0u;i<16u;++i){vpOut[i]=vec4(0,0,0,1);vpInput[i]=vec4(0);}\n'
            '    vpInput[0]=position;vpInput[1]=vec4((color>>16u)&255u,(color>>8u)&255u,color&255u,color>>24u)/255.0;\n'
            + native + '}\n')
    sources = {'point-vertex.glsl': body,
               'point-fragment.glsl': fixed_combiner(point_pixel()),
               'line-fragment.glsl': fixed_combiner(point_pixel(True)),
               'shadow-filter-fragment.glsl': fixed_combiner(shadow_filter_pixel())}
    plate = ['// Generated finite original 3A5C0 control tuples. Constants are uniform data.',
             'layout(constant_id=0)const uint nativeWeatherPlateVariant=0u;']
    controls = []
    for power in range(8):
        for alpha in range(2):
            words = plate_controls(power, alpha)
            controls.append(words)
            plate.append(fixed_combiner(words, name=f'nativeWeatherPlate{power*2+alpha}', constants=True))
    plate += ['vec4 runCombiners(vec4 textures[4],vec4 v0,vec4 v1){']
    plate += [f'if(nativeWeatherPlateVariant=={i}u)return nativeWeatherPlate{i}(textures,v0,v1);' for i in range(16)]
    plate += ['return vec4(0);}', '']
    sources['plate-fragment.glsl'] = '\n'.join(plate)
    literal = lambda words: {'words': words, 'sha256': hashlib.sha256(struct.pack('<'+'I'*len(words), *words)).hexdigest()}
    sources['programs.json'] = json.dumps({
        'schema': 'HALO2_NATIVE_WEATHER_SHADOW_FILTER_KERNELS_V1',
        'authority': 'Complete original Xbox shader payloads and original TU1.5 weather/20F30 source control producers',
        'vertex_programs': {'point_vs22': literal(vp), 'plate_vs21': literal(program('plate'))},
        'fragment_programs': {'point': literal(point_pixel()), 'line': literal(point_pixel(True)),
                              'shadow_filter': literal(shadow_filter_pixel())},
        'plate_control_variants': controls,
        'dynamic_plate_words': list(range(10,26)) + [43,44],
        'runtime_instruction_words': 0}, indent=2) + '\n'
    return sources


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DESTINATION)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sources = generated_sources()
    if args.check:
        for name, text in sources.items():
            if (args.output / name).read_text() != text:
                raise ValueError('Stale native weather kernel source: ' + name)
    else:
        args.output.mkdir(parents=True, exist_ok=True)
        for name, text in sources.items():
            (args.output / name).write_text(text)
    print('Native weather/shadow-filter source kernels: two VS identities, nineteen FS identities, zero runtime instructions')


if __name__ == '__main__':
    main()
