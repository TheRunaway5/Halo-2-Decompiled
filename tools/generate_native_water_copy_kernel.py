#!/usr/bin/env python3
"""Maintain the direct native combiner for the literal source water-copy owner.

Normal builds compile the checked-in GLSL. This explicit maintenance helper
reads the complete existing C++ literal program, lowers its words at build time
and pins the resulting source. No shader instructions run through a runtime
interpreter and no game executable/cache is required.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

from native_world_fragment_kernel import lower_fragment_program

ROOT = Path(__file__).resolve().parents[1]
OWNER = 'src/rendering/source_scene_copy.cpp'
OUTPUT = 'shaders/native-programs/world/water-copy-combiner.glsl'
MANIFEST = 'shaders/native-programs/world/water-copy-combiner.json'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def literal_program(text):
    matches = re.findall(r'PixelProgram source_scene_copy_program\(\)\s*\{(.*?)\n\}',
                         text, re.DOTALL)
    if len(matches) != 1:
        raise ValueError('Water copy requires one complete literal native source owner')
    body = re.sub(r'\s+', '', matches[0])
    prefix, suffix = 'PixelProgramout;auto&w=out.words;', 'returnout;'
    if not body.startswith(prefix) or not body.endswith(suffix):
        raise ValueError('Water-copy program is no longer an admitted literal initializer')
    assignments = body[len(prefix):-len(suffix)]
    pattern = r'w\[([0-9]+)\]=(0x[0-9a-fA-F]+|[0-9]+);'
    if re.sub(pattern, '', assignments):
        raise ValueError('Water-copy initializer contains an unproved operation')
    words, assigned = [0] * 60, set()
    for index, value in re.findall(pattern, assignments):
        at, word = int(index), int(value, 16 if value.startswith('0x') else 10)
        if not 0 <= at < 60 or at in assigned or not 0 <= word <= 0xffffffff:
            raise ValueError('Water-copy initializer has an invalid or duplicate literal word')
        words[at] = word; assigned.add(at)
    if not assigned:
        raise ValueError('Water-copy initializer has no admitted words')
    return words, sha(matches[0].encode())


def outputs(root=ROOT):
    root = Path(root)
    words, owner_hash = literal_program((root / OWNER).read_text())
    word_hash = sha(struct.pack('<60I', *words))
    lowered = lower_fragment_program(words)['combiner_glsl']
    source = ('// Generated by tools/generate_native_water_copy_kernel.py.\n'
              '// Complete literal source_scene_copy_program; native arithmetic only.\n'
              f'// Source owner body SHA-256: {owner_hash}\n'
              f'// Complete 60-word program SHA-256: {word_hash}\n' + lowered).encode()
    manifest = dict(schema='HALO2_NATIVE_WATER_COPY_COMBINER_V1', source_owner=OWNER,
                    source_owner_body_sha256=owner_hash, program_words=words,
                    program_sha256=word_hash, glsl=OUTPUT, glsl_sha256=sha(source),
                    lowerer='tools/native_world_fragment_kernel.py',
                    lowerer_sha256=sha((root / 'tools/native_world_fragment_kernel.py').read_bytes()),
                    runtime_instruction_interpreter=False,
                    scope='Complete source-owned copy combiner; sampling coordinates and four authored scene taps unchanged')
    return {OUTPUT: source, MANIFEST: (json.dumps(manifest, indent=2) + '\n').encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, data in outputs(args.root).items():
        path = args.root / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError('Native water-copy source is stale: ' + name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


if __name__ == '__main__':
    main()
