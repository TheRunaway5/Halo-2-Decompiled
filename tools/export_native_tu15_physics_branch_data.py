#!/usr/bin/env python3
"""Export audited TU1.5 branch literals; run through tools/run_test.py.

The original executable is an offline reference only. Generated native data
contains bounded immutable branch/selector tables, never code or tag payloads.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe
from functions import _Code, _trace

REFERENCE_SHA256 = '21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd'
GRAPH_SHA256 = '4f2cbf886af68d453aaf22d59ac946434919dfbbb0aaca06bba4ebf8ac66ded4'
# Original selector tables also contain literal null targets. Preserve their
# bytes; native dispatch must not turn a selected null into a successful call.
NULL_TARGET_ENTRIES = {0xe97d0, 0xe9870, 0xe9990, 0x185c00, 0x1d73d0, 0x1dec80}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    scratch = Path(os.environ['HALO2_TEST_SCRATCH'])
    graph = ROOT / 'src/physics_live_support_tu15_generated.cpp'
    source = graph.read_bytes()
    assert hashlib.sha256(source).hexdigest() == GRAPH_SHA256
    image = Xbe(args.reference)
    assert hashlib.sha256(image.data).hexdigest() == REFERENCE_SHA256
    text = source.decode()
    starts = {int(value, 16) for value in re.findall(r'static void run_([0-9a-f]+)\(WorldState &s\)', text)}
    code = _Code(image, '.text')
    tables, null_entries = {}, set()
    for entry in sorted(starts):
        fn = _trace(code, entry, starts)
        rows = []
        for address, width, count in fn.tables:
            section = next(s for s in image.sections if s.va <= address and address + width * count <= s.va + s.vsize)
            assert not section.flags & 1 and width in (1, 4) and count > 0
            raw = image.read(address, width * count)
            # Original E999F and E99C3 use an operand two bytes before the
            # first valid selector (input range begins at2). The trace reports
            # the actual bounded table, not that biased addressing operand.
            biased = {0xe9bb8: 0xe9bb6, 0xe9c40: 0xe9c3e}
            operand = biased.get(address, address)
            assert f'0x{operand:x}u' in text, hex(address)
            if width == 4:
                targets = [int.from_bytes(raw[i:i+4], 'little') for i in range(0, len(raw), 4)]
                assert all(target == 0 or target in fn.code for target in targets)
                if 0 in targets:
                    assert entry in NULL_TARGET_ENTRIES, hex(entry)
                    null_entries.add(entry)
            rows.append((address, width, count, raw))
        for address, width, count, raw in rows:
            previous = tables.setdefault((address, width, count), raw)
            assert previous == raw
    assert null_entries == NULL_TARGET_ENTRIES and len(tables) == 118
    lines = ['// Generated by tools/export_native_tu15_physics_branch_data.py.',
             '// English TU1.5 reference SHA256: ' + REFERENCE_SHA256,
             '// Compiled physics graph SHA256: ' + GRAPH_SHA256,
             '// 118 proved readonly tables, including original literal null targets.']
    ordered = sorted(tables.items())
    for ordinal, (_, raw) in enumerate(ordered):
        lines.append(f'constexpr std::array<std::byte,{len(raw)}> branch_{ordinal}{{')
        for i in range(0, len(raw), 12):
            lines.append('    ' + ','.join(f'std::byte{{0x{value:02x}}}' for value in raw[i:i+12]) + ',')
        lines.append('};')
    lines.append('constexpr std::array branch_tables{')
    for ordinal, ((address, _, _), _) in enumerate(ordered):
        lines.append(f'    BranchTable{{0x{address:x}u,branch_{ordinal}}},')
    lines.append('};')
    data = ('\n'.join(lines) + '\n').encode()
    temporary = scratch / 'branch-data.inc'
    temporary.write_bytes(data)
    args.output.write_bytes(temporary.read_bytes())
    report = dict(passed=True, reference_sha256=REFERENCE_SHA256, graph_sha256=GRAPH_SHA256,
                  functions=len(starts), tables=len(tables), literal_bytes=sum(len(raw) for raw in tables.values()),
                  original_null_target_entries=[hex(entry) for entry in sorted(null_entries)],
                  output=str(args.output), output_sha256=hashlib.sha256(data).hexdigest(),
                  scratch=str(scratch), runtime_reference_file_required=False, full_physics_parity=False)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
