#!/usr/bin/env python3
"""Export the original readonly double consumed by the native light-portal query.

No instruction, mutable storage, admission or lighting result is exported.
Run under tools/run_test.py; generation intermediates stay in owned scratch.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct

from oracle_smg_firing_1_1 import Xbe,_Code
from research_mp_sandbox_update_functions import NEW_DEFAULT,NEW_PIN
from capstone import CS_AC_READ
from capstone.x86 import X86_OP_MEM

ROOT=Path(__file__).resolve().parents[1]
SITES=(0x1765b0,0x1765bf,0x176754)
ADDRESS=0x46a598


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();owner=Path(os.environ['HALO2_TEST_SCRATCH']).resolve(strict=True)
    if not args.output.resolve().is_relative_to(owner):parser.error('Generate into owned scratch first')
    if sha(NEW_DEFAULT)!=NEW_PIN:raise ValueError('Original English TU1.5 image differs')
    image=Xbe(NEW_DEFAULT);code=_Code(image,'.text');readonly=image.section('.rdata')
    if readonly.flags&1 or not readonly.va<=ADDRESS<ADDRESS+8<=readonly.va+readonly.vsize:
        raise ValueError('Light-portal operand has no original readonly owner')
    module=ROOT/'src/pstencil/native_light_portal_tu15_generated.cpp';text=module.read_text();reads=[]
    for pc in SITES:
        instruction=code.at(pc)
        if instruction.mnemonic!='fld' or len(instruction.operands)!=1:raise ValueError('Original load changed')
        operand=instruction.operands[0]
        if not (operand.type==X86_OP_MEM and not operand.mem.base and not operand.mem.index and
                operand.mem.disp==ADDRESS and operand.size==8 and operand.access&CS_AC_READ):
            raise ValueError('Original portal constant is not a fixed readonly qword read')
        prefix=f'if(s.services.instruction){{s.services.instruction(0x{pc:x}u);}}'
        rows=[line for line in text.splitlines() if line.startswith(prefix)]
        if len(rows)!=1 or 'native_read64(s.memory,(0x46a598u))' not in rows[0]:
            raise ValueError('Native consumer differs from the actual original load')
        reads.append(dict(pc=pc,instruction_hex=instruction.bytes.hex(),mnemonic=instruction.mnemonic,
            operands=instruction.op_str,address=ADDRESS,bytes=8))
    raw=image.read(ADDRESS,8)
    output=('// Generated by tools/export_native_tu15_light_portal_literal_data.py.\n'
        '// Original English TU1.5 SHA256: '+NEW_PIN+'\n'
        '// Exact readonly operand of1765B0/1765BF/176754; no surrounding bytes or produced state.\n'
        'constexpr std::array<std::byte,8> light_portal_comparison_literal{\n    '+
        ','.join(f'std::byte{{0x{byte:02x}}}' for byte in raw)+'\n};\n'
        'constexpr std::array light_portal_literal_tables{\n'
        '    BranchTable{0x46a598u,light_portal_comparison_literal},\n};\n')
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(output)
    report=dict(passed=True,original_xbe_sha256=NEW_PIN,original_section='.rdata',
        original_section_flags=readonly.flags,readonly=True,address=ADDRESS,bytes=8,data_hex=raw.hex(),
        ieee64_value=struct.unpack('<d',raw)[0],reads=reads,native_consumer_sha256=sha(module),
        output_sha256=sha(args.output),tool_sha256=sha(Path(__file__)),
        instruction_or_admission_results_exported=False,production_emulator=False,full_vehicle_parity=False)
    args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(dict(passed=True,data_hex=raw.hex(),ieee64_value=report['ieee64_value'],report=str(args.report))),flush=True)


if __name__=='__main__':main()
