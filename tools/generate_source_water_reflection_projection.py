#!/usr/bin/env python3
"""Retain one fixed TU1.5 stencil projection as native GLSL/test C++.

This maintenance tool authenticates the complete original payload. Normal game
builds compile the checked-in straight-line GLSL; no instruction bank, shader
opcode decoder or original cache is used by the runtime projection.
"""
import argparse
import hashlib
import struct
from pathlib import Path
from native_world_vertex_kernel import lower_vertex_program
from native_cpu_vertex_kernel import lower_cpu_vertex_program

PROGRAM_SHA256 = '46ff53294ae335c47103b1c5ec0b8b84cde853490d2e761df919f8e2589e8083'
FIXTURE_SHA256 = '4d9c0710064ecaf45a30e8b1be738e84d85514b1a0b08edee40c000460036f1f'

def outputs(fixture):
    data=fixture.read_bytes()
    if hashlib.sha256(data).hexdigest()!=FIXTURE_SHA256:
        raise ValueError('Original campaign vertex fixture identity changed')
    rows=[line.split() for line in data.decode().splitlines() if line.startswith('P stencil_texture 0 ')]
    if len(rows)!=1 or rows[0][3:6]!=['2','0','3']:
        raise ValueError('Exact world-class stencil projection/declaration changed')
    raw=bytes.fromhex(rows[0][6])
    if len(raw)!=196 or hashlib.sha256(raw).hexdigest()!=PROGRAM_SHA256 or raw[:4]!=bytes.fromhex('78200c00'):
        raise ValueError('Complete original stencil projection payload changed')
    words=[list(struct.unpack_from('<4I',raw,4+i*16)) for i in range(12)]
    lowered=lower_vertex_program(words,[0,3]+[255]*14,False)
    glsl=lowered['glsl'].replace('void runVertexProgram()', 'void runSourceWaterReflectionProjection()')
    prefix='// Generated by tools/generate_source_water_reflection_projection.py.\n// Original stencil_texture class0: '+PROGRAM_SHA256+'.\n// Fixed native arithmetic only; no runtime instruction/operand decoding.\n'
    header=['#pragma once','#include "halo2/vertex_program.hpp"','#include <algorithm>','#include <cmath>',
        '#include <limits>','namespace halo2::native_water_reflection_projection_test {',
        'inline float native_product(float a,float b){return a==0 || b==0?0.f:a*b;}',
        'inline const ShaderVector& native_constant(const VertexProgramState& s,int i){',
        ' if(i<0 || unsigned(i)>=s.constants.size())throw FormatError("Fixed reflection source constant escapes bank");',
        ' return s.constants[unsigned(i)];}',
        lower_cpu_vertex_program(words,'run'),'}','']
    return {'shaders/source_water_reflection_projection.glsl':prefix+glsl,
        'tests/helpers/native_water_reflection_projection_kernel.hpp':prefix+'\n'.join(header)}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fixture',type=Path,default=Path(__file__).resolve().parents[1]/'tests/fixtures/retail_campaign_character_vertex.tsv')
    parser.add_argument('--output-root',type=Path,default=Path(__file__).resolve().parents[1])
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for name,text in outputs(args.fixture).items():
        target=args.output_root/name;raw=text.encode()
        if args.check:
            if not target.is_file() or target.read_bytes()!=raw:raise ValueError('Stale fixed reflection source: '+name)
        else:
            target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(raw)
    print('PASS exact fixed TU1.5 reflection projection source'+(' freshness' if args.check else ' generation'))
if __name__=='__main__':main()
