#!/usr/bin/env python3
"""Validate/emit the finite nine-pair shared three-channel light profile."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def need(ok, why):
    if not ok:
        raise ValueError("Three-channel paired profile: " + why)


def generate(raw):
    value = json.loads(raw)
    need(value["schema"] == "H2_MCC_NATIVE_ILLUM_THREE_CHANNEL_PROFILES_V1" and len(value["profiles"]) == 1,
         "finite source census changed")
    profile = value["profiles"][0]
    name = "shaders\\shader_templates\\opaque\\tex_bump_illum_3_channel"
    need(profile["template"] == name and profile["native_source_map"] == "04a_gasgiant" and
         profile["native_record"]["group"] == "stem" and profile["native_record"]["name"] == name and
         profile["shader_type_flags"] == 1 and profile["runtime_diffuse_slot"] == 1, "unreviewed native source")
    graph = profile["source_graph"]
    need(hashlib.sha256(canonical(graph)).hexdigest() == profile["source_graph_sha256"] and
         len(bytes.fromhex(graph["root_hex"])) == 96 and len(graph["definitions"]) == 3, "complete source remap root differs")
    for definition in graph["definitions"]:
        need(len(bytes.fromhex(definition["definition_hex"])) == 40 and len(definition["arrays"]) == 5, "source definition differs")
        for array, (field, stride) in zip(definition["arrays"], ((0, 10), (8, 2), (16, 10), (24, 6), (32, 4)), strict=True):
            need(array["field"] == field and len(bytes.fromhex(array["raw_hex"])) == array["count"] * stride and
                 len(array["typed_references"]) == (array["count"] if field == 16 else 0) and
                 all(len(reference) == 2 and reference[0] == "spas" for reference in array["typed_references"]),
                 "complete typed source remap bank differs")
    counts = profile["source_counts"]
    need(all(counts[str(k)] == v for k, v in {4: 6, 12: 11, 20: 8, 28: 2, 52: 35, 60: 1, 68: 1, 76: 1, 84: 2, 92: 5, 100: 2, 108: 6}.items()),
         "complete source setup shape differs")
    need(profile["native_shape"] == {"0": 1, "8": 25, "16": 7, "24": 25, "32": 84}, "complete original shape differs")
    source, native = profile["source_role_banks"], profile["native_role_banks"]
    need(all(source[str(field)] == native[str(field)] for field in (68, 76, 92)) and
         len(bytes.fromhex(source["52"])) == 350 and len(bytes.fromhex(native["52"])) == 250 and
         source["84"] == "8300000083000000" and native["84"] == "40000400" and
         source["68"] == "0000ffff" and source["76"] == "0002" and
         source["28"] == "800000000032800000001932" and native["28"] == "800000000032", "literal original animation roles differ")
    need(profile["role_mapping"] == dict(bitmap_slots=[0, 1, 2, 3, 5], pixel_slots=[0, 1, 2, 3, 4, 6, 5, 7], vector_slots=[0, 1, 2, 3, 4, 6, 7, 5]),
         "unproved main-role mapping")
    setup = profile["source_setup"]
    need(len(setup["images"]) == 6 and all(row[0][0] == "bitm" and row[1] == 0 for row in setup["images"]) and
         len(bytes.fromhex(setup["pixel_hex"])) == 44 and len(bytes.fromhex(setup["vector_hex"])) == 128 and
         len(bytes.fromhex(setup["property_hex"])) == 24 and len(bytes.fromhex(setup["nie_hex"])) == 24 and
         len(bytes.fromhex(setup["runtime_hex"])) == 80 and [row[0] for row in setup["runtime_references"]] == [4, 12, 48, 56],
         "complete finite main/runtime setup differs")
    overlays = profile["clock_overlays"]
    need(len(overlays) == 1 and overlays[0]["input"] == overlays[0]["range"] == 0 and
         overlays[0]["period_words"] == [1065353216] and len(bytes.fromhex(overlays[0]["curve_hex"])) == 52, "complete native clock authority differs")
    proof = profile["paired_proof"]
    need(proof["paired_owners"] == 9 and all(proof[key] for key in ("all_full_main_outputs_exact", "complete_source_shared_setup_exact", "complete_required_curve_exact", "source_and_native_role_banks_literal")),
         "missing complete nine-pair proof")
    need(len(profile["needed_PC_owners"]) == 1 and profile["needed_PC_owners"][0]["map"] == "needle" and len(profile["paired_controls"]) == 9,
         "required actual owner/control census differs")
    data = {key: profile[key] for key in ("template", "source_graph", "source_counts", "native_shape", "shader_type_flags", "runtime_diffuse_slot", "source_role_banks", "native_role_banks", "clock_overlays", "source_setup")}
    data["native_record"] = {key: profile["native_record"][key] for key in ("payload", "bytes", "fnv64")}
    return ('// Generated by tools/generate_mcc_native_illum_three_channel.py; do not edit.\n'
            '// Complete paired source data SHA256: ' + hashlib.sha256(raw).hexdigest() + '\n'
            'constexpr std::string_view native_illum_three_channel_profiles=R"H2ILLUM3(' + canonical({"profiles": [data]}).decode() + ')H2ILLUM3";\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate((ROOT / "tools/data/mcc-native-illum-three-channel-profiles.json").read_bytes())
    target = ROOT / "src/rendering/mcc_native_illum_three_channel_profiles.inc"
    if args.check:
        need(target.is_file() and target.read_text() == text, "stale generated source")
    else:
        target.write_text(text)


if __name__ == "__main__":
    main()
