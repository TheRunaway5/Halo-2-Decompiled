#!/usr/bin/env python3
"""Compile the reviewed named damage tuples; no executable or XML is read."""
import argparse
import hashlib
import json
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = root / "tools/mcc-gameplay-scalar-damage-profiles.json"
    target = root / "src/mcc_gameplay_scalar_damage_profiles.inc"
    raw = source.read_bytes()
    manifest = json.loads(raw)
    if manifest["schema"] != "H2_MCC_TU15_DAMAGE_AREA_FLAGS_PROFILE_V1":
        raise ValueError("Unsupported reviewed damage profile schema")
    rows = manifest["profiles"]
    if len(rows) != 153 or len({row["name"] for row in rows}) != len(rows):
        raise ValueError("Reviewed damage profile census is not complete and unique")
    output = [
        "// Generated by tools/generate_mcc_gameplay_scalar_profiles.py.",
        "// Reviewed profile manifest SHA256: " + hashlib.sha256(raw).hexdigest(),
        "// Exact named tuples only; unknown paths or other authored bits are preserved.",
        "constexpr std::array damage_profiles{",
    ]
    for row in rows:
        donor = int(row["donor_bits"], 16)
        original = int(row["target_bits"], 16)
        if (row["group"], row["offset"], row["bytes"]) != ("jpt!", 12, 4):
            raise ValueError("Reviewed damage profile field changed")
        if donor not in (4, 5, 6) or original != donor - 4:
            raise ValueError("Reviewed damage profile tuple changed")
        output.append(
            "    Profile{tag_groups::damage_effect,"
            + json.dumps(row["name"])
            + ',"tu15-retail-area-damage-flags",'
            + "{{{0x0c,0x%08x,0x%08x,4},{},{}}},1}," % (donor, original)
        )
    output.append("};")
    text = "\n".join(output) + "\n"
    if args.check:
        if target.read_text() != text:
            raise SystemExit("Compiled MCC scalar damage profiles differ from their reviewed manifest")
    else:
        target.write_text(text)
    print(f"Verified {len(rows)} explicit named retail damage tuples")


if __name__ == "__main__":
    main()
