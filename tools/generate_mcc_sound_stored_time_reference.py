#!/usr/bin/env python3
"""Generate the finite original stored-ms/MCC payload identity policy."""
from pathlib import Path
import argparse
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]


def text(value):
    data = value.encode("utf-8")
    if not data or len(data) > 0x100000:
        raise ValueError("invalid sound identity")
    return struct.pack("<I", len(data)) + data


def digest(value):
    result = bytes.fromhex(value)
    if len(result) != 32:
        raise ValueError("invalid SHA256")
    return result


def generate(policy):
    if policy["schema"] != "H2_MCC_SOUND_STORED_TIME_REFERENCE_V1":
        raise ValueError("unknown policy schema")
    values = {}
    for row in policy["values"]:
        key = hashlib.sha256(b"H2_TU15_SOUND_STORED_TIME_KEY_V1\0" + text(row["path"])).digest()
        ms = row["original_ms"]
        source = row["original_reference"]
        header = bytes.fromhex(source["root_hex"])
        if (len(header) != 20 or hashlib.sha256(header).digest() != digest(source["root_sha256"]) or
                struct.unpack_from("<i", header, 16)[0] != ms or source["ms"] != ms or
                type(ms) is not int or not 0 <= source["full_salt"] < 0xffffffff):
            raise ValueError("stored time differs from its exact original header")
        if key != digest(row["key_sha256"]) or key in values or not 0 <= ms <= 0x7fffffff:
            raise ValueError("invalid/duplicate original stored time")
        values[key] = key + struct.pack("<i", ms)
    payloads = {}
    for row in policy["payloads"]:
        key = hashlib.sha256(b"H2_TU15_SOUND_TIMING_KEY_V1\0" + text(row["path"]) +
                             text(row["range"]) + text(row["permutation"])).digest()
        if key != digest(row["key_sha256"]) or key in payloads:
            raise ValueError("invalid/duplicate payload identity")
        payloads[key] = key + digest(row["payload_sha256"])
    lines = ["// Generated by tools/generate_mcc_sound_stored_time_reference.py; do not edit."]
    for name, rows in [("stored_time_values", values), ("stored_time_payloads", payloads)]:
        lines.append(f"static constexpr char {name}[]=\n" + "\n".join(
            '    "' + "".join(f"\\x{x:02x}" for x in rows[key]) + '"' for key in sorted(rows)) + ";")
    owners = set()
    encoded = []
    for row in policy["owners"]:
        identity = (row["handle"], row["root"], row["path"], row["metadata_sha256"])
        if identity in owners or not 0 <= row["handle"] <= 0xffffffff or not 0 < row["root"] < 0xffffffff:
            raise ValueError("invalid/duplicate complete owner")
        owners.add(identity)
        raw = digest(row["metadata_sha256"])
        name = json.dumps(row["path"])
        encoded.append("    Owner{{%du},%du,%s,{%s}}," % (
            row["handle"], row["root"], name,
            ",".join("std::byte{0x%02x}" % x for x in raw)))
    lines.append("static const std::array<Owner,%d> stored_time_owners{{\n%s\n}};" %
                 (len(encoded), "\n".join(encoded)))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = ROOT / "tools/mcc-sound-stored-time-reference-profiles.json"
    target = ROOT / "src/audio/mcc_sound_stored_time_reference_profiles.inc"
    result = generate(json.loads(source.read_text()))
    if args.check:
        if not target.exists() or target.read_text() != result:
            raise SystemExit("stored-time reference profile is stale")
    else:
        target.write_text(result)


if __name__ == "__main__":
    main()
