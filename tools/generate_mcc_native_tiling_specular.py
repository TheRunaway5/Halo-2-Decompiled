"""Emit the sealed, completely paired tiling-specular metadata contract."""
import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PROFILE_SHA256 = '8b141780f11bde953fc3ebc14922e79dfd7b3afd93ac2d427f12fd5244c189ac'


def need(ok, why):
    if not ok:
        raise ValueError('Native tiling-specular metadata: ' + why)


def generate(raw):
    need(hashlib.sha256(raw).hexdigest() == PROFILE_SHA256, 'complete sealed projection profile changed')
    profile = json.loads(raw)
    need(profile['schema'] == 'H2_MCC_NATIVE_TILING_SPECULAR_PROFILES_V1' and
         profile['template'] == r'shaders\shader_templates\opaque\tex_bump_env_tiling_specular' and
         profile['roles']['vector_sources'] == [2, 3, 1, 0, 4, 5, 10, 11] and
         profile['authority']['materials'] == 14 and profile['authority']['paired_controls'] == 2,
         'complete paired authority contract differs')
    need(len(profile['native_records']) == 2 and len(profile['source_graph']['definitions']) == 3,
         'complete original variants or source platform definitions differ')
    data = {key: profile[key] for key in ('template', 'source_graph', 'native_arrays', 'native_records', 'roles')}
    text = json.dumps(data, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
    need(')H2TILING"' not in text, 'metadata escaped its generated literal')
    return ('// Generated by tools/generate_mcc_native_tiling_specular.py; do not edit.\n'
            '// Complete paired metadata SHA256: ' + PROFILE_SHA256 + '\n'
            'constexpr std::string_view native_tiling_specular_profile=R"H2TILING(' + text + ')H2TILING";\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate((ROOT / 'tools/data/mcc-native-tiling-specular-profiles.json').read_bytes())
    target = ROOT / 'src/rendering/mcc_native_tiling_specular_profiles.inc'
    if args.check:
        need(target.is_file() and target.read_text() == text, 'stale generated source')
    else:
        target.write_text(text)


if __name__ == '__main__':
    main()
