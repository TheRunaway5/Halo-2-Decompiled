#!/usr/bin/env python3
"""Export exact fixed readonly operands of compiled English TU1.5 physics.

Only original .text instruction sites in the pinned native physics bodies and
their reached death/contact-action dependencies qualify. SDK sites, indexed
operands, loader-resolved clock imports, writable storage, gaps, tags and
produced state are excluded.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys

from export_native_tu15_physics_callable_data import SOURCES, REFERENCE_SHA256

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe
from functions import _Code
from capstone import CS_AC_READ
from capstone.x86 import X86_OP_MEM


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    args = parser.parse_args()
    scratch = Path(os.environ['HALO2_TEST_SCRATCH'])
    sites = {}
    for name, expected in SOURCES.items():
        raw = (ROOT / 'src' / name).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == expected
        text = raw.decode()
        if name.endswith('_tu15_generated.cpp'):
            for pc in re.findall(r'services\.instruction\(0x([0-9a-f]+)u?\)', text):
                sites.setdefault(int(pc, 16), set()).add(name)
        for _, pc in re.findall(r'\b\w*observation_pc\(\s*0x([0-9a-f]+)u?,\s*0x([0-9a-f]+)u?', text):
            sites.setdefault(int(pc, 16), set()).add(name)
    image = Xbe(args.reference)
    assert hashlib.sha256(image.data).hexdigest() == REFERENCE_SHA256
    code = _Code(image, '.text')
    readonly = image.section('.rdata')
    assert not readonly.flags & 1
    reads, values, sdk_sites, runtime_bindings = [], {}, [], []
    for pc, sources in sorted(sites.items()):
        if not code.inside(pc):
            section = next(section for section in image.sections
                           if section.va <= pc < section.va + section.vsize)
            sdk_sites.append(dict(pc=pc, section=section.name))
            continue
        instruction = code.at(pc)
        assert instruction is not None, hex(pc)
        if instruction.mnemonic == 'lea' or instruction.mnemonic.startswith(('prefetch', 'nop')):
            continue
        for ordinal, operand in enumerate(instruction.operands):
            if (operand.type != X86_OP_MEM or operand.mem.base or operand.mem.index
                    or not operand.access & CS_AC_READ):
                continue
            address, size = operand.mem.disp, operand.size
            if not readonly.va <= address < address + size <= readonly.va + readonly.vsize:
                continue
            assert 0 < size <= 16
            raw = image.read(address, size)
            # source_runtime_image.cpp/native_tu15_world_memory.cpp relocate
            # this kernel data import to the supplied tick-count cell. The
            # file ordinal is not an immutable runtime program operand.
            if address < 0x41b778 and 0x41b774 < address + size:
                assert address == 0x41b774 and size == 4 and raw.hex() == '9c000080'
                runtime_bindings.append(dict(pc=pc, address=address, bytes=size,
                    data_hex=raw.hex(), owner='SourceRuntimeKernelTickCount data import'))
                continue
            for offset, byte in enumerate(raw):
                at = address + offset
                assert at not in values or values[at] == byte
                values[at] = byte
            reads.append(dict(pc=pc, instruction_hex=instruction.bytes.hex(),
                              mnemonic=instruction.mnemonic, operands=instruction.op_str,
                              operand_index=ordinal, address=address, bytes=size,
                              data_hex=raw.hex(), sources=sorted(sources)))
    records = []
    for address in sorted(values):
        if records and records[-1]['address'] + len(records[-1]['data']) == address:
            records[-1]['data'].append(values[address])
        else:
            records.append(dict(address=address, data=[values[address]]))
    assert len(reads) == 2567 and len(records) == 146 and len(values) == 1380
    assert len(runtime_bindings) == 1
    assert len(sdk_sites) == 466
    lines = ['// Generated by tools/export_native_tu15_physics_literal_data.py.',
             '// English TU1.5 reference SHA256: ' + REFERENCE_SHA256,
             '// Exact fixed readonly reads; no gaps or indexed extents.']
    for ordinal, row in enumerate(records):
        raw = row['data']
        lines.append(f'constexpr std::array<std::byte,{len(raw)}> literal_{ordinal}{{')
        for offset in range(0, len(raw), 12):
            lines.append('    ' + ','.join(f'std::byte{{0x{byte:02x}}}'
                                         for byte in raw[offset:offset+12]) + ',')
        lines.append('};')
    lines.append('constexpr std::array literal_tables{')
    for ordinal, row in enumerate(records):
        lines.append(f'    BranchTable{{0x{row["address"]:x}u,literal_{ordinal}}},')
    lines.append('};')
    output = ('\n'.join(lines) + '\n').encode()
    temporary = scratch / 'physics-literal-data.inc'
    temporary.write_bytes(output)
    args.output.write_bytes(temporary.read_bytes())
    report = dict(passed=True, scratch=str(scratch), reference_sha256=REFERENCE_SHA256,
                  source_sha256=SOURCES, fixed_reads=len(reads), records=len(records),
                  literal_bytes=len(values), excluded_sdk_sites=sdk_sites, reads=reads,
                  excluded_runtime_bindings=runtime_bindings,
                  output_sha256=hashlib.sha256(output).hexdigest(),
                  runtime_reference_file_required=False, full_physics_parity=False,
                  scope=__doc__, rows=[dict(address=row['address'], bytes=len(row['data']),
                                            data_hex=bytes(row['data']).hex()) for row in records])
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({key: value for key, value in report.items()
                      if key not in ('rows', 'reads', 'excluded_sdk_sites')}))


if __name__ == '__main__':
    main()
