#!/usr/bin/env python3
"""Export the seven authored non-linear transition rows as native constant data.

The existing independent whole-original fixture checks every exported byte.
Only parameter data is exported; no instruction or computed geometry is loaded
by production. Generate under tools/run_test.py before promoting the fragment.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import struct

from oracle_smg_firing_1_1 import Xbe,_Code
from research_mp_sandbox_update_functions import NEW_DEFAULT,NEW_PIN
from audit_weapon_vehicle_sound_presence_tu15 import schema,PIN,SCHEMAS

ROOT=Path(__file__).resolve().parents[1]
BASE=0x4782a8
FIRST=BASE+1024
SIZE=7*1024


def sha(path):return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();owner=Path(os.environ['HALO2_TEST_SCRATCH']).resolve(strict=True)
    if not args.output.resolve().is_relative_to(owner):parser.error('Generate into owned scratch first')
    if sha(NEW_DEFAULT)!=NEW_PIN:raise ValueError('Original English TU1.5 image differs')
    image=Xbe(NEW_DEFAULT);code=_Code(image,'.text');section=image.section('.data')
    if not section.va<=FIRST<FIRST+SIZE<=section.va+section.vsize:
        raise ValueError('Original transition tables escape their data owner')
    fixture_path=ROOT/'tests/fixtures/light_fade_curves_tu15_original.json'
    fixture=json.loads(fixture_path.read_text())
    if fixture['original_sha256']!=NEW_PIN or len(fixture['tables'])!=16 or len(fixture['cases'])!=18592:
        raise ValueError('Independent complete original transition fixture differs')
    # The old scalar fixture deliberately swept sixteen numeric selectors.
    # Its loop count is not an authored enum or a static-data extent: type8
    # already aliases writable placement state. Type0 bypasses the lookup.
    enum=next(node for node in schema('ligh').iter()
        if node.get('name')=='Falloff Function' and node.get('offset')=='0xB6')
    options=[dict(name=node.get('name'),value=int(node.get('value'),0)) for node in enum]
    if options!=[dict(name=name,value=value) for value,name in enumerate(
            ('Linear','Late','Very Late','Early','Very Early','Cosine','Zero','One'))]:
        raise ValueError('Requalify the authored transition enum')
    raw=image.read(FIRST,SIZE)
    if b''.join(bytes.fromhex(row) for row in fixture['tables'][1:8])!=raw:
        raise ValueError('Original image and independent table bytes differ')
    reads=[]
    for pc,mnemonic,operands in (
            (0x17f8bb,'test','ax, ax'),(0x17f8be,'je','0x17f98c'),
            (0x17f8d6,'shl','esi, 0xa'),(0x17f8dd,'add','esi, 0x4782a8'),
            (0x17f912,'cmp','ax, 0x3ff'),(0x17f920,'movzx','eax, byte ptr [esi + 0x3ff]'),
            (0x17f946,'movzx','edx, byte ptr [ecx + esi]'),(0x17f94d,'movzx','eax, byte ptr [eax + 1]')):
        ins=code.at(pc)
        if ins.mnemonic!=mnemonic or ins.op_str!=operands:raise ValueError('Original transition reader differs')
        reads.append(dict(pc=pc,hex=ins.bytes.hex(),mnemonic=ins.mnemonic,operands=ins.op_str))
    text_section=image.section('.text');text=image.read(text_section.va,text_section.vsize)
    literal=struct.pack('<I',BASE);sites=[];at=0
    while (at:=text.find(literal,at))!=-1:
        sites.append(text_section.va+at);at+=1
    if sites!=[0x17f8df]:raise ValueError('Requalify additional original transition-bank references')
    consumer=ROOT/'src/rendering/effects/source_contrail_geometry_tu15_generated.cpp'
    lines=consumer.read_text().splitlines()
    for row in reads:
        if not any(f's.services.instruction(0x{row["pc"]:x}u)' in line for line in lines):
            raise ValueError('Native complete transition consumer omitted an original instruction')
    output=('// Generated by tools/export_native_tu15_fade_curve_data.py.\n'
        '// Original English TU1.5 SHA256: '+NEW_PIN+'\n'
        '// Authored types1..7 only; type0 bypasses the lookup.\n'
        '// Ends before mutable placement state47A2A8; no opcode or geometry result.\n'
        'constexpr std::array<std::byte,7168> transition_fade_curve_bank{\n')
    output+=''.join('    '+','.join(f'std::byte{{0x{v:02x}}}' for v in raw[at:at+16])+',\n'
        for at in range(0,SIZE,16))
    # Retain the material provider's complete1024-byte ownership boundaries.
    # Its independently authenticated loader shares these exact rows and
    # correctly rejects larger, partial, mutable or mismatched owners.
    output+='};\nconstexpr std::array fade_curve_bank_tables{\n'
    output+=''.join(f'    BranchTable{{0x{FIRST+row*1024:x}u,std::span(transition_fade_curve_bank).subspan({row*1024},1024)}},\n'
        for row in range(7))
    output+='};\n'
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(output)
    authored_cases=sum(row[0]<8 for row in fixture['cases'])
    report=dict(passed=True,original_XBE_sha256=NEW_PIN,address=FIRST,end_exclusive=FIRST+SIZE,bytes=SIZE,
        tables=7,bytes_per_table=1024,original_section='.data',original_section_flags=section.flags,
        native_owner_extent_per_row=1024,shares_existing_material_row_boundaries=True,
        authored_schema_commit=PIN,authored_schema_sha256=SCHEMAS,authored_enum=options,
        linear_type_zero_uses_no_table=True,unused_row_zero_exported=False,
        mutable_placement_state_excluded=[0x47a2a8,0x47a2ac],
        role='Static lookup inputs consumed by complete17F8A0; native provider preserves them as immutable data',
        input_sha256=hashlib.sha256(raw).hexdigest(),independent_fixture_sha256=sha(fixture_path),
        independent_numeric_sweep_cases=18592,independent_authored_domain_cases=authored_cases,
        numeric_selectors_8_through_15_are_not_authored_tables=True,every_table_byte_verified=True,
        original_reader=reads,complete_text_base_literal_sites=sites,native_consumer_sha256=sha(consumer),
        output_sha256=sha(args.output),instruction_or_geometry_results_exported=False,
        production_opcode_execution=False,full_vehicle_parity=False,tool_sha256=sha(Path(__file__)))
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(dict(passed=True,tables=7,bytes=SIZE,report=str(args.report))),flush=True)


if __name__=='__main__':main()
