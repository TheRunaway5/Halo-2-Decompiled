#!/usr/bin/env python3
"""Export screen231's authenticated logical geometry, without artwork pixels.

Run through tools/run_test.py. Runtime rasters and localized strings remain
owned by the selected MCC cache; Xbox data supplies reference geometry only.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil

from export_matchmaking_ui_tu15 import Cache, Definition, MccCache, XBOX_PIN, file_sha

ROOT = Path(__file__).resolve().parents[1]
MCC_PIN = 'ba4c3f599ae6191d4cca5e444a40bd2442f1458b3ee38bac3c5f3dec09f9497d'


def definition(cache):
    reader = Definition(cache)
    tag = next(t for t in cache.tags.values() if t['group'] == 'wgit' and
               t['address'] and cache.u16(cache.tag(t['datum'], 'wgit')[1] + 4) == 231)
    screen = reader.screen(tag)
    return dict(screen=screen, images={cache.tags[d]['name']: reader.image(d)
                                      for d in sorted(reader.images)})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--xbox', type=Path, default=ROOT / 'assets/disc/maps/mainmenu.map')
    parser.add_argument('--mcc', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--report', type=Path, required=True)
    parser.add_argument('--publish', action='store_true')
    args = parser.parse_args()
    scratch = Path(os.environ['HALO2_TEST_SCRATCH']).resolve(strict=True)
    assert args.output.resolve().is_relative_to(scratch)
    assert file_sha(args.xbox) == XBOX_PIN and file_sha(args.mcc) == MCC_PIN
    original_cache, imported_cache = Cache(args.xbox), MccCache(args.mcc)
    try:
        original, raw = definition(original_cache), definition(imported_cache)
        assert original['screen']['id'] == raw['screen']['id'] == 231
        assert original['images'].keys() == raw['images'].keys()
        for name, image in original['images'].items():
            actual = raw['images'][name]
            assert image['sequences'] == actual['sequences'] == []
            assert len(image['frames']) == len(actual['frames']) == 1
        payload = dict(schema='H2_TU15_NETWORK_TRANSITION_LAYOUT_V1',
                       asset_policy='admitted-mcc-artwork-source-tu15-logical-layout',
                       original_mainmenu_sha256=XBOX_PIN, mcc_mainmenu_sha256=MCC_PIN,
                       original=original, raw=raw)
        encoded = json.dumps(payload, sort_keys=True, separators=(',', ':'))
        assert len(encoded) < 16384 and ')H2NT"' not in encoded
        args.output.write_text('// Generated by export_network_transition_ui_tu15.py; metadata only.\n'
                               'inline constexpr std::string_view network_transition_layout_data{R"H2NT('
                               + encoded + ')H2NT"};\n')
        if args.publish:
            shutil.copyfile(args.output, ROOT / 'src/ui/frontend_network_transition_layout_data.inc')
        report = dict(passed=True, original_mainmenu_sha256=XBOX_PIN,
                      mcc_mainmenu_sha256=MCC_PIN, profile_sha256=hashlib.sha256(encoded.encode()).hexdigest(),
                      artwork_pixels_exported=0, layout=payload)
        args.report.write_text(json.dumps(report, indent=2) + '\n')
        print(json.dumps({k: v for k, v in report.items() if k != 'layout'}))
    finally:
        original_cache.close()


if __name__ == '__main__':
    main()
