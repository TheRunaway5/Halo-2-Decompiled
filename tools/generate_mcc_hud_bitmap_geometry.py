#!/usr/bin/env python3
"""Generate the finite authored HUD logical-extent table; no runtime game files."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_SHA256 = "e28fac2f54c474e65c6097f6537ae2de193d8f396faa05270ca80fa67cd943df"


def generate(raw):
    if hashlib.sha256(raw).hexdigest() != DATA_SHA256:
        raise ValueError("unrecognized HUD bitmap geometry authority")
    data = json.loads(raw)
    if data["schema"] != "H2_MCC_HUD_BITMAP_LOGICAL_GEOMETRY_V1":
        raise ValueError("unsupported HUD bitmap geometry schema")
    pages, sprites, sequences, banks = [], [], [], []
    for bank in data["banks"]:
        first_page, first_sequence = len(pages), len(sequences)
        if len(bank["physical"]) != len(bank["logical"]):
            raise ValueError("HUD logical/physical bank mismatch")
        for physical, logical in zip(bank["physical"], bank["logical"]):
            pages.append([*physical, *(logical or [0, 0])])
        for sequence in bank["sequences"]:
            sequences.append([len(sprites), len(sequence)])
            sprites.extend(sequence)
        banks.append([bank["name"], first_page, len(bank["physical"]),
                      first_sequence, len(bank["sequences"])])
    lines = ["// Generated by tools/generate_mcc_hud_bitmap_geometry.py; do not edit.",
             f"// Authored metadata SHA256: {DATA_SHA256}"]
    for name, kind, values in (("pages", "Page", pages), ("sequences", "Sequence", sequences)):
        lines.append(f"constexpr std::array<{kind},{len(values)}> {name}{{{{")
        lines.extend("  {" + ",".join(str(v) + "u" for v in row) + "}," for row in values)
        lines.append("}};")
    lines.append(f"constexpr std::array<Sprite,{len(sprites)}> sprites{{{{")
    for image, words in sprites:
        lines.append("  {" + str(image) + "u,{" + ",".join(hex(w) + "u" for w in words) + "}},")
    lines.append("}};")
    lines.append(f"constexpr std::array<Bank,{len(banks)}> banks{{{{")
    for name, *values in banks:
        lines.append("  {" + json.dumps(name) + "," + ",".join(str(v) + "u" for v in values) + "},")
    lines.append("}};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, default=ROOT / "tools/data/mcc-hud-bitmap-geometry.json")
    parser.add_argument("--output", type=Path, default=ROOT / "src/mcc_hud_bitmap_geometry.inc")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        value = generate(args.data.read_bytes())
        if args.check:
            if args.output.read_text() != value:
                raise ValueError("HUD bitmap geometry output is stale")
        else:
            args.output.write_text(value)
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
