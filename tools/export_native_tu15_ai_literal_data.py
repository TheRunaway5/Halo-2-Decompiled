#!/usr/bin/env python3
"""Export exact original fixed readonly reads of the compiled TU1.5 AI frame.

The actual three-Grunt frame reaches272914 reading46A6C0. Audit the complete
pinned frame instead of supplying isolated guessed operands. Only fixed .rdata
reads qualify; no indexed extent, writable bank, tag, clock binding or computed
state is imported. The Xbox executable is an offline reference only.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
from capstone import CS_AC_READ
from capstone.x86 import X86_OP_MEM
from oracle_smg_firing_1_1 import Xbe, _Code
from research_mp_sandbox_update_functions import NEW_DEFAULT, NEW_PIN

ROOT=Path(__file__).resolve().parents[1]
FRAME_SHA256='0faad001eff14edaaa31df28eddcde059ab855a5a3639fff4b81e3526ee15308'


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--output',type=Path,required=True)
    ap.add_argument('--report',type=Path,required=True)
    args=ap.parse_args()
    if 'HALO2_TEST_SCRATCH' not in os.environ:ap.error('Run through tools/run_test.py')
    source=ROOT/'src/campaign/ai/source_ai_frame_tu15_generated.cpp';raw=source.read_bytes()
    assert hashlib.sha256(raw).hexdigest()==FRAME_SHA256
    image=Xbe(NEW_DEFAULT);assert hashlib.sha256(image.data).hexdigest()==NEW_PIN
    code=_Code(image,'.text');readonly=image.section('.rdata');assert not readonly.flags&1
    sites={int(pc,16) for pc in re.findall(r'services\.instruction\(0x([0-9a-f]+)u?\)',raw.decode())}
    reads,values,excluded_sdk,bindings=[],{},[],[]
    for pc in sorted(sites):
        if not code.inside(pc):excluded_sdk.append(pc);continue
        instruction=code.at(pc);assert instruction is not None
        if instruction.mnemonic=='lea' or instruction.mnemonic.startswith(('prefetch','nop')):continue
        for operand in instruction.operands:
            if operand.type!=X86_OP_MEM or operand.mem.base or operand.mem.index or not operand.access&CS_AC_READ:continue
            address,size=operand.mem.disp,operand.size
            if not readonly.va<=address<address+size<=readonly.va+readonly.vsize:continue
            assert 0<size<=16
            data=image.read(address,size)
            row=dict(pc=pc,instruction_hex=bytes(instruction.bytes).hex(),mnemonic=instruction.mnemonic,
                operands=instruction.op_str,address=address,bytes=size,data_hex=data.hex())
            if address<0x41b778 and 0x41b774<address+size:
                bindings.append(row);continue
            for offset,byte in enumerate(data):
                at=address+offset;assert at not in values or values[at]==byte;values[at]=byte
            reads.append(row)
    assert any(row['pc']==0x272914 and row['address']==0x46a6c0 and row['bytes']==8 for row in reads)
    records=[]
    for address in sorted(values):
        if records and records[-1]['address']+len(records[-1]['data'])==address:records[-1]['data'].append(values[address])
        else:records.append(dict(address=address,data=[values[address]]))
    lines=['// Generated by tools/export_native_tu15_ai_literal_data.py.',
        '// English TU1.5 SHA256: '+NEW_PIN,'// Exact compiled AI-frame fixed readonly reads; no gaps, indexed extents or live bindings.']
    for ordinal,row in enumerate(records):
        data=row['data'];lines.append(f'constexpr std::array<std::byte,{len(data)}> ai_literal_{ordinal}{{')
        for offset in range(0,len(data),12):lines.append('    '+','.join(f'std::byte{{0x{b:02x}}}' for b in data[offset:offset+12])+',')
        lines.append('};')
    lines.append('constexpr std::array ai_literal_tables{')
    for ordinal,row in enumerate(records):lines.append(f'    BranchTable{{0x{row["address"]:x}u,ai_literal_{ordinal}}},')
    lines.append('};')
    output=('\n'.join(lines)+'\n').encode();args.output.write_bytes(output)
    assert hashlib.sha256(source.read_bytes()).hexdigest()==FRAME_SHA256
    report=dict(passed=True,scope=__doc__,original_xbe_sha256=NEW_PIN,source_sha256=FRAME_SHA256,
        tool_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),fixed_reads=len(reads),
        literal_bytes=len(values),records=len(records),reads=reads,excluded_sdk_sites=excluded_sdk,
        excluded_runtime_bindings=bindings,rows=[dict(address=row['address'],bytes=len(row['data']),
            data_hex=bytes(row['data']).hex()) for row in records],output_sha256=hashlib.sha256(output).hexdigest(),
        runtime_reference_file_required=False,full_AI_or_campaign_parity=False)
    args.report.parent.mkdir(parents=True,exist_ok=True);args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({key:report[key] for key in ('fixed_reads','literal_bytes','records','output_sha256')}))


if __name__=='__main__':main()
