#!/usr/bin/env python3
"""Validate/emit the single paired opaque illumination data profile."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def generate(raw):
    value = json.loads(raw)
    if value["schema"] != "H2_MCC_NATIVE_ILLUM_NO_SPECULAR_PROFILES_V1" or len(value["profiles"]) != 1:
        raise ValueError("Changed finite illumination profile census")
    profile = value["profiles"][0]
    name = "shaders\\shader_templates\\opaque\\tex_bump_illum_no_specular"
    if (profile["template"] != name or profile["native_source_map"] != "turf" or
            profile["native_record"]["group"] != "stem" or profile["native_record"]["name"] != name or
            profile["shader_type_flags"] != 1 or profile["runtime_diffuse_slot"] != 1):
        raise ValueError("Unreviewed illumination template/source")
    graph = profile["source_graph"]
    if hashlib.sha256(canonical(graph)).hexdigest() != profile["source_graph_sha256"]:
        raise ValueError("Changed literal full MCC template/remap identity")
    if len(bytes.fromhex(graph["root_hex"])) != 96 or len(graph["definitions"]) != 3:
        raise ValueError("Changed complete source template root")
    for definition in graph["definitions"]:
        if len(bytes.fromhex(definition["definition_hex"])) != 40 or len(definition["arrays"]) != 5:
            raise ValueError("Changed source platform definition")
        for array, (field, stride) in zip(definition["arrays"], ((0, 10), (8, 2), (16, 10), (24, 6), (32, 4))):
            if (array["field"] != field or len(bytes.fromhex(array["raw_hex"])) != array["count"] * stride or
                    len(array["typed_references"]) != (array["count"] if field == 16 else 0) or
                    any(len(reference) != 2 or reference[0] != "spas" for reference in array["typed_references"])):
                raise ValueError("Changed complete typed source remap bank")
    if (profile["source_counts"]["12"] != 3 or profile["source_counts"]["20"] != 10 or
            profile["source_counts"]["52"] != 35 or profile["source_counts"]["60"] != 1 or
            profile["native_shape"]["24"] != 34):
        raise ValueError("Changed source/native finite bank shape")
    source, native = profile["source_role_banks"], profile["native_role_banks"]
    for field in (28, 68, 76, 92):
        if source[str(field)] != native[str(field)]:
            raise ValueError("Unproved unchanged illumination role")
    if (len(bytes.fromhex(source["52"])) != 350 or len(bytes.fromhex(native["52"])) != 340 or
            source["84"] != "8100000081000000" or native["84"] != "0000040000000400" or
            source["68"] != "0000ffff" or source["76"] != "0002" or
            source["28"] != "800000000032800000001932"):
        raise ValueError("Changed complete paired illumination role mapping")
    overlays = profile["clock_overlays"]
    if (len(overlays) != 1 or overlays[0]["input"] != 0 or overlays[0]["range"] != 0 or
            overlays[0]["period_words"] != [1065353216] or len(bytes.fromhex(overlays[0]["curve_hex"])) != 52):
        raise ValueError("Unreviewed clock input/range/period/complete curve")
    proof = profile["paired_proof"]
    if not all(proof[key] for key in ("images_normalized_exact", "vectors_exact", "first_pixel_exact", "complete_required_curve_exact", "source_and_native_role_banks_literal")):
        raise ValueError("Missing original complete paired role/curve proof")
    owners = profile["needed_PC_owners"]
    if len(owners) != 2 or len({x["datum"] for x in owners}) != 2 or any(x["map"] != "street_sweeper" for x in owners):
        raise ValueError("Changed complete two-owner source proof")
    data = {key: profile[key] for key in ("template", "source_graph", "source_counts", "shader_type_flags", "runtime_diffuse_slot", "native_shape", "source_role_banks", "native_role_banks", "clock_overlays")}
    data["native_record"] = {key: profile["native_record"][key] for key in ("payload", "bytes", "fnv64")}
    return ('// Generated by tools/generate_mcc_native_illum_no_specular.py; do not edit.\n'
            '// Paired source data SHA256: ' + hashlib.sha256(raw).hexdigest() + '\n'
            'constexpr std::string_view native_illum_no_specular_profiles=R"H2ILLUM(' + canonical({"profiles": [data]}).decode() + ')H2ILLUM";\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate((ROOT / "tools/data/mcc-native-illum-no-specular-profiles.json").read_bytes())
    target = ROOT / "src/rendering/mcc_native_illum_no_specular_profiles.inc"
    if args.check:
        if not target.is_file() or target.read_text() != text:
            raise ValueError("Stale finite illumination source registry")
    else:
        target.write_text(text)


if __name__ == "__main__":
    main()
