#!/usr/bin/env python3
"""Generate the finite source-owned HUD closure bootstrap policy."""
import argparse
import hashlib
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]


def generate(raw):
    data = json.loads(raw)
    if (data.get('schema') != 'H2_MCC_NATIVE_HUD_BOOTSTRAP_V1' or
            data.get('source_map') != '01b_spacestation' or
            data.get('excluded') != dict(rasterizer=True, world_materials=True, existing_manifests=True)):
        raise ValueError('Changed finite HUD bootstrap domain')
    def sha(text):
        if not isinstance(text, str) or not re.fullmatch('[a-f0-9]{64}', text):
            raise ValueError('Invalid source digest')
    sha(data['source_canonical_sha256'])
    if [r['map'] for r in data['maps']] != ['needle', 'street_sweeper']:
        raise ValueError('Changed exact source map set')
    for r in data['maps']:
        sha(r['sha256'])
        if not 0 < r['bytes'] < 16 * 1024 * 1024:
            raise ValueError('Invalid source file extent')
    expected = [('vrtx', r'rasterizer\vertex_shaders_dx9\screen'),
                ('stem', r'shaders\shader_templates\hud\widget_simple_flash'),
                ('spas', r'shaders\shader_passes\hud\widget_simple_flash'),
                ('shad', r'ui\hud\shaders\widget_simple_flash_grey')]
    if [(r['group'], r['name']) for r in data['owners']] != expected:
        raise ValueError('Changed complete MCC owner set')
    handles = set()
    for r in data['owners']:
        sha(r['sha256'])
        if r['datum'] in handles or not 0 < r['size'] < 8192 or not 0 < r['address'] < 2**32-r['size']:
            raise ValueError('Invalid typed MCC owner')
        handles.add(r['datum'])
    if len(data['grey_borrowed_regions']) != 18 or data['grey_strings'] != {'150996442': 'hud_elite', '0': '', '167773659': 'hud_input1'}:
        raise ValueError('Changed complete grey metadata/namespace closure')
    for row in data['grey_borrowed_regions']:
        sha(row['sha256'])
        if not 0 < row['bytes'] < 8192 or not 0 < row['address'] < 2**32-row['bytes']:
            raise ValueError('Invalid borrowed grey metadata range')
    records = data['records']
    identities = {(r['group'], r['name']) for r in records}
    if identities != set(expected[1:3] + [('vrtx', r'rasterizer\vertex_shaders_xbox\screen')]) or len(records) != 3:
        raise ValueError('Changed three-record native closure')
    for r in records:
        sha(r['payload'][:-4])
        if not r['payload'].endswith('.bin') or not re.fullmatch('[a-f0-9]{16}', r['fnv64']) or r['strings']:
            raise ValueError('Invalid native payload identity')
        fields = set()
        for field, target in r['pointers']:
            if field in fields or not 0 <= field <= r['bytes']-4 or not 0 <= target < r['bytes']:
                raise ValueError('Invalid native pointer')
            fields.add(field)
        for field, identity in r['references']:
            if field in fields or not 0 <= field <= r['bytes']-4 or tuple(identity) not in identities:
                raise ValueError('Escaping native dependency')
            fields.add(field)
    value = json.dumps(data, sort_keys=True, separators=(',', ':'), ensure_ascii=False)
    return '// Generated by tools/generate_mcc_native_hud_bootstrap.py; do not edit.\n// Data SHA256: ' + hashlib.sha256(raw).hexdigest() + '\nconstexpr std::string_view native_hud_bootstrap_policy=R"H2HUD(' + value + ')H2HUD";\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=ROOT/'tools/data/mcc-native-hud-bootstrap.json')
    parser.add_argument('--output', type=Path, default=ROOT/'src/mcc_native_hud_bootstrap.inc')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate(args.data.read_bytes())
    if args.check:
        if not args.output.is_file() or args.output.read_text() != result:
            parser.error('Generated native HUD bootstrap policy is out of date')
    else:
        args.output.write_text(result)


if __name__ == '__main__':
    main()
