"""Emit the complete paired environment/three-channel metadata contract."""
import argparse
import hashlib
import json
from pathlib import Path

from mcc_env_illum_projection import TEMPLATE, PIXELS, canonical, conversion, need

ROOT = Path(__file__).resolve().parents[1]


def generate(raw):
    profile = json.loads(raw)
    need(profile["schema"] == "H2_MCC_NATIVE_ENV_ILLUM_THREE_CHANNEL_PROFILES_V1" and
         profile["template"] == TEMPLATE and profile["pixel_slots"] == list(PIXELS), "unreviewed profile")
    authority = profile["authority"]
    need(authority["sha256"] == "8360224f4a7f2948fb7ad2ec018a59415a72ffa30871102d4c800e227423e949" and
         authority["paired_controls"] == 114 and authority["materials"] == 164 and
         authority["complete_banks_per_control"] == 14, "complete original paired authority changed")
    graph = profile["source_graph"]
    need(hashlib.sha256(canonical(graph)).hexdigest() == "405dbcaee038aa122bbee29bba13265e49a7060c7ffee395980a234e898bfec5" and
         len(graph["definitions"]) == 3, "complete source compiler graph changed")
    native = profile["native_arrays"]
    need([a["count"] for a in native] == [3, 75, 18, 60, 267], "complete original template shape changed")
    need(profile["roles"] == conversion(graph["definitions"][0]["arrays"], native), "compiler-derived native roles changed")
    records = profile["native_records"]
    need(len(records) == len({x["payload"] for x in records}) == len({x["map"] for x in records}) == 39 and
         all(x["bytes"] in (1926, 1928) and len(x["payload"]) == 68 and x["payload"].endswith(".bin") and
             len(x["source_xbe_sha256"]) == 64 for x in records), "complete native template variants changed")
    data = {k: profile[k] for k in ("template", "source_graph", "native_arrays", "native_records", "roles", "pixel_slots")}
    return ("// Generated by tools/generate_mcc_native_env_illum_three_channel.py; do not edit.\n"
            "// Complete paired metadata SHA256: " + hashlib.sha256(raw).hexdigest() + "\n"
            "constexpr std::string_view native_env_illum_three_channel_profile=R\"H2ENVILLUM(" +
            canonical(data).decode() + ")H2ENVILLUM\";\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate((ROOT / "tools/data/mcc-native-env-illum-three-channel-profiles.json").read_bytes())
    target = ROOT / "src/rendering/mcc_native_env_illum_three_channel_profiles.inc"
    if args.check:
        need(target.is_file() and target.read_text() == text, "stale generated source")
    else:
        target.write_text(text)


if __name__ == "__main__":
    main()
