    g=element(d.root,'g',id='foreground',transform=f'scale({d.width/256} {d.height/256})',
              fill=ink,fill_rule='evenodd')
    if i in OUTLINES:
        element(g,'path',d=OUTLINES[i])
        if i==4:
            # Four fasteners and the chin opening are part of the design.
            holes=''
            for x,y in ((66,158),(66,172),(192,158),(192,172)):
                holes+=f'M{x-4} {y} A4 4 0 1 1 {x+4} {y} A4 4 0 1 1 {x-4} {y} Z '
            g[0].set('d',OUTLINES[i]+' '+holes)
        if i==27:
            for x,y,r in ((128,20,10),(73.5,45,7.5),(182,45,7.5),(40,73,6),(216,73,6)):
                element(g,'circle',cx=x,cy=y,r=r)
        if i==29:element(g,'circle',cx=129,cy=130,r=38)
    elif i==0:
        g.set('fill','#ffff00')
        element(g,'path',d='M107 11 H149 Q155 11 155 17 V148 Q155 154 149 154 H107 '
                'Q101 154 101 148 V17 Q101 11 107 11 Z')
