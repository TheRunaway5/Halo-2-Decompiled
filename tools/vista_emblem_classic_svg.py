def native_emblem(d):
    """Return None for families not admitted by this canvas-corrected recipe."""
    i=d.frame
    supported=set(OUTLINES)|{0,1,8,11,13,15,16,17,18,21,24,31,33,43}
    if i not in supported:return None
    d.family='emblem-foreground'
    blue=d.source[(d.source[:,:,3]>=128)&(d.source[:,:,2]>200)&(d.source[:,:,0]<50),:3]
