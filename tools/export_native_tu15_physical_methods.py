#!/usr/bin/env python3
"""Export five exact original TU1.5 eight-slot physical method prefixes.

Original constructors publish each vptr. Independently observed next records,
type-name bytes and scalar data bound the prefixes. No callback body, inferred
class layout or successful physics result is substituted.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools/reference/halo2-decompiled/tools'))
from xbe import Xbe
from functions import _Code
PIN='21b207e7efdacaf6124a0822837f8be570766a42505057f7fd2d2ba8f409c4fd'

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--fixture',type=Path,required=True)
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args();image=Xbe(args.reference)
    assert hashlib.sha256(image.data).hexdigest()==PIN
    code=_Code(image,'.text');readonly=image.section('.rdata');assert not readonly.flags&1
    roots=(0x41ce80,0x41d03c,0x41d070,0x41d090,0x41d638)
    for pc,opcode in ((0x2fbb92,'c70080ce4100'),(0x30411a,'c7063cd04100'),(0x30518a,'c70670d04100'),
            (0x305a0a,'c70690d04100'),(0x30bae9,'c70038d64100')):
        assert code.at(pc).bytes.hex()==opcode
    assert image.read(0x41d05c,len(b'TtConvexWelder\0'))==b'TtConvexWelder\0'
    assert image.read(0x41cea0,len(b'TtSphereBox\0'))==b'TtSphereBox\0'
    assert image.read(0x41d0b0,4)==struct.pack('<I',0x41d0d8)
    assert image.read(0x41d658,4)==struct.pack('<I',0x34000000)
    rows=[]
    for base in roots:
        raw=image.read(base,32);words=struct.unpack('<8I',raw)
        assert readonly.va<=base<base+len(raw)<=readonly.va+readonly.vsize
        assert all(value%16==0 and code.inside(value)and code.at(value)for value in words)
        rows.append(dict(base=base,words=words,bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest()))
    lines=['// Generated by tools/export_native_tu15_physical_methods.py.',
        '// English TU1.5 reference SHA256: '+PIN,
        '// Exact eight-method prefixes only; neighbouring strings/scalars stay outside.',
        'constexpr std::array physical_method_records{']
    for row in rows:
        lines.append(f'    std::pair{{0x{row["base"]:x}u,std::array<std::uint32_t,8>{{')
        for offset in range(0,8,8):
            lines.append('        '+','.join(f'0x{v:x}u'for v in row['words'][offset:offset+8])+(','if offset+8<8 else''))
        lines.append('    }}'+(','if row is not rows[-1] else''))
    lines+=['};','for(const auto &[base,methods]:physical_method_records)',
        '    for(unsigned slot=0;slot<methods.size();++slot)',
        '        share_immutable_word(memory,base+slot*4u,methods[slot],',
        '            "native TU1.5 authored physical shape method record");']
    args.output.write_text('\n'.join(lines)+'\n')
    fixture=['// Original bytes independently read from the authenticated TU1.5 image.',
        '// Reference SHA256: '+PIN,
        'struct OriginalPhysicalMethods {std::uint32_t base;std::array<std::byte,32> bytes;};',
        'constexpr std::array original_physical_methods{']
    for row in rows:
        raw=image.read(row['base'],32);fixture.append(f'    OriginalPhysicalMethods{{0x{row["base"]:x}u,{{')
        for offset in range(0,len(raw),16):
            fixture.append('        '+','.join(f'std::byte{{0x{v:02x}}}'for v in raw[offset:offset+16])+(','if offset+16<len(raw)else''))
        fixture.append('    }}'+(','if row is not rows[-1]else''))
    fixture.append('};');args.fixture.write_text('\n'.join(fixture)+'\n')
    report=dict(passed=True,reference_sha256=PIN,records=rows,total_bytes=sum(r['bytes']for r in rows),output_sha256=hashlib.sha256(args.output.read_bytes()).hexdigest(),fixture_sha256=hashlib.sha256(args.fixture.read_bytes()).hexdigest(),scope=__doc__)
    args.report.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items()if k not in('records','scope')}))

if __name__=='__main__':main()
