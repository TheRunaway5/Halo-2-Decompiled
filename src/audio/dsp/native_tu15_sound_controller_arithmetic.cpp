#include <limits>
#include <stdexcept>
namespace halo2::tu15_sound_controller_arithmetic {
namespace {
void valid(Word24 word) {if(word.bits>0xffffff)throw std::invalid_argument("Controller word exceeds 24 bits");}
std::int64_t signed24(Word24 word) {return word.bits&0x800000?std::int64_t(word.bits)-0x1000000:word.bits;}
Word24 word24(std::int64_t value) {return Word24(std::uint32_t(value)&0xffffff);}
Word24 transfer(std::int64_t accumulator) {
    // Normal transfer floors by 24 and then limits the full signed value.
    constexpr std::int64_t unit=std::int64_t(1)<<24;
    auto value=accumulator>=0?accumulator/unit:-((-accumulator+unit-1)/unit);
    if(value>0x7fffff)value=0x7fffff;
    if(value<-0x800000)value=-0x800000;
    return word24(value);
}
bool overlap(const void* a,std::size_t an,const void* b,std::size_t bn) {
    const auto x=reinterpret_cast<std::uintptr_t>(a),y=reinterpret_cast<std::uintptr_t>(b);
    if(x>std::numeric_limits<std::uintptr_t>::max()-an||y>std::numeric_limits<std::uintptr_t>::max()-bn)
        throw std::invalid_argument("Controller object range wraps native address space");
    return x<y+bn&&y<x+an;
}
}
Parameters authored_parameters(){return {Word24(6),Word24(4100000)};}
Result process(const Controls& controls,const Parameters& parameters,State& state,std::span<Word24,32> storage) {
    valid(controls.entry_status);valid(parameters.threshold);valid(parameters.gain);valid(state.flags);valid(state.counter);
    // Only the mode-clear observed entry domain is admitted. This rejects
    // incoming SC/LF/FV, scaling, SM/SA/DM and other unmodeled high controls;
    // counted loops generated by the original body are a different boundary.
    if(controls.entry_status.bits&~0x3ffu||controls.storage_read!=AddressingMode::linear||
       controls.storage_write!=AddressingMode::linear||controls.state_relative!=AddressingMode::linear)
        throw std::invalid_argument("Controller entry modes are unsupported");
    if(overlap(storage.data(),storage.size_bytes(),&state,sizeof(state))||
       overlap(storage.data(),storage.size_bytes(),&parameters,sizeof(parameters))||
       overlap(&state,sizeof(state),&parameters,sizeof(parameters)))
        throw std::invalid_argument("Controller state and parameters overlap native storage");
    for(auto word:storage)valid(word);
    Result result{};
    if(!(state.flags.bits&1)) {state.flags.bits|=1;state.counter=Word24(0x010000);}
    auto counter=signed24(state.counter);const auto threshold=signed24(parameters.threshold),gain=signed24(parameters.gain);
    for(std::uint32_t input_index=0;input_index<32;++input_index) {
        const auto input=signed24(storage[input_index]);
        if(counter>=threshold) {
            auto& emission=result.emissions[result.produced_count];emission.input_index=input_index;
            // Original MPY leaves the complete fractional product in A. Its
            // separate limited transfer supplies X0 for eight additions to A.
            // Every admitted product+sum fits signed 56 (in fact signed 52).
            auto accumulator=2*input*gain;emission.fractional_product=accumulator;
            emission.limited_product=transfer(accumulator);
            const auto addend=signed24(emission.limited_product)*(std::int64_t(1)<<24);
            for(unsigned n=0;n<8;++n){accumulator+=addend;emission.addition_results[n]=accumulator;}
            emission.output=transfer(accumulator);storage[result.produced_count++]=emission.output;counter=0;
        }
        // A skipped counter<threshold<=7FFFFF cannot overflow signed24 on
        // increment. A processed counter was just reset to zero.
        ++counter;
    }
    state.counter=word24(counter);
    return result;
}
} // namespace halo2::tu15_sound_controller_arithmetic
