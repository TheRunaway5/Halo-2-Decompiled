#[test]
fn actual_selected_profile_datum_is_required_before_profile_conversion() {
    for kind in 0..4 {
        let e = Env::new(false);
        let mut live = e.live.borrow_mut();
        match kind {
            0 => live[0].connected = false,
            1 => live[0].datum = u32::MAX,
            2 => live[0].datum = 0x12340001,
            _ => live[0].profile_present = false,
        }
        drop(live);
        assert_eq!(
            publish(&e).unwrap_err().to_string(),
            "ONLINE postgame participant lacks its actual selected profile"
        );
        assert!(!e.calls.borrow().iter().any(|s| s == "configuration:0"));
    }
}
#[test]
fn team_history_requires_exact_fixed_membership_and_retains_changing_teams() {
    let e = Env::new(true);
    e.state.borrow_mut().retained_teams = 7;
    assert_eq!(
        publish(&e).unwrap_err().to_string(),
        "ONLINE postgame team history differs from admission"
    );
    *e.changing.borrow_mut() = true;
    e.live.borrow_mut()[3].membership = 2;
    e.state.borrow_mut().players[3].membership = 2;
    publish(&e).unwrap();
    let output = e.output.borrow();
    assert_eq!(output.as_ref().unwrap().teams[2].occupied, 1);
    assert_eq!(output.as_ref().unwrap().players[3].configuration[0x7c], 2);
}
