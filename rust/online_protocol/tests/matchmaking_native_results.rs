//! Modern native admission adapter controls. Native gameplay/rank IO is declared.
use halo2_online_protocol::{matchmaking_native_results::*, security_policy::PCR_SIZE};
use std::cell::RefCell;

struct Env {
    state: RefCell<State>,
    roster: RefCell<Vec<Admission>>,
    live: RefCell<[LivePlayer; 16]>,
    variant: RefCell<[u8; 304]>,
    recording: RefCell<Recording>,
    round: RefCell<u32>,
    ranks: Ranks,
    changing: RefCell<bool>,
    calls: RefCell<Vec<String>>,
    fault: RefCell<Option<String>>,
    output: RefCell<Option<Publication>>,
}
impl Env {
    fn new(teams: bool) -> Self {
        let roster = vec![
            Admission {
                slot: 3,
                team: 0,
                identity: [3; 8],
            },
            Admission {
                slot: 0,
                team: 1,
                identity: [1; 8],
            },
            Admission {
                slot: 15,
                team: 0,
                identity: [15; 8],
            },
        ];
        let mut state = State {
            finished: true,
            results_finalized: true,
            team_mode: teams,
            retained_teams: if teams { 3 } else { 0 },
            accuracy: Some([[[0; 2]; 34]; 16]),
            ..Default::default()
        };
        let mut live = [LivePlayer::default(); 16];
        let mut ranks = Ranks {
            players: [255; 16],
            teams: [255; 8],
        };
        for (index, p) in roster.iter().enumerate() {
            let i = p.slot as usize;
            let membership = if teams { p.team } else { -1 };
            state.players[i] = Player {
                connected: true,
                membership,
                total_score: i as i32 - 7,
                kills: i as i32 + 1,
                deaths: i as i32 + 2,
                assists: i as i32,
                suicides: 0,
            };
            for w in 0..34 {
                state.accuracy.as_mut().unwrap()[i][w] = [(i + w) as u16, (w / 2) as u16];
            }
            live[i] = LivePlayer {
                connected: true,
                datum: 0x12340000 | p.slot,
                profile_present: true,
                membership,
            };
            ranks.players[i] = (index * 2) as u8;
        }
        ranks.teams[0] = 0;
        ranks.teams[1] = 2;
        state.team_scores[0] = 23;
        state.team_scores[1] = -4;
        let mut variant = [0; 304];
        variant[0x44] = 2;
        variant[0x48] = u8::from(teams);
        Self {
            state: RefCell::new(state),
            roster: RefCell::new(roster),
            live: RefCell::new(live),
            variant: RefCell::new(variant),
            recording: RefCell::new(Recording {
                statistics_present: true,
                enabled: 1,
                frozen: 1,
            }),
            round: RefCell::new(0x20),
            ranks,
            changing: RefCell::new(false),
            calls: RefCell::new(vec![]),
            fault: RefCell::new(None),
            output: RefCell::new(None),
        }
    }
    fn enter(&self, name: String) -> Result<()> {
        self.calls.borrow_mut().push(name.clone());
        if self.fault.borrow().as_ref() == Some(&name) {
            Err(Error::Io(format!("Native refusal: {name}")))
        } else {
            Ok(())
        }
    }
    fn encoded_name(&self, index: u32) -> [u8; 64] {
        let mut b = [0; 64];
        b[0] = b'P';
        b[2] = b'0' + self.roster.borrow()[index as usize].slot as u8;
        b
    }
    // Independent wire layout fixture. It is not generated by publish().
    fn raw(&self) -> Vec<u8> {
        let mut b = vec![0; PCR_SIZE];
        b[0] = 1;
        b[1] = 1;
        b[0x10] = 1;
        b[0x11] = 1;
        let state = self.state.borrow();
        b[0x13] = u8::from(state.team_mode);
        b[0x20..0x150].copy_from_slice(&*self.variant.borrow());
        let put = |b: &mut Vec<u8>, at: usize, value: u16| {
            b[at..at + 2].copy_from_slice(&value.to_le_bytes())
        };
        for (index, a) in self.roster.borrow().iter().enumerate() {
            let i = a.slot as usize;
            let p = state.players[i];
            let at = 0x370 + i * 0x94;
            b[at] = 1;
            b[at + 2..at + 10].copy_from_slice(&a.identity);
            let mut name = [0; 64];
            name[0] = b'P';
            name[2] = b'0' + a.slot as u8;
            b[at + 12..at + 76].copy_from_slice(&name);
            b[at + 0x88] = if state.team_mode {
                p.membership as u8
            } else {
                255
            };
            b[at + 0x90] = self.ranks.players[i] / 2;
            put(&mut b, at + 0x92, p.total_score as i16 as u16);
            for (stat, value) in [
                (7, p.kills),
                (9, p.deaths),
                (8, p.assists),
                (11, p.suicides),
            ] {
                put(&mut b, 0xe30 + 2 * (i * 437 + stat), value as u16);
            }
            for w in 0..34 {
                for k in 0..2 {
                    put(
                        &mut b,
                        0xecc + 2 * (i * 437 + (w + 5) * 8 + 4 + k),
                        state.accuracy.as_ref().unwrap()[i][w][k],
                    );
                }
            }
            let _ = index;
        }
        if state.team_mode {
            for team in 0..8 {
                if state.retained_teams & (1 << team) != 0 {
                    let at = 0xcb0 + team * 0x18;
                    b[at] = 1;
                    b[at + 1] = self.ranks.teams[team] / 2;
                    put(&mut b, at + 2, state.team_scores[team] as i16 as u16);
                }
            }
        }
        b
    }
}
impl Io for Env {
    fn state(&self) -> Result<State> {
        self.enter("state".into())?;
        Ok(self.state.borrow().clone())
    }
    fn roster(&self) -> Result<Vec<Admission>> {
        self.enter("roster".into())?;
        Ok(self.roster.borrow().clone())
    }
    fn round_flags(&self) -> Result<u32> {
        self.enter("round".into())?;
        Ok(*self.round.borrow())
    }
    fn variant(&self) -> Result<[u8; 304]> {
        self.enter("variant".into())?;
        Ok(*self.variant.borrow())
    }
    fn recording(&self) -> Result<Recording> {
        self.enter("recording".into())?;
        Ok(*self.recording.borrow())
    }
    fn ranks(&self, extended: bool, count: u32) -> Result<Ranks> {
        self.enter(format!("ranks:{extended}:{count}"))?;
        Ok(self.ranks)
    }
    fn changing_teams(&self) -> Result<bool> {
        self.enter("changing".into())?;
        Ok(*self.changing.borrow())
    }
    fn live_player(&self, slot: u32) -> Result<LivePlayer> {
        self.enter(format!("live:{slot}"))?;
        Ok(self.live.borrow()[slot as usize])
    }
    fn configuration(&self, slot: u32) -> Result<[u8; 132]> {
        self.enter(format!("configuration:{slot}"))?;
        Ok([0xa5; 132])
    }
    fn name(&self, index: u32) -> Result<[u8; 64]> {
        self.enter(format!("name:{index}"))?;
        Ok(self.encoded_name(index))
    }
    fn team_score(&self, team: u32) -> Result<i32> {
        self.enter(format!("team_score:{team}"))?;
        Ok(self.state.borrow().team_scores[team as usize])
    }
    fn accumulated_score(&self, datum: u32) -> Result<i16> {
        self.enter(format!("score:{datum}"))?;
        Ok(self.state.borrow().players[(datum & 0xffff) as usize].total_score as i16)
    }
    fn write(&self, input: Publication) -> Result<()> {
        self.enter("write".into())?;
        self.output.replace(Some(input));
        Ok(())
    }
}

#[test]
fn publish_preserves_sparse_slots_roster_index_names_profiles_and_exact_order() {
    for teams in [false, true] {
        let e = Env::new(teams);
        publish(&e).unwrap();
        let output = e.output.borrow();
        let output = output.as_ref().unwrap();
        assert_eq!(output.variant, *e.variant.borrow());
        assert_eq!(
            (output.current, output.finalized, output.engine_present),
            (1, 1, true)
        );
        for (index, a) in e.roster.borrow().iter().enumerate() {
            let p = &output.players[a.slot as usize];
            assert_eq!(p.occupied, 1);
            assert_eq!(p.identity, a.identity);
            assert_eq!(p.configuration[..64], e.encoded_name(index as u32));
            assert_eq!(p.configuration[64], 0xa5);
            assert_eq!(
                p.configuration[0x7c],
                if teams { a.team as u8 } else { 255 }
            );
            assert_eq!(p.score, a.slot as i32 - 7);
        }
        assert_eq!(output.players[1], PublicationPlayer::default());
        assert_eq!(output.teams[8], PublicationTeam::default());
        let calls = e.calls.borrow();
        assert_eq!(
            &calls[..7],
            [
                "state",
                "round",
                "roster",
                "variant",
                "recording",
                "ranks:false:3",
                "changing"
            ]
        );
        assert_eq!(calls.last().unwrap(), "write");
        assert!(
            calls.iter().position(|s| s == "configuration:0").unwrap()
                < calls.iter().position(|s| s == "name:1").unwrap()
        );
    }
}
#[test]
fn publication_completion_round_roster_and_recording_fail_before_later_io() {
    for stage in 0..6 {
        let e = Env::new(false);
        match stage {
            0 => e.state.borrow_mut().finished = false,
            1 => *e.round.borrow_mut() = 0,
            2 => e.roster.borrow_mut().clear(),
            3 => e.roster.borrow_mut()[0].slot = 16,
            4 => e.recording.borrow_mut().frozen = 0,
            _ => e.state.borrow_mut().accuracy = None,
        }
        assert!(publish(&e).is_err());
        assert!(e.output.borrow().is_none());
        let calls = e.calls.borrow();
        assert!(!calls.iter().any(|s| s.starts_with("live:") || s == "write"));
        if stage < 4 {
            assert!(!calls.iter().any(|s| s == "variant"));
        }
    }
}
