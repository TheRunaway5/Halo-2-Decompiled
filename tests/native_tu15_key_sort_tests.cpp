// Native TU1.5 2F33B0 key sort (hkAlgorithm::quickSortRecursive over unsigned
// 32-bit keys) against the unmodified translated canonical body run_2ef8f0,
// extracted by tools/validate_native_key_sort_tu15.py into sort_bodies.inc
// with the unit's selected() operand case (sort_selected.inc) and the
// binder's verification reference (sort_reference.inc). The native runs its
// recursion inline; the translated body recurses through itself.
//
// Seeded fixtures: 0-40 keys (random, sorted, reversed, few distinct values,
// all equal, keys with the top bit set), bounds inside the array, empty or
// inverted ranges, bounds past the fixture (faults), random comparator
// arguments, random register files, x87 depths, an active MMX state (the sort
// has no x87 instruction, so it still runs), every MXCSR mode, and one fixture
// page removed. Each case compares the ordered store events, the bank, the
// registers, flags, XMM, x87, MXCSR and the cursor; faults by exception,
// cursor and bank. Modes: <cases> [census|verify].
