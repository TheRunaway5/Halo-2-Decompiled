int main(int argc,char **argv)try {
    const unsigned cases=argc>1?unsigned(std::stoul(argv[1])):4000;
    const std::string mode=argc>2?argv[2]:"";
    const auto base=leaves_remap::parse(mode);census_mode=base=="census";verify=base=="verify";
    if(census_mode)setenv("HALO2_CENSUS_NATIVE_BRIDGES","1",1);
    if(verify)setenv("HALO2_VERIFY_PHYSICS_WORLD_LEAVES","1",1);
    const std::uint32_t variant=(census_mode?1u:0u)+(verify?2u:0u)+(leaves_remap::enabled?4u:0u);
    Totals sort;
    if(compare("2F33B0",cases,0x2f33b0u+variant,sort,author_sort,
        [](ObservedWorldState &s){return leaves::bridge_2f33b0(s,[](auto &v){t_sort::native_world_leaves_reference_2ef8f0(v);});},
        [](ObservedWorldState &s){t_sort::run_2ef8f0(s);}))return 1;
    std::printf("{\"cases\":%u,\"compared\":%llu,\"ordered_stores\":%llu,\"faults\":%llu,\"coverage\":%llu,\"mode\":\"%s\"}\n",
        cases,(unsigned long long)sort.compared,(unsigned long long)sort.stores,(unsigned long long)sort.faults,
        (unsigned long long)leaves::coverage().load(),mode.c_str());
    return 0;
}catch(const std::exception &e){std::fprintf(stderr,"%s\n",e.what());return 1;}
